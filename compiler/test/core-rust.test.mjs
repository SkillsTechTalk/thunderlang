// Thunder Core compiled to Rust (src/core/target-rust.mjs). The conformance (Python, the Thunder engine, compiled
// TypeScript, and compiled Rust give the same output for every Core test program) runs in core-engines.mjs, which
// core-run, core-stdlib, and core-engine use. This file checks the Rust itself: its shape, a runtime with no
// dependencies, Use refused, and the commands (cargo build / run / test).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, cpSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { compileCore } from '../src/core/index.mjs';
import { toRust, rs } from '../src/core/target-rust.mjs';
import { RUST_RUNTIME, CARGO_TOML, rustDiagnostics, rustToolchain } from '../src/core/rust-run.mjs';
import { RS } from './core-engines.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLI = join(HERE, '..', 'src', 'cli.mjs');
const EXAMPLES = join(HERE, '..', '..', 'examples', 'core');
const skipRun = RS.error ? `Rust cannot be built here: ${RS.error}` : (spawnSync('cargo', ['--version']).status !== 0 ? 'cargo is not installed' : false);
const tmp = () => mkdtempSync(join(tmpdir(), 'thunder-rs-'));
const thunder = (args, cwd, env = process.env) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8', env });

const JOURNAL = readFileSync(join(EXAMPLES, 'trading-journal.thunder'), 'utf8');

test('the Rust reads like the program: functions, records, line marks, and one runtime', () => {
  const r = compileCore(JOURNAL, { file: 'trading-journal.thunder' });
  const code = toRust(r.program, r.info, { source: 'trading-journal.thunder' });
  assert.match(code, /^\/\/ Generated by the Thunder compiler from trading-journal\.thunder\./);
  assert.match(code, /use thunder_runtime::\{self as T, Value\};/);
  assert.match(code, /pub fn kind_Trade\(\) -> std::rc::Rc<T::Kind>/);
  assert.match(code, /pub fn calculate_profit\(trade: Value\) -> Value \{ {2}\/\/ thunder:10/);
  assert.match(code, /T::set_line\(12\); return T::mul\(T::sub\(/);
  assert.match(code, /pub fn thunder_tests\(\) -> Vec<\(&'static str, fn\(\), i64\)>/);
  assert.equal(rs('a "b"\n\\'), '"a \\"b\\"\\n\\\\"');
});

test('the runtime needs nothing but the standard library, and builds offline', () => {
  assert.doesNotMatch(RUST_RUNTIME, /^\s*extern crate|^\s*use (?!std::)[a-z_]+::/m);
  assert.doesNotMatch(CARGO_TOML, /\[dependencies\][^[]*\S/);
  assert.match(RUST_RUNTIME, /pub fn run_tests\(/);
  assert.match(RUST_RUNTIME, /pub const MAX_FRAMES: usize = 997;/);
});

test('a Python module (Use) is refused for Rust before anything is written (TC405)', () => {
  const r = compileCore('Use csv as csv\nsay "hi"\n');
  const [d] = rustDiagnostics(r);
  assert.equal(d.code, 'TC405');
  assert.match(d.message, /"csv" is a Python module, and this program is compiled to Rust, which cannot use it\./);
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'prog.thunder'), 'Use csv as csv\nsay "hi"\n');
    const b = thunder(['build', 'prog.thunder', '--core', '--target', 'rust'], dir);
    assert.equal(b.status, 1);
    assert.match(b.stderr, /prog\.thunder, line 1: "csv" is a Python module[\s\S]*\[TC405\]\nthunder build: 1 problem; nothing was built\./);
    assert.equal(existsSync(join(dir, 'generated', 'rust')), false);
  } finally { rmSync(dir, { recursive: true }); }
});

test('thunder build / run / test --target rust (cargo), and target = "rust" in thunder.toml', { skip: skipRun }, () => {
  const dir = tmp();
  try {
    cpSync(EXAMPLES, dir, { recursive: true, filter: (p) => !p.includes('generated') && !p.endsWith('csv-summary.thunder') });
    const b = thunder(['build', '--target', 'rust'], dir);
    assert.equal(b.status, 0, b.stderr);
    assert.match(b.stdout, /^thunder build: 5 files -> generated\/rust\/ \(Rust\)\n/);
    for (const f of ['m_hello.rs', 'main.rs', 'thunder_runtime.rs', 'Cargo.toml']) assert.ok(existsSync(join(dir, 'generated', 'rust', f)), f);
    const run = thunder(['run', '--target', 'rust'], dir);
    assert.equal(run.status, 0, run.stderr);
    assert.equal(run.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    const t = thunder(['test', '--target', 'rust'], dir);
    assert.equal(t.status, 0, t.stderr);
    assert.match(t.stdout, /14 tests: 14 passed, 0 failed\n$/);
    writeFileSync(join(dir, 'thunder.toml'), readFileSync(join(dir, 'thunder.toml'), 'utf8').replace('target = "python"', 'target = "rust"').replace('output = "generated/python"', 'output = "out/rs"'));
    const viaToml = thunder(['run'], dir);
    assert.equal(viaToml.status, 0, viaToml.stderr);
    assert.equal(viaToml.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    assert.ok(existsSync(join(dir, 'out', 'rs', 'Cargo.toml')));
  } finally { rmSync(dir, { recursive: true }); }
});

test('an error names the Thunder line, the same as every other target', { skip: skipRun }, () => {
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'p.thunder'), 'To half:\n  Receive n\n  Give n / 0\n\nsay half with 4\n');
    const r = thunder(['run', 'p.thunder', '--core', '--target', 'rust'], dir);
    assert.equal(r.status, 1);
    assert.equal(r.stderr, 'p.thunder, line 3 (reached from line 5): You divided by zero.  [TC501]\n');
  } finally { rmSync(dir, { recursive: true }); }
});

test('without the Rust toolchain: building works, running says what to install', () => {
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'p.thunder'), 'say "hi"\n');
    const env = { ...process.env, PATH: dirname(process.execPath) };
    const b = thunder(['build', 'p.thunder', '--core', '--target', 'rust'], dir, env);
    assert.equal(b.status, 0, b.stderr);
    const r = thunder(['run', 'p.thunder', '--core', '--target', 'rust'], dir, env);
    assert.equal(r.status, 2);
    assert.match(r.stderr, /Running Rust needs the Rust toolchain \(rustc and cargo\): install it from https:\/\/rustup\.rs\. "thunder build --target rust" works without it\./);
    assert.match(thunder(['run', 'p.thunder', '--core', '--target', 'rust', '--engine', 'thunder'], dir).stderr, /choose one: --target rust runs compiled Rust, --engine thunder runs Thunder directly\./);
  } finally { rmSync(dir, { recursive: true }); }
  assert.ok(rustToolchain().error || rustToolchain().version);
});
