// Thunder Core compiled to Java (src/core/target-java.mjs). The four-way conformance (Python, the Thunder engine,
// compiled TypeScript, and compiled Java give the same output for every Core test program) runs in core-engines.mjs,
// which core-run, core-stdlib, and core-engine use. This file checks the Java itself: its shape, the runtime, the parts
// Java asks for that the other targets don't (lambdas, unreachable steps, defaults), Use refused, and the commands.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { compileCore } from '../src/core/index.mjs';
import { toJava, javaString, javaClassName } from '../src/core/target-java.mjs';
import { JAVA_RUNTIME, javaDiagnostics, findJava } from '../src/core/java-run.mjs';
import { runBoth, JDK } from './core-engines.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLI = join(HERE, '..', 'src', 'cli.mjs');
const EXAMPLES = join(HERE, '..', '..', 'examples', 'core');
const skipRun = JDK.error ? `no JDK here: ${JDK.error}` : false;
const thunder = (args, cwd, env = process.env) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8', env });
const java = (src) => { const r = compileCore(src); assert.deepEqual(r.diagnostics, []); return toJava(r.program, r.info, { source: 'main.thunder', module: 'main' }); };

test('the Java reads like the program: one class, static methods, records, and line marks', () => {
  const src = readFileSync(join(EXAMPLES, 'trading-journal.thunder'), 'utf8');
  const r = compileCore(src, { file: 'trading-journal.thunder' });
  const j = toJava(r.program, r.info, { source: 'trading-journal.thunder', module: 'trading_journal' });
  assert.match(j, /^\/\/ Generated by the Thunder compiler from trading-journal\.thunder\./);
  assert.match(j, /\npackage app;\n\nimport java\.math\.BigInteger;\nimport thunder\.T;\n\npublic final class TradingJournal \{/);
  assert.match(j, /public static final T\.RecordKind Trade = T\.recordKind\("Trade", new T\.Field\[\] \{/);
  assert.match(j, /public static Object calculate_profit\(Object trade\) \{ {2}\/\/ thunder:10/);
  assert.match(j, /F\.line = 12; return T\.mul\(T\.sub\(/);
  assert.match(j, /public static void main\(String\[\] args\) \{\n {8}T\.run\(TradingJournal::thunderMain\);/);
  assert.equal(javaClassName('tests_greet'), 'TestsGreet');
  assert.equal(javaClassName('T'), 'TModule');
});

test('the runtime is written next to the Java: the JDK only, the engine\'s rules and messages', () => {
  const rt = JAVA_RUNTIME['thunder/ThunderRuntime.java'];
  assert.match(rt, /^\/\/ ThunderRuntime\.java: written by the Thunder compiler next to compiled Java\. Standard library only/);
  assert.doesNotMatch(rt, /^import (?!java\.)/m, 'only java.* imports');
  for (const words of ['A function called itself too many times.', 'You divided by zero.', 'This needs a yes/no value, but it is ', "I can't take the average of an empty list.", 'MAX_FRAMES = 997']) assert.ok(rt.includes(words), words);
  assert.match(JAVA_RUNTIME['thunder/T.java'], /public final class T extends ThunderRuntime/);
});

test('Java needs: a name a lambda uses is boxed, a step after Give is still compiled, defaults become overloads', () => {
  const j = java(`To pick:\n  Receive limit and rate (7% if not given)\n  Set limit to limit + 1\n  Give [1, 5, 9] where it is at least limit\n  say "never"\n\nsay pick with 4\n`);
  assert.match(j, /public static Object pick\(Object limit\) \{ {2}\/\/ thunder:1\n {8}return pick\(limit, T\.dec\("0\.07"\)\);/);
  assert.match(j, /public static Object pick\(Object \$in_limit, Object rate\) \{/);
  assert.match(j, /final T\.Box limit = new T\.Box\(\$in_limit\);/);
  assert.match(j, /limit\.v = T\.add\(limit\.v, T\.i\("1"\)\);/);
  assert.match(j, /if \(true\) \{\n\s+F\.line = 4; return T\.filter\(/);
  assert.match(j, /T\.compare\(">=", \$item\d+, limit\.v\)/);
});

test('a Java string literal for any text', () => {
  assert.equal(javaString('a "b" \\ c\nd\te'), '"a \\"b\\" \\\\ c\\nd\\te"');
  assert.equal(javaString('café 😀'), '"café 😀"');
  assert.equal(javaString('\u0001\ud800x'), '"\\u0001\\ud800x"');
});

test('a Python module (Use) is refused for Java before anything is written (TC405)', () => {
  const r = compileCore('Use csv as csv\nsay "hi"\n');
  const [d] = javaDiagnostics(r);
  assert.equal(d.code, 'TC405');
  assert.match(d.message, /"csv" is a Python module, and this program is compiled to Java, which cannot use it\./);
  const dir = mkdtempSync(join(tmpdir(), 'thunder-java-'));
  try {
    writeFileSync(join(dir, 'prog.thunder'), 'Use csv as csv\nsay "hi"\n');
    const b = thunder(['build', 'prog.thunder', '--core', '--target', 'java'], dir);
    assert.equal(b.status, 1);
    assert.match(b.stderr, /\[TC405\]/);
    assert.ok(!existsSync(join(dir, 'generated', 'java')), 'nothing is written');
  } finally { rmSync(dir, { recursive: true }); }
});

test('without a JDK, running says what to install (building still works)', () => {
  assert.match(findJava({ env: { PATH: '' } }).error, /^Running Java needs a JDK 17 or newer \(javac and java\), and none was found\. Install one/);
  const dir = mkdtempSync(join(tmpdir(), 'thunder-java-'));
  try {
    writeFileSync(join(dir, 'hi.thunder'), 'say "hi"\n');
    const env = { PATH: dirname(process.execPath) };
    const r = thunder(['run', 'hi.thunder', '--core', '--target', 'java'], dir, env);
    assert.equal(r.status, 2);
    assert.match(r.stderr, /needs a JDK 17 or newer/);
    assert.equal(thunder(['build', 'hi.thunder', '--core', '--target', 'java'], dir, env).status, 0);
    assert.ok(existsSync(join(dir, 'generated', 'java', 'app', 'Hi.java')));
    assert.ok(existsSync(join(dir, 'generated', 'java', 'thunder', 'ThunderRuntime.java')));
  } finally { rmSync(dir, { recursive: true }); }
});

test('the parts Java asks for give the same results on every target', { skip: skipRun }, () => {
  // A Give with steps after it; both sides of a choice give; a loop name a "where" uses; an Expect that must fail
  // using a local; the high end of "between" from a local; a default that is a kept value.
  assert.equal(runBoth(`To sign:\n  Receive n\n  When n is less than 0:\n    Give "minus"\n  Otherwise:\n    Give "plus"\n\nTo first:\n  Receive xs\n  Give xs at 1\n  say "unreachable"\n\nsay sign with -3\nsay first with [7, 8]\n`).out, 'minus\n7');
  assert.equal(runBoth(`Set total to 0\nFor each limit in [1, 2, 3]:\n  Set picked to [1, 2, 3, 4] where it is more than limit\n  Increase total by the count of picked\nsay total\n`).out, '6');
  assert.equal(runBoth(`Keep base rate at 5%\nTo price:\n  Receive amount and rate (base rate if not given)\n  Give amount + amount * rate\n\nSet top to 10\nsay price with $100\nsay 5 is between 1 and top\n`).out, '$105.00\nyes');
  assert.match(runBoth(`To half:\n  Receive n\n  Give n / 2\n\nTest "dividing works":\n  Set zero to 0\n  Expect half with 4 to be 2\n  Expect 1 / zero to fail\n`, { tests: true }).out, /PASS {2}dividing works/);
});

test('thunder build, run, and test --target java', { skip: skipRun }, () => {
  const dir = mkdtempSync(join(tmpdir(), 'thunder-java-'));
  try {
    assert.equal(thunder(['new', 'hello'], dir).status, 0);
    const run = thunder(['run', 'hello', '--target', 'java'], dir);
    assert.equal(run.status, 0, run.stderr);
    assert.equal(run.stdout, 'Hello, world!\n');
    const t = thunder(['test', 'hello', '--target', 'java'], dir);
    assert.equal(t.status, 0, t.stderr);
    assert.match(t.stdout, /PASS {2}greet says hello \(tests\/greet\.thunder, line 3\)\n1 test: 1 passed, 0 failed/);
    const b = thunder(['build', 'hello', '--target', 'java'], dir);
    assert.match(b.stdout, /^thunder build: 1 file -> hello\/generated\/java\/ \(Java 17\+\)/);
    // Set it for the project in thunder.toml instead.
    const toml = join(dir, 'hello', 'thunder.toml');
    writeFileSync(toml, readFileSync(toml, 'utf8').replace('target = "python"', 'target = "java"').replace('output = "generated/python"', 'output = "generated/java"'));
    assert.equal(thunder(['run'], join(dir, 'hello')).stdout, 'Hello, world!\n');
    const bad = thunder(['run', 'hello', '--target', 'java', '--engine', 'thunder'], dir);
    assert.equal(bad.status, 2);
    assert.match(bad.stderr, /choose one: --target java runs compiled Java, --engine thunder runs Thunder directly\./);
  } finally { rmSync(dir, { recursive: true }); }
});
