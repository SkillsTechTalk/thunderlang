import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { readRepo, searchRepo, groupByFile, readableLanguage } from '../src/read-repo.mjs';
import { collectReadableFiles } from '../src/read-repo-fs.mjs';
import { READ_SAMPLES } from '../../src/app/read/samples.mjs';

const SHOP = {
  'shipping/shipping.go': READ_SAMPLES[0].source,
  'payments/fraud.rs': READ_SAMPLES[1].source,
  'loans/LoanPolicy.java': READ_SAMPLES[2].source,
  'school/grading.py': READ_SAMPLES[3].source,
  'docs/AccessPolicy.cs': READ_SAMPLES[4].source,
};
const files = Object.entries(SHOP).map(([path, source]) => ({ path, source }));

test('one index across five languages, with answer and input facets', () => {
  const idx = readRepo(files);
  assert.equal(idx.files.length, 5);
  assert.deepEqual(Object.keys(idx.languages).sort(), ['csharp', 'go', 'java', 'python', 'rust']);
  assert.equal(idx.counts.decision, 8);
  // "Where does the code decide Review?" spans Rust and Java.
  const review = idx.answers.find((a) => a.name === 'Review');
  assert.deepEqual(review.decisions.map((id) => id.split('#')[0]).sort(), ['loans/LoanPolicy.java', 'payments/fraud.rs']);
  assert.ok(idx.inputs.some((i) => i.name === 'creditScore' && i.decisions.length === 2));
});

test('searchRepo narrows by text, answer, input, language, and folder', () => {
  const idx = readRepo(files);
  assert.deepEqual(searchRepo(idx, { answer: 'Deny' }).map((i) => i.name), ['CanOpen']);
  assert.deepEqual(searchRepo(idx, { input: 'creditScore' }).map((i) => i.name).sort(), ['decide', 'rateBand']);
  assert.deepEqual(searchRepo(idx, { query: 'domestic' }).map((i) => i.name), ['DeliveryWindow']);
  assert.ok(searchRepo(idx, { languages: ['python'] }).every((i) => i.file === 'school/grading.py'));
  assert.ok(searchRepo(idx, { path: 'payments/' }).every((i) => i.file.startsWith('payments/')));
  assert.deepEqual(searchRepo(idx, { query: 'loans', kinds: ['decision'] }).map((i) => i.name), ['decide', 'rateBand']);
  assert.deepEqual(groupByFile(searchRepo(idx, { kinds: ['decision'] })).map((g) => g.file), ['docs/AccessPolicy.cs', 'loans/LoanPolicy.java', 'payments/fraud.rs', 'school/grading.py', 'shipping/shipping.go']);
});

test('dependency folders, declarations, and minified files are never read; too-large and generated files are listed', () => {
  assert.equal(readableLanguage('node_modules/x/index.js'), null);
  assert.equal(readableLanguage('src/types.d.ts'), null);
  assert.equal(readableLanguage('vendor/github.com/a/b.go'), null);
  assert.equal(readableLanguage('app/main.py'), 'python');
  const idx = readRepo([
    ...files,
    { path: 'gen/api.ts', source: '// Code generated by protoc. DO NOT EDIT.\nexport function a(x: number) { return x > 1 ? "A" : "B"; }' },
    { path: 'big/huge.go', source: '', size: 10_000_000 },
  ]);
  assert.deepEqual(idx.skipped.map((s) => s.path).sort(), ['big/huge.go', 'gen/api.ts']);
  assert.match(idx.skipped.find((s) => s.path === 'gen/api.ts').reason, /generated/);
});

test('thunder read <folder> reads a repository from disk', () => {
  const root = mkdtempSync(join(tmpdir(), 'thunder-read-'));
  for (const [path, source] of Object.entries(SHOP)) {
    mkdirSync(join(root, path, '..'), { recursive: true });
    writeFileSync(join(root, path), source);
  }
  mkdirSync(join(root, 'node_modules/dep'), { recursive: true });
  writeFileSync(join(root, 'node_modules/dep/index.js'), 'function x(a){ return a ? "Yes" : "No"; }');
  assert.equal(collectReadableFiles(root).length, 5);
  const cli = new URL('../src/cli.mjs', import.meta.url).pathname;
  const out = spawnSync(process.execPath, [cli, 'read', root, '--answer', 'Review'], { encoding: 'utf8' });
  assert.equal(out.status, 0, out.stderr);
  assert.match(out.stdout, /5 files/);
  assert.match(out.stdout, /payments\/fraud\.rs/);
  assert.match(out.stdout, /loans\/LoanPolicy\.java/);
  assert.doesNotMatch(out.stdout, /shipping\.go/);
  const json = JSON.parse(spawnSync(process.execPath, [cli, 'read', root, '--input', 'creditScore', '--json'], { encoding: 'utf8' }).stdout);
  assert.equal(json.schema, 'thunder-repo-reading-v1');
  assert.deepEqual(json.items.map((i) => i.name).sort(), ['decide', 'rateBand']);
});
