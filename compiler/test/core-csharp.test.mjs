// Thunder Core compiled to C# (src/core/target-csharp.mjs). The four-way conformance (Python, the Thunder engine,
// compiled TypeScript, and compiled C# give the same output for every Core test program) runs in core-engines.mjs,
// which core-run, core-stdlib, and core-engine use (their last test builds every program as C#). This file checks the
// C# itself: its shape, Use refused, errors, the commands, and a missing .NET SDK.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, cpSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { compileCore } from '../src/core/index.mjs';
import { toCSharp, cs } from '../src/core/target-csharp.mjs';
import { csharpDiagnostics, writeCSharp, runCSharp, CS_RUNTIME } from '../src/core/csharp-run.mjs';
import { CS } from './core-engines.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLI = join(HERE, '..', 'src', 'cli.mjs');
const EXAMPLES = join(HERE, '..', '..', 'examples', 'core');
const skipRun = CS.error ? `C# cannot be built here: ${CS.error}` : false;
const tmp = () => mkdtempSync(join(tmpdir(), 'thunder-cs-'));
const thunder = (args, cwd, env = {}) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8', env: { ...process.env, ...env } });

const JOURNAL = readFileSync(join(EXAMPLES, 'trading-journal.thunder'), 'utf8');

test('the C# reads like the program: a static class, functions, records, and line marks', () => {
  const r = compileCore(JOURNAL, { file: 'trading-journal.thunder' });
  const code = toCSharp(r.program, r.info, { source: 'trading-journal.thunder', module: 'trading_journal' });
  assert.match(code, /^\/\/ Generated by the Thunder compiler from trading-journal\.thunder\./);
  assert.match(code, /namespace ThunderProgram\n\{\n {4}using Thunder;\n\n {4}public static class M_trading_journal\n/);
  assert.match(code, /public static readonly RecordKind Trade = T\.recordKind\("Trade", new FieldDef\[\] \{ T\.field\(/);
  assert.match(code, /public static object calculate_profit\(object trade\) {2}\/\/ thunder:10/);
  assert.match(code, /F\.line = 12; return T\.mul\(T\.sub\(/);
  assert.match(code, /public static readonly \(string, System\.Action, int\)\[\] THUNDER_TESTS/);
  assert.match(code, /public static void main\(\)/);
});

test('one meaning: the C# runtime is a port of the engine\'s value code, with its rules and messages', () => {
  for (const [what, re] of [
    ['exact decimals with 28 digits', /const int PREC = 28;/],
    ['money rounds half away from zero', /public Dec QuantizeHalfUp\(int ee\)/],
    ['positions start at 1', /if \(pos >= 1 && pos <= list_\.Count\) return list_\[\(int\)pos - 1\];/],
    ['the same error words', /"This needs a yes\/no value, but it is " \+ describe\(v\)/],
    ['sorting compares the same pairs as V8', /static class V8Sort/],
  ]) assert.match(CS_RUNTIME, re, what);
  assert.equal(cs('a b"c\n'), '"a\\u2028b\\"c\\n"');
});

test('a Python module (Use) is refused for C# before anything is written (TC405)', () => {
  const r = compileCore('Use csv as csv\nsay "hi"\n');
  const [d] = csharpDiagnostics(r);
  assert.equal(d.code, 'TC405');
  assert.match(d.message, /"csv" is a Python module, and this program is compiled to C#, which cannot use it\./);
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'prog.thunder'), 'Use csv as csv\nsay "hi"\n');
    const b = thunder(['build', 'prog.thunder', '--core', '--target', 'csharp'], dir);
    assert.equal(b.status, 1);
    assert.match(b.stderr, /prog\.thunder, line 1: "csv" is a Python module[\s\S]*\[TC405\]\nthunder build: 1 problem; nothing was built\./);
    assert.equal(existsSync(join(dir, 'generated', 'csharp')), false);
  } finally { rmSync(dir, { recursive: true }); }
});

test('thunder build / run / test --target csharp, and target = "csharp" in thunder.toml', { skip: skipRun }, () => {
  const dir = tmp();
  try {
    cpSync(EXAMPLES, dir, { recursive: true, filter: (p) => !p.includes('generated') && !p.endsWith('csv-summary.thunder') });
    const b = thunder(['build', '--target', 'csharp'], dir);
    assert.equal(b.status, 0, b.stderr);
    assert.match(b.stdout, /^thunder build: 5 files -> generated\/csharp\/ \(C#\)\n/);
    for (const f of ['hello.cs', 'ThunderRuntime.cs', 'Program.cs', 'ThunderProgram.csproj']) assert.ok(existsSync(join(dir, 'generated', 'csharp', f)), f);
    const run = thunder(['run', '--target', 'csharp'], dir);
    assert.equal(run.status, 0, run.stderr);
    assert.equal(run.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    const t = thunder(['test', '--target', 'csharp'], dir);
    assert.equal(t.status, 0, t.stderr);
    assert.match(t.stdout, /14 tests: 14 passed, 0 failed\n$/);
    writeFileSync(join(dir, 'thunder.toml'), readFileSync(join(dir, 'thunder.toml'), 'utf8').replace('target = "python"', 'target = "csharp"').replace('output = "generated/python"', 'output = "out/cs"'));
    const viaToml = thunder(['run'], dir);
    assert.equal(viaToml.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    assert.ok(existsSync(join(dir, 'out', 'cs', 'hello.cs')));
  } finally { rmSync(dir, { recursive: true }); }
});

test('an error names the Thunder line, and the lines it was reached from, as the other targets do', { skip: skipRun }, () => {
  const dir = tmp();
  try {
    const r = compileCore('To share:\n  Receive total and people\n  Give total / people\n\nsay share with 10 and 2\nsay share with 10 and 0\n');
    writeCSharp([{ ...r, module: 'main', kind: 'src' }], dir);
    const out = runCSharp(dir);
    assert.equal(out.status, 1);
    assert.equal(out.stdout, '5\n');
    assert.equal(out.stderr, 'main.thunder, line 3 (reached from line 6): You divided by zero.  [TC501]\n');
  } finally { rmSync(dir, { recursive: true }); }
});

test('no .NET SDK: a plain message saying what to install, and exit 2', () => {
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'p.thunder'), 'say 1\n');
    const r = thunder(['run', 'p.thunder', '--core', '--target', 'csharp'], dir, { THUNDER_DOTNET: join(dir, 'no-dotnet-here') });
    assert.equal(r.status, 2);
    assert.match(r.stderr, /^thunder run: Building C# needs the \.NET SDK \(dotnet\), version 8 or newer, and I could not find it\. Install it from https:\/\/dotnet\.microsoft\.com\/download/);
    const both = thunder(['run', 'p.thunder', '--core', '--target', 'csharp', '--engine', 'thunder'], dir);
    assert.equal(both.status, 2);
    assert.match(both.stderr, /choose one: --target csharp runs compiled C#, --engine thunder runs Thunder directly\./);
  } finally { rmSync(dir, { recursive: true }); }
});
