// Thunder Core compiled to TypeScript (src/core/target-typescript.mjs). The three-way conformance (Python, the
// Thunder engine, and compiled TypeScript give the same output for every Core test program) runs in
// core-engines.mjs, which core-run, core-stdlib, and core-engine use. This file checks the TypeScript itself: its
// shape, its types (tsc --strict), the shared runtime, Use refused, and the commands.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, mkdirSync, cpSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { compileCore, toTypeScript } from '../src/core/index.mjs';
import { TS_RUNTIME, TS_RUNTIME_DTS } from '../src/core/runtime-typescript.mjs';
import { buildProject } from '../src/core/project.mjs';
import { typescriptRunner, typecheckTypeScript, typescriptDiagnostics } from '../src/core/typescript-run.mjs';
import { runCompiledTypeScript, TS, tally } from './core-engines.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLI = join(HERE, '..', 'src', 'cli.mjs');
const EXAMPLES = join(HERE, '..', '..', 'examples', 'core');
const skipRun = TS.error ? `TypeScript cannot run here: ${TS.error}` : false;
const tmp = () => mkdtempSync(join(tmpdir(), 'thunder-ts-'));
const thunder = (args, cwd) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8' });

const JOURNAL = readFileSync(join(EXAMPLES, 'trading-journal.thunder'), 'utf8');

test('the TypeScript reads like the program: functions, records, line marks, and only types Node can strip', () => {
  const r = compileCore(JOURNAL, { file: 'trading-journal.thunder' });
  const ts = toTypeScript(r.program, r.info, { source: 'trading-journal.thunder' });
  assert.match(ts, /^\/\/ Generated by the Thunder compiler from trading-journal\.thunder\./);
  assert.match(ts, /import \* as T from '\.\/thunder_runtime\.mjs';/);
  assert.match(ts, /export const Trade = T\.recordKind\("Trade", \[/);
  assert.match(ts, /export function calculate_profit\(trade: any\): any \{ {2}\/\/ thunder:10/);
  assert.match(ts, /F\.line = 12; return T\.mul\(T\.sub\(/);
  assert.match(ts, /export const THUNDER_TESTS: \[string, \(\) => void, number\]\[\] = \[/);
  assert.match(ts, /if \(T\.isEntry\(import\.meta\.url\)\) T\.run\(main\);/);
  // Erasable syntax only: Node strips these types without transforming the code.
  for (const bad of [/\benum\s+\w+/, /\bnamespace\s+\w+/, /\bconstructor\s*\(\s*(public|private|protected|readonly)\b/, /<\w+>\s*\w/, /\bdeclare\b/]) assert.doesNotMatch(ts, bad);
});

test('one meaning: the runtime is the Thunder engine\'s own value code, byte for byte, plus how to run', () => {
  const values = readFileSync(join(HERE, '..', 'src', 'core', 'engine-values.mjs'), 'utf8').trimEnd();
  assert.ok(TS_RUNTIME.includes(values), 'thunder_runtime.mjs must contain engine-values.mjs unchanged');
  assert.match(TS_RUNTIME, /export function runTests\(modules\)/);
  assert.match(TS_RUNTIME_DTS, /export declare class Dec \{/);
  assert.match(TS_RUNTIME_DTS, /export declare function add\(\.\.\.args: any\[\]\): any;/);
});

test('a Python module (Use) is refused for TypeScript before anything is written (TC405)', () => {
  const r = compileCore('Use csv as csv\nsay "hi"\n');
  assert.deepEqual(r.diagnostics, []);
  const [d] = typescriptDiagnostics(r);
  assert.equal(d.code, 'TC405');
  assert.equal(d.line, 1);
  assert.match(d.message, /"csv" is a Python module, and this program is compiled to TypeScript, which cannot use it\./);
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'prog.thunder'), 'Use csv as csv\nsay "hi"\n');
    const b = thunder(['build', 'prog.thunder', '--core', '--target', 'typescript'], dir);
    assert.equal(b.status, 1);
    assert.match(b.stderr, /prog\.thunder, line 1: "csv" is a Python module[\s\S]*\[TC405\]\nthunder build: 1 problem; nothing was built\./);
    assert.equal(existsSync(join(dir, 'generated', 'typescript')), false);
  } finally { rmSync(dir, { recursive: true }); }
});

test('thunder build / run / test --target typescript, and target = "typescript" in thunder.toml', { skip: skipRun }, () => {
  const dir = tmp();
  try {
    cpSync(EXAMPLES, dir, { recursive: true, filter: (p) => !p.includes('generated') && !p.endsWith('csv-summary.thunder') });
    const b = thunder(['build', '--target', 'typescript'], dir);
    assert.equal(b.status, 0, b.stderr);
    assert.match(b.stdout, /^thunder build: 5 files -> generated\/typescript\/ \(TypeScript\)\n/);
    for (const f of ['hello.ts', 'run_tests.ts', 'thunder_runtime.mjs', 'thunder_runtime.d.mts', 'tsconfig.json', 'package.json']) assert.ok(existsSync(join(dir, 'generated', 'typescript', f)), f);
    const run = thunder(['run', '--target', 'typescript'], dir);
    assert.equal(run.status, 0, run.stderr);
    assert.equal(run.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    const t = thunder(['test', '--target', 'typescript'], dir);
    assert.equal(t.status, 0, t.stderr);
    assert.match(t.stdout, /14 tests: 14 passed, 0 failed\n$/);
    writeFileSync(join(dir, 'thunder.toml'), readFileSync(join(dir, 'thunder.toml'), 'utf8').replace('target = "python"', 'target = "typescript"').replace('output = "generated/python"', 'output = "out/ts"'));
    const viaToml = thunder(['run'], dir);
    assert.equal(viaToml.stdout, 'Hello, world!\nNice to meet you, Ada.\n');
    assert.ok(existsSync(join(dir, 'out', 'ts', 'hello.ts')));
  } finally { rmSync(dir, { recursive: true }); }
});

test('tsc --strict accepts the generated TypeScript (examples and a project with tests)', { skip: skipRun }, (t) => {
  const dir = tmp();
  try {
    cpSync(EXAMPLES, dir, { recursive: true, filter: (p) => !p.includes('generated') && !p.endsWith('csv-summary.thunder') });
    const b = buildProject({ root: dir, includeTests: true, target: 'typescript' });
    assert.ok(b.ok);
    const tc = typecheckTypeScript(b.outDir, { searchFrom: [HERE] });
    if (tc.skipped) { t.skip(tc.skipped); return; }
    assert.ok(tc.ok, tc.output);
  } finally { rmSync(dir, { recursive: true }); }
});

test('an error names the Thunder line, and the lines it was reached from, as Python and the engine do', { skip: skipRun }, () => {
  const r = compileCore('To share:\n  Receive total and people\n  Give total / people\n\nsay share with 10 and 2\nsay share with 10 and 0\n');
  const out = runCompiledTypeScript([{ ...r, module: 'main' }]);
  assert.deepEqual(out, { out: '5', err: 'main.thunder, line 3 (reached from line 6): You divided by zero.  [TC501]', status: 1 });
});

test('mistakes in the command say what to do', () => {
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'p.thunder'), 'say 1\n');
    const bad = thunder(['build', 'p.thunder', '--core', '--target', 'java'], dir);
    assert.equal(bad.status, 2);
    assert.match(bad.stderr, /there is no target "java"\. Use --target python \(the default\) or --target typescript\./);
    const both = thunder(['run', 'p.thunder', '--core', '--target', 'typescript', '--engine', 'thunder'], dir);
    assert.equal(both.status, 2);
    assert.match(both.stderr, /choose one: --target typescript runs compiled TypeScript, --engine thunder runs Thunder directly\./);
  } finally { rmSync(dir, { recursive: true }); }
  assert.match(typescriptRunner({ nodeVersion: '20.10.0', searchDefaults: false }).error, /^Running TypeScript needs Node\.js 22\.6 or newer \(this is Node 20\.10\.0\), or the typescript package/);
  assert.deepEqual(typescriptRunner({ nodeVersion: '22.6.0' }).args, ['--experimental-strip-types']);
  assert.deepEqual(typescriptRunner({ nodeVersion: '24.1.0' }).args, []);
});

