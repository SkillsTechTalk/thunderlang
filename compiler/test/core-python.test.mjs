// Thunder Core -> Python: the generated code for each feature (no Python needed for these tests).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { compileCore } from '../src/core/index.mjs';
import { percentDecimal } from '../src/core/target-python.mjs';

const gen = (src) => {
  const r = compileCore(src, { file: 'main.thunder' });
  assert.deepEqual(r.diagnostics, [], JSON.stringify(r.diagnostics));
  return r.python;
};
const has = (src, ...parts) => { const py = gen(src); for (const p of parts) assert.ok(py.includes(p), `missing ${p} in:\n${py}`); return py; };

test('header names the source and every statement carries # thunder:N', () => {
  const py = has('say "Hello, world!"', '# Generated by the Thunder compiler from main.thunder.', 'print("Hello, world!")  # thunder:1', 'run(main, __file__)');
  assert.match(py, /THUNDER_SOURCE = "main.thunder"/);
});

test('Set and Keep: names become snake_case and kept values UPPER_CASE', () => {
  has('Keep tax rate at 7%\nSet unit price to 2\nsay unit price * tax rate', 'TAX_RATE = Decimal("0.07")  # thunder:1', 'unit_price = 2  # thunder:2', 'unit_price * TAX_RATE');
});

test('percent literals become exact decimals', () => {
  assert.equal(percentDecimal('7'), '0.07');
  assert.equal(percentDecimal('20'), '0.20');
  assert.equal(percentDecimal('12.5'), '0.125');
  assert.equal(percentDecimal('100'), '1.00');
  has('Set x to 20% of 150', 'x = Decimal("0.20") * 150');
});

test('arithmetic: division is always exact, mod has the sign of the divisor', () => {
  has('Set x to 7 / 2\nSet y to 7 mod 3\nSet z to 7.5 mod 2', 'x = divide(7, 2)', 'y = 7 % 3', 'z = modulo(Decimal("7.5"), 2)');
});

test('money literals and money arithmetic', () => {
  has('Set total to $0.10 + $0.20', 'total = Money("0.10") + Money("0.20")');
});

test('comparisons, and/or/not, yes/no', () => {
  has('Set x to 1\nSet ok to x is at least 1 and not (x is 3) or x is between 5 and 9', 'ok = x >= 1 and not x == 3 or 5 <= x <= 9');
  has('Set member to true\nWhen member is true:\n  say 1', 'if member is True:');
});

test('functions with Receive and Give; calls', () => {
  has('To calculate discount:\n  Receive total and member\n  When member is true and total is at least 100:\n    Give 20% of total\n  Otherwise:\n    Give 0\nsay calculate discount with 150 and true',
    'def calculate_discount(total, member):  # thunder:1', '        return Decimal("0.20") * num(total)  # thunder:4', '    else:', 'print(show(calculate_discount(150, True)))');
});

test('For each, Repeat while, Repeat N times, ranges', () => {
  has('Set xs to [1, 2]\nFor each x in xs:\n  say x\nSet n to 2\nRepeat while n is positive:\n  Decrease n by 1\nRepeat 2 times:\n  say "hi"\nFor each i from 1 to 3:\n  say i',
    'for x in xs:', 'while n > 0:', 'n -= 1', 'for _ in range(2):', 'for i in range(1, 4):');
});

test('lists: sum, average, count, min, max, where, sorted by', () => {
  has('An Order has:\n  Price is money\n  Paid is yes/no\nSet orders to an empty list of Orders\nsay the sum of prices from orders where paid is true\nsay the average of prices from orders\nsay the count of orders\nsay the largest of prices from orders\nsay orders sorted by price descending',
    'total_of([order.price for order in orders if order.paid is True])', 'average_of([order.price for order in orders])', 'len(orders)', 'largest_of(', 'sorted(orders, key=lambda order: order.price, reverse=True)');
});

test('records become keyword-only dataclasses; making one uses field names', () => {
  has('A Customer has:\n  Name is text\n  Balance is money\n  Note is optional text\nSet c to a Customer with name "Ada" and balance $10',
    '@dataclass(kw_only=True)  # thunder:1', 'class Customer:', 'name: str  # thunder:2', 'balance: Money  # thunder:3', 'note: str | None = None', 'c = Customer(name="Ada", balance=Money("10"))');
});

test('text interpolation becomes an f-string; non-text values are shown the Thunder way', () => {
  has('Set name to "Ada"\nSet n to 2\nSet ok to true\nsay "Hi {name}, {n} items, ok: {ok}"', 'print(f"Hi {name}, {n} items, ok: {show(ok)}")');
});

test('If this fails: becomes try/except with the error explained', () => {
  has('Set x to 1 / 0\nIf this fails:\n  say "Oops: {error}"', 'try:  # thunder:2', '    x = divide(1, 0)  # thunder:1', 'except Exception as failure:  # thunder:2', 'error = explain(failure)');
});

test('Test and Expect become plain functions and checks', () => {
  has('Test "adds up":\n  Expect 1 + 1 to be 2\n  Expect 1 / 0 to fail',
    'def test_adds_up():  # thunder:1', 'expect_value(1 + 1, "is", 2, "Expect 1 + 1 to be 2")  # thunder:2', 'with expect_failure("Expect 1 / 0 to fail"):', 'THUNDER_TESTS = [');
});

test('Never on a record field is checked before the field changes', () => {
  const py = has('A Trade has:\n  Quantity is whole number\n  Never allow a negative quantity', 'def __setattr__(self, name, value):', 'never(value < 0, "Never allow a negative quantity", rule=3, value=value)');
  assert.ok(py.indexOf('never(value < 0') < py.indexOf('super().__setattr__(name, value)'));
});

test('Never on a name: the new value is checked before it is stored', () => {
  has('Never allow a negative stock\nSet stock to 5\nDecrease stock by 1', 'new_stock = 5  # thunder:2', 'never(new_stock < 0, "Never allow a negative stock", rule=1, value=new_stock)', 'stock = new_stock');
});

test('Use <module> imports the module and calls stay Python', () => {
  has('Use csv as csv\nUse os.path as paths\nSet rows to csv.DictReader(["a,b"]) as list\nsay paths.join("a", "b")', 'import csv', 'import os.path as paths', 'rows = list(csv.DictReader(["a,b"]))');
});

test('maps: entries with a default, keys, sorted by value', () => {
  has('Set counts to an empty map\nSet counts at "a" to (counts at "a" otherwise 0) + 1\nFor each word and seen in counts sorted by value descending:\n  say word',
    'counts = {}', 'counts["a"] = num(counts.get("a", 0)) + 1', 'for word, seen in sorted(counts.items(), key=lambda entry: entry[1], reverse=True):');
});

test('positions in a list start at 1', () => {
  has('Set xs to [1, 2]\nsay xs at 1', 'item_at(xs, 1)');
});

test('the same source always gives the same Python (deterministic)', () => {
  const src = 'To f:\n  Receive x\n  Give x * 2\nsay f with 2';
  assert.equal(gen(src), gen(src));
});
