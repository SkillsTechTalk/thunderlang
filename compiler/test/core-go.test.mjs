// Thunder Core compiled to Go (src/core/target-go.mjs, go-run.mjs). The four-way conformance (Python, the Thunder
// engine, compiled TypeScript, and compiled Go give the same output for every Core test program) runs in
// core-engines.mjs, which core-run, core-stdlib, and core-engine use. This file checks the Go itself: its shape, that
// it builds, Use refused, a missing toolchain, and the commands.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, writeFileSync, readFileSync, rmSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { compileCore } from '../src/core/index.mjs';
import { buildProject } from '../src/core/project.mjs';
import { compileGo, writeGo, buildGo, goDiagnostics, GO_RUNTIME, runGo } from '../src/core/go-run.mjs';
import { goStr } from '../src/core/target-go.mjs';
import { GO } from './core-engines.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CLI = join(HERE, '..', 'src', 'cli.mjs');
const EXAMPLES = join(HERE, '..', '..', 'examples', 'core');
const skipRun = GO.error ? `Go cannot run here: ${GO.error}` : false;
const tmp = () => mkdtempSync(join(tmpdir(), 'thunder-go-'));
const thunder = (args, cwd, env = {}) => spawnSync(process.execPath, [CLI, ...args], { cwd, encoding: 'utf8', env: { ...process.env, ...env } });
const JOURNAL = readFileSync(join(EXAMPLES, 'trading-journal.thunder'), 'utf8');

test('the Go reads like the program: one package, functions, records, and a line mark on every statement', () => {
  const r = compileCore(JOURNAL, { file: 'trading-journal.thunder' });
  const go = compileGo([{ ...r, module: 'journal', kind: 'src' }])['journal.go'];
  assert.match(go, /^\/\/ Generated by the Thunder compiler from trading-journal\.thunder\./);
  assert.match(go, /^package main$/m);
  assert.match(go, /^import T "thunderprogram\/thunder"$/m);
  assert.match(go, /^var Trade = T\.Kind\("Trade", \[\]T\.Field\{/m);
  assert.match(go, /^func calculate_profit\(trade T\.V\) T\.V \{ {2}\/\/ thunder:10$/m);
  assert.match(go, /F\.Line = 12; return T\.Mul\(T\.Sub\(/);
  assert.match(go, /defer func\(\) \{ T\.Exit\(recover\(\)\) \}\(\)/);
  assert.match(go, /^var tests_journal = \[\]T\.Test\{$/m);
  // Every statement that does something carries its Thunder line.
  for (const l of go.split('\n').filter((x) => /^\s*F\.Line = \d+; /.test(x))) assert.match(l, /\/\/ thunder:\d+$/);
});

test('the runtime is standard library only, one package of its own', () => {
  assert.match(GO_RUNTIME, /^package thunder$/m);
  const imports = GO_RUNTIME.match(/import \(([\s\S]*?)\)/)[1].match(/"([^"]+)"/g).map((x) => x.slice(1, -1));
  for (const i of imports) assert.ok(!i.includes('.'), `${i} is not in Go's standard library`);
});

test('Go string literals hold any text', () => {
  assert.equal(goStr('a"b\\c\nd\t\u0001é'), '"a\\"b\\\\c\\nd\\t\\x01é"');
});

test('a name two files both define gets its file in front, so one Go package holds both', { skip: skipRun }, () => {
  const a = compileCore('To total:\n  Receive n\n  Give n + 1\n\nsay total with 1\n', { file: 'src/a.thunder' });
  const b = compileCore('To total:\n  Receive n\n  Give n * 10\n', { file: 'src/b.thunder' });
  const files = compileGo([{ ...a, module: 'a', kind: 'src' }, { ...b, module: 'b', kind: 'src' }]);
  assert.match(files['a.go'], /^func a_total\(n T\.V\) T\.V/m);
  assert.match(files['b.go'], /^func b_total\(n T\.V\) T\.V/m);
  const d = tmp();
  try {
    writeGo([{ ...a, module: 'a', kind: 'src' }, { ...b, module: 'b', kind: 'src' }], d, { entry: 'a' });
    const r = runGo(d);
    assert.equal(r.stdout, '2\n');
  } finally { rmSync(d, { recursive: true }); }
});

test('Use (a Python module) is refused for Go before anything is written (TC405)', () => {
  const r = compileCore('Use csv as csv\nsay 1\n', { file: 'main.thunder' });
  const [d] = goDiagnostics(r);
  assert.equal(d.code, 'TC405');
  assert.match(d.message, /"csv" is a Python module, and this program is compiled to Go, which cannot use it\./);
  const dir = tmp();
  try {
    writeFileSync(join(dir, 'main.thunder'), 'Use csv as csv\nsay 1\n');
    const b = buildProject({ root: dir, single: join(dir, 'main.thunder'), target: 'go' });
    assert.equal(b.ok, false);
    assert.equal(existsSync(join(dir, 'generated', 'go')), false);
  } finally { rmSync(dir, { recursive: true }); }
});

test('thunder new, then run and test with --target go; thunder.toml target = "go"; thunder build writes a module go runs', { skip: skipRun }, () => {
  const d = tmp();
  try {
    thunder(['new', 'hello'], d);
    const run = thunder(['run', 'hello', '--target', 'go'], d);
    assert.equal(run.stdout, 'Hello, world!\n', run.stderr);
    const t = thunder(['test', 'hello', '--target', 'go'], d);
    assert.match(t.stdout, /PASS {2}greet says hello \(tests\/greet\.thunder, line 3\)\n1 test: 1 passed, 0 failed\n/);
    const toml = join(d, 'hello', 'thunder.toml');
    writeFileSync(toml, readFileSync(toml, 'utf8').replace('target = "python"', 'target = "go"').replace('output = "generated/python"', 'output = "generated/go"'));
    assert.equal(thunder(['run', 'hello'], d).stdout, 'Hello, world!\n');
    const b = thunder(['build', 'hello'], d);
    assert.match(b.stdout, /-> hello\/generated\/go\/ \(Go\)/);
    for (const f of ['go.mod', 'main.go', 'thunder_main.go', 'run_tests.go', join('thunder', 'thunder_runtime.go')]) assert.ok(existsSync(join(d, 'hello', 'generated', 'go', f)), f);
    const plain = spawnSync(GO.cmd, ['run', '.'], { cwd: join(d, 'hello', 'generated', 'go'), encoding: 'utf8', env: { ...process.env, GOTOOLCHAIN: 'local' } });
    assert.equal(plain.stdout, 'Hello, world!\n', plain.stderr);
  } finally { rmSync(d, { recursive: true }); }
});

test('an error names the Thunder line and the calls that reached it, the same words as every other target', { skip: skipRun }, () => {
  const d = tmp();
  try {
    writeFileSync(join(d, 'main.thunder'), 'To half:\n  Receive n\n  Give n / 0\n\nTo twice:\n  Receive n\n  Give half with n\n\nsay twice with 4\n');
    const r = thunder(['run', '--core', 'main.thunder', '--target', 'go'], d);
    assert.equal(r.status, 1);
    assert.equal(r.stderr, 'main.thunder, line 3 (reached from line 7, then line 9): You divided by zero.  [TC501]\n');
  } finally { rmSync(d, { recursive: true }); }
});

test('no go toolchain: a plain message, and thunder build still works', () => {
  const d = tmp();
  try {
    thunder(['new', 'hello'], d);
    const r = thunder(['run', 'hello', '--target', 'go'], d, { THUNDER_GO: join(d, 'no-go-here') });
    assert.equal(r.status, 2);
    assert.match(r.stderr, /Running Go needs the Go toolchain, version 1\.21 or newer \(https:\/\/go\.dev\/dl\/\)/);
    assert.equal(thunder(['build', 'hello', '--target', 'go'], d, { THUNDER_GO: join(d, 'no-go-here') }).status, 0);
  } finally { rmSync(d, { recursive: true }); }
});

test('the example programs build as Go (go build checks every generated file)', { skip: skipRun }, () => {
  const b = buildProject({ root: EXAMPLES, includeTests: true, write: false, target: 'go' });
  const d = tmp();
  try {
    writeGo(b.results, d);
    assert.deepEqual(buildGo(d), { ok: true, output: '' });
    assert.deepEqual(buildGo(d, { tests: true }), { ok: true, output: '' });
  } finally { rmSync(d, { recursive: true }); }
});
