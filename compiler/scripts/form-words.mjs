#!/usr/bin/env node
// Writes src/form-words.mjs: every word that appears in the fixed text of Thunder's step readers (the string and
// template literals of the reader modules). Say less (src/say-less.mjs) accepts a word in a step's words only when it
// is a word of the step's own code or one of these fixed form words, so a reading never contains a word that came
// from nowhere. Run after changing a reader's wording: node scripts/form-words.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', 'src');
const READERS = ['steps.mjs', 'read.mjs', 'shell.mjs', 'commands.mjs', 'powershell.mjs', 'rlang.mjs', 'libraries.mjs', 'sql-proc.mjs'];

/** The text parts of every string and template literal (template values `${…}` scanned for literals of their own). */
function literals(text) {
  const out = [];
  let i = 0;
  const n = text.length;
  const template = () => {
    // at the opening backtick
    let part = '';
    for (i++; i < n; i++) {
      const c = text[i];
      if (c === '\\') { part += text[i + 1] ?? ''; i++; continue; }
      if (c === '`') { out.push(part); return; }
      if (c === '$' && text[i + 1] === '{') {
        out.push(part); part = ' ';
        i += 2;
        code('}');
        continue;
      }
      part += c;
    }
    out.push(part);
  };
  const quoted = (q) => {
    let part = '';
    for (i++; i < n; i++) {
      const c = text[i];
      if (c === '\\') { part += text[i + 1] ?? ''; i++; continue; }
      if (c === q || c === '\n') break;
      part += c;
    }
    out.push(part);
  };
  // Code up to an unmatched `close` (or the end): comments skipped, literals collected, regex literals skipped.
  const code = (close) => {
    let depth = 0, prev = '';
    for (; i < n; i++) {
      const c = text[i];
      if (c === '/' && text[i + 1] === '/') { while (i < n && text[i] !== '\n') i++; continue; }
      if (c === '/' && text[i + 1] === '*') { const e = text.indexOf('*/', i + 2); i = e < 0 ? n : e + 1; continue; }
      if (c === '/' && /[=(,:;!&|?{}\[\n]|^$/.test(prev)) {
        // A regular expression literal: skip it (a class may hold a slash).
        let cls = false;
        for (i++; i < n; i++) { const d = text[i]; if (d === '\\') { i++; continue; } if (d === '[') cls = true; else if (d === ']') cls = false; else if (d === '/' && !cls) break; else if (d === '\n') break; }
        prev = 'x';
        continue;
      }
      if (c === "'" || c === '"') { quoted(c); prev = 'x'; continue; }
      if (c === '`') { template(); prev = 'x'; continue; }
      if (c === '{') depth++;
      if (c === '}') { if (depth === 0 && close === '}') return; depth--; }
      if (!/\s/.test(c)) prev = c;
    }
  };
  code(null);
  return out;
}

const words = new Set();
for (const f of READERS) {
  let text;
  try { text = readFileSync(join(src, f), 'utf8'); } catch { continue; }
  // The scanner above, and a plain pattern over the file as a second pass (each misses some literals the other finds).
  const plain = [...text.replace(/^\s*\/\/.*$/gm, '').matchAll(/'((?:\\.|[^'\\\n])*)'|"((?:\\.|[^"\\\n])*)"|`((?:\\.|[^`\\])*)`/g)].map((m) => (m[1] ?? m[2] ?? m[3]).replace(/\$\{[^}]*\}/g, ' '));
  for (const lit of [...literals(text), ...plain]) {
    // Wording is words with spaces between them, or one capitalized word that starts a sentence ("Uploads").
    // (A lone lowercase verb form, such as 'deleting' or 'uploads', is a word a reader puts into a sentence.)
    if (!/[a-z] [a-z]/i.test(lit) && !/^\s*[A-Z][a-z]+\s*$/.test(lit) && !/^[a-z]{3,}(?:ing|ed|es)$/.test(lit)) continue;
    for (const w of lit.toLowerCase().split(/[^a-z]+/)) if (w.length > 1 && w.length < 20) words.add(w);
  }
}
const list = [...words].sort();
writeFileSync(join(src, 'form-words.mjs'), `// Generated by scripts/form-words.mjs from the step readers' fixed wording. Do not edit by hand.\nexport const FORM_WORDS = new Set(${JSON.stringify(list.join(' '))}.split(' '));\n`);
console.log(`${list.length} form words`);
