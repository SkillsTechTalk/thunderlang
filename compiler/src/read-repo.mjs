// Read a whole repository: run the single-file reader (read.mjs) over every supported file and
// merge the results into one searchable index, with facets a newcomer actually asks about:
// "where does the code decide Decline?" (answers), "which rules use creditScore?" (inputs),
// plus language, folder, kind, and how completely each item was read.
// Pure and browser-safe: callers pass { path, source } pairs (the CLI reads them from disk, the
// browser from a folder the person picks; nothing is uploaded). Deterministic, no AI.
import { readCode, looksCpp } from './read.mjs';
import { readableFormat } from './file-formats.mjs';

export const READ_REPO_SCHEMA = 'thunder-repo-reading-v1';

const EXT_LANG = [
  [/\.d\.ts$/i, null],
  [/\.min\.js$/i, null],
  [/\.(ts|tsx|mts|cts)$/i, 'typescript'],
  [/\.(js|jsx|mjs|cjs)$/i, 'javascript'],
  [/\.pyi?$/i, 'python'],
  [/\.go$/i, 'go'],
  [/\.rs$/i, 'rust'],
  [/\.cs$/i, 'csharp'],
  [/\.java$/i, 'java'],
  [/\.kts?$/i, 'kotlin'],
  [/\.php$/i, 'php'],
  [/\.rb$/i, 'ruby'],
  [/\.sql$/i, 'sql'],
  [/\.c$/i, 'c'],
  [/\.(cc|cpp|cxx|c\+\+|hpp|hh|hxx|ipp|tpp)$/i, 'cpp'],
  [/\.h$/i, 'c'], // C unless its content is C++ (readableLanguage with the source decides)
  [/\.swift$/i, 'swift'],
  [/\.r$/i, 'r'],
  [/\.(sh|bash|zsh|ksh)$/i, 'shell'],
  [/\.(ps1|psm1)$/i, 'powershell'],
];

/** Folders that hold dependencies, build output, or tooling state rather than the application. */
export const READ_SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'build', 'out', '.next', '.nuxt', '.vercel', '.turbo', 'coverage',
  'vendor', 'target', 'bin', 'obj', '__pycache__', '.venv', 'venv', 'env', '.tox', '.mypy_cache',
  '.gradle', '.idea', '.vscode', '.intent', 'third_party', 'Pods', '.terraform',
]);

/** True when a file's first line is a shell shebang (#!/bin/bash, #!/usr/bin/env sh, zsh, ksh, dash). */
export const isShellScript = (source) => /^#!\s*\S*\/(?:env\s+(?:-\S+\s+)*)?(?:ba|z|k|da|a)?sh\b/.test(String(source ?? ''));

/**
 * The language or format the reader uses for a file, or null when it is not read. `source` (the whole file, or at
 * least its first ~2 KB) lets a format that is known by its content be recognized (infrastructure and delivery formats
 * come from file-formats.mjs), and makes a `.h` header C++ when it uses classes, namespaces, templates, or `::`.
 */
export function readableFile(path, source = '') {
  const p = String(path).replace(/\\/g, '/');
  if (p.split('/').some((seg) => READ_SKIP_DIRS.has(seg))) return null;
  const format = readableFormat(p, String(source ?? '').slice(0, 2048));
  if (format) return format;
  for (const [re, lang] of EXT_LANG) if (re.test(p)) return lang === 'c' && /\.h$/i.test(p) && source && looksCpp(source) ? 'cpp' : lang;
  if (source && !/\.[^./]+$/.test(p.split('/').pop()) && isShellScript(source)) return 'shell';
  return null;
}

/** The language the reader uses for a path, or null when the file is not read (see readableFile for `source`). */
export function readableLanguage(path, source = '') {
  return readableFile(path, source);
}

/** Folders whose names start with a dot but hold files Thunder reads (workflows live in .github). */
export const READ_DOT_DIRS = new Set(['.github']);

/** True for files that look machine-generated or minified (very long lines), which read as noise. */
function looksGenerated(source) {
  const lines = source.split('\n');
  if (/^\s*(\/\/|#)\s*(Code generated|@generated|<auto-generated)/im.test(lines.slice(0, 5).join('\n'))) return true;
  const long = lines.filter((l) => l.length > 400).length;
  return long > 3 && long / lines.length > 0.2;
}

const topFolder = (path) => {
  const parts = String(path).replace(/\\/g, '/').split('/');
  return parts.length > 1 ? parts[0] : '.';
};

/**
 * Read every supported file into one index. `files` is [{ path, source }]. Files outside the
 * supported languages, inside dependency/build folders, generated, or too large are listed in
 * `skipped` with the reason, never silently dropped.
 */
export function readRepo(files, { maxFileBytes = 400000, maxFiles = 5000 } = {}) {
  const items = [], fileSummaries = [], skipped = [];
  let considered = 0;
  for (const f of files || []) {
    const path = String(f.path).replace(/\\/g, '/').replace(/^\.\//, '');
    const language = readableLanguage(path, f.source);
    if (!language) continue; // not code this reader understands; not worth listing one by one
    considered++;
    if (considered > maxFiles) { skipped.push({ path, reason: `More than ${maxFiles} files; read a smaller folder to include this one.` }); continue; }
    const source = String(f.source ?? '');
    if (source.length > maxFileBytes || (f.size ?? 0) > maxFileBytes) { skipped.push({ path, reason: `Larger than ${Math.round(maxFileBytes / 1000)} KB.` }); continue; }
    if (looksGenerated(source)) { skipped.push({ path, reason: 'Looks generated or minified.' }); continue; }
    let reading;
    try { reading = readCode(source, { language, file: path }); }
    catch (e) { skipped.push({ path, reason: e instanceof Error ? e.message : 'Could not be read.' }); continue; }
    if (reading.skipped) { skipped.push({ path, reason: reading.skipped }); continue; }
    for (const it of reading.items) items.push({ ...it, id: `${path}#${it.id}`, file: path, language });
    fileSummaries.push({ path, language, counts: reading.counts });
  }
  return { schema: READ_REPO_SCHEMA, ...summarize(items, fileSummaries), skipped };
}

function summarize(items, files) {
  const counts = { decision: 0, function: 0, error: 0, test: 0, partial: 0, guarded: 0, route: 0 };
  const languages = {}, folders = {}, answers = new Map(), inputs = new Map();
  for (const f of files) {
    languages[f.language] = (languages[f.language] || 0) + 1;
    const top = topFolder(f.path);
    folders[top] = (folders[top] || 0) + 1;
  }
  for (const it of items) {
    counts[it.kind]++;
    if (it.status === 'partial') counts.partial++;
    if (it.guards?.length) counts.guarded++;
    if (it.route) counts.route++;
    // Answers include what guards fail with or respond, so "where does the code fail with NotFound?" works.
    const guardAnswers = (it.guards || []).filter((g) => ['fails', 'responds', 'returns'].includes(g.effect.kind)).map((g) => g.effect.name);
    if (it.kind !== 'decision' && !guardAnswers.length) continue;
    for (const result of new Set([...(it.rules || []).map((r) => r.result), it.otherwise?.result, ...guardAnswers].filter(Boolean))) {
      if (!answers.has(result)) answers.set(result, []);
      answers.get(result).push(it.id);
    }
    if (it.kind !== 'decision') continue;
    for (const p of it.inputs || []) {
      if (!inputs.has(p.name)) inputs.set(p.name, []);
      inputs.get(p.name).push(it.id);
    }
  }
  const byUse = (m) => [...m].map(([name, ids]) => ({ name, decisions: ids })).sort((a, b) => b.decisions.length - a.decisions.length || a.name.localeCompare(b.name));
  return { files, items, counts, languages, folders, answers: byUse(answers), inputs: byUse(inputs) };
}

/**
 * Filter the index. Every filter narrows: free text (all words must match), kinds, statuses,
 * languages, a path prefix, an answer the decision can give, and an input it uses.
 */
export function searchRepo(index, { query = '', kinds = [], status = [], languages = [], path = '', answer = '', input = '' } = {}) {
  const terms = String(query).trim().toLowerCase().split(/\s+/).filter(Boolean);
  const prefix = String(path).replace(/\\/g, '/').replace(/^\.\//, '');
  return index.items.filter((it) => {
    if (kinds.length && !kinds.includes(it.kind) && !(kinds.includes('guard') && it.guards?.length) && !(kinds.includes('route') && it.route)) return false;
    if (status.length && !status.includes(it.status)) return false;
    if (languages.length && !languages.includes(it.language)) return false;
    if (prefix && !it.file.startsWith(prefix)) return false;
    if (answer && !((it.rules || []).some((r) => r.result === answer) || it.otherwise?.result === answer || (it.guards || []).some((g) => g.effect.name === answer))) return false;
    if (input && !(it.inputs || []).some((p) => p.name === input)) return false;
    if (!terms.length) return true;
    const hay = [it.file, it.name, it.route && `${it.route.method} ${it.route.path}`, it.says, it.thunder, ...(it.guards || []).flatMap((g) => [g.code, g.effect.name, g.says]), ...(it.inputs || []).map((p) => `${p.name} ${p.type ?? ''}`), ...(it.rules || []).flatMap((r) => [r.when, r.result, r.says]), it.otherwise?.result]
      .filter(Boolean).join(' ').toLowerCase();
    return terms.every((t) => hay.includes(t));
  });
}

/** Group items by file, keeping file order stable (path order) and item order (line order). */
export function groupByFile(items) {
  const groups = new Map();
  for (const it of items) {
    if (!groups.has(it.file)) groups.set(it.file, []);
    groups.get(it.file).push(it);
  }
  return [...groups].sort(([a], [b]) => a.localeCompare(b)).map(([file, list]) => ({ file, language: list[0].language, items: list }));
}

/**
 * Read every file once. Whole-app stages (thunderModel, thunderizeFiles, sameMeaning) reuse `reading` when a file
 * carries one, so a caller running several stages pays for reading only once: `const app = readFiles(files)`, then
 * pass `app` to each. Files Thunder does not read are passed through unchanged.
 */
export function readFiles(files) {
  return files.map((f) => {
    const language = readableLanguage(f.path, f.source);
    if (!language || !f.source || f.reading) return f;
    try { return { ...f, reading: readCode(f.source, { language, file: f.path }) }; }
    catch (e) { return { ...f, readError: e.message }; }
  });
}

/** A file's reading: the one readFiles attached, or a fresh one. Throws the same error the reader would. */
export function readingOf(f, language = readableLanguage(f.path, f.source)) {
  if (f.readError) throw new Error(f.readError);
  return f.reading ?? readCode(f.source, { language, file: f.path });
}
