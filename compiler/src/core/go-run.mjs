// Writing compiled Go to disk, and running it.
//
// The output is one Go module: go.mod, thunder/thunder_runtime.go (the runtime, a package of its own so Go's build
// cache keeps it compiled), one <module>.go per Thunder file (package main), and two entry files picked by a build tag:
// thunder_main.go runs the program, run_tests.go (-tags thundertests) runs every Test block.
// Running needs the go toolchain (https://go.dev/dl/). Standard library only: nothing is downloaded.
import { writeFileSync, mkdirSync, readFileSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { toGo, pythonOnlyUses, id, goStr, goNamespaces as namespaces } from './target-go.mjs';
import { npmRefusals, dotnetRefusals, httpRefusals } from './target-typescript.mjs';
import { diag } from './diagnostics.mjs';

export const GO_RUNTIME = readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'runtime-go', 'thunder_runtime.go'), 'utf8');

/** TC405 for every Use in a file: Python modules exist only for the Python target. */
export function goDiagnostics(result) {
  return [...npmRefusals(result.info, 'Go', diag), ...dotnetRefusals(result.info, 'Go', diag), ...httpRefusals(result.info, 'Go', diag), ...pythonOnlyUses(result.info).map((u) => diag('TC405', u.line,
    `"${u.module}" is a Python module, and this program is compiled to Go, which cannot use it.`,
    'Build for Python (target = "python") to use Python modules. Thunder never swaps in a different library.'))];
}


/** Compile checked results to Go: { [file]: text } for the module files. */
export function compileGo(results) {
  const ns = namespaces(results);
  const files = {};
  for (const r of results) files[`${r.module}.go`] = toGo(r.program, r.info, { source: r.file, module: r.module, ns: ns.get(r.module) });
  return files;
}

/**
 * Write the Go module for `results` into outDir. `entry` is the module `thunder run` runs (its kept values are worked
 * out first, as Python's import of it does); the tests entry works out every file's kept values, in order.
 */
export function writeGo(results, outDir, { entry = null } = {}) {
  mkdirSync(join(outDir, 'thunder'), { recursive: true });
  const files = compileGo(results);
  for (const [f, text] of Object.entries(files)) writeFileSync(join(outDir, f), text);
  writeFileSync(join(outDir, 'go.mod'), 'module thunderprogram\n\ngo 1.21\n');
  writeFileSync(join(outDir, 'thunder', 'thunder_runtime.go'), GO_RUNTIME);
  const main = entry ?? results.find((r) => r.kind !== 'test')?.module ?? results[0]?.module;
  writeFileSync(join(outDir, 'thunder_main.go'), [
    '//go:build !thundertests',
    '',
    '// Generated by the Thunder compiler: runs the program. Build it with: go build -o program .',
    'package main',
    '',
    'import T "thunderprogram/thunder"',
    '',
    'func main() {',
    ...(main ? [`\tkeep_${main}()`, `\tT.Run(main_${main})`] : ['\tT.Run(func() {})']),
    '}',
    '',
  ].join('\n'));
  writeFileSync(join(outDir, 'run_tests.go'), [
    '//go:build thundertests',
    '',
    '// Generated by the Thunder compiler: runs every Test block in this project. Run it with: go run -tags thundertests .',
    'package main',
    '',
    'import T "thunderprogram/thunder"',
    '',
    'func main() {',
    ...results.map((r) => `\tkeep_${r.module}()`),
    `\tT.RunTests([]T.Suite{${results.map((r) => `{File: ${goStr(r.file)}, Tests: tests_${r.module}}`).join(', ')}})`,
    '}',
    '',
  ].join('\n'));
  return Object.keys(files);
}

/** The go toolchain here: { cmd, version } or { error }. */
export function goToolchain() {
  const cmd = process.env.THUNDER_GO || 'go';
  const r = spawnSync(cmd, ['version'], { encoding: 'utf8' });
  if (r.status === 0 && /go version go\d/.test(r.stdout)) return { cmd, version: r.stdout.match(/go(\d+\.\d+(?:\.\d+)?)/)[1] };
  return { error: 'Running Go needs the Go toolchain, version 1.21 or newer (https://go.dev/dl/), or set THUNDER_GO to its path. "thunder build --target go" works without it.' };
}

const goEnv = () => ({ ...process.env, GOTOOLCHAIN: 'local', GOFLAGS: '-mod=mod', GO111MODULE: 'on', CGO_ENABLED: '0' });

/**
 * Build the Go module in outDir (the program, or with `tests` its Test blocks) and run it in the folder `cwd`.
 * Returns spawnSync's result ({ status, stdout, stderr }), or { status: 2, stderr } when Go can't run here.
 */
export function runGo(outDir, { tests = false, cwd = outDir, stdio = 'pipe' } = {}) {
  const go = goToolchain();
  if (go.error) return { status: 2, stdout: '', stderr: `${go.error}\n`, error: go.error };
  const bin = join(outDir, '.run', process.platform === 'win32' ? 'program.exe' : 'program');
  rmSync(dirname(bin), { recursive: true, force: true });
  const args = ['build', '-trimpath', '-o', bin, ...(tests ? ['-tags', 'thundertests'] : []), '.'];
  const b = spawnSync(go.cmd, args, { cwd: outDir, encoding: 'utf8', env: goEnv() });
  if (b.status !== 0) return { status: 2, stdout: '', stderr: `The generated Go did not build (a bug in the Thunder compiler):\n${b.stdout}${b.stderr}`, buildFailed: true };
  return spawnSync(bin, [], { cwd, stdio, encoding: 'utf8' });
}

/** Check that the generated Go builds (go vet off: generated code is not linted). { ok, output } */
export function buildGo(outDir, { tests = false } = {}) {
  const go = goToolchain();
  if (go.error) return { skipped: go.error };
  const r = spawnSync(go.cmd, ['build', '-trimpath', '-o', join(tmpdir(), `thunder-go-check-${process.pid}`), ...(tests ? ['-tags', 'thundertests'] : []), '.'], { cwd: outDir, encoding: 'utf8', env: goEnv() });
  return { ok: r.status === 0, output: `${r.stdout}${r.stderr}`.trim() };
}

