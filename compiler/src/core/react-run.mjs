/** Write the app: every src file with screens to <module>.tsx; the entry file's ThunderApp is the app. */
export function writeReact(results, outDir, { entry }) {
  mkdirSync(outDir, { recursive: true });
  const name = entry.file.split('/').pop().replace(/\.thunder$/, '');
  for (const r of results.filter((x) => x.kind !== 'test' && hasScreens(x.info))) {
    writeFileSync(join(outDir, `${r.module}.tsx`), toReact(r.program, r.info, { source: r.file }));
  }
  writeFileSync(join(outDir, 'main.tsx'), [
    '// Generated by the Thunder compiler: starts the app.',
    "import { createRoot } from 'react-dom/client';",
    `import { ThunderApp } from './${entry.module}.tsx';`,
    "import './thunder.css';",
    '',
    "createRoot(document.getElementById('root')!).render(<ThunderApp />);",
    '',
  ].join('\n'));
  writeFileSync(join(outDir, 'index.html'), `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>${name}</title>
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="./main.tsx"></script>
  </body>
</html>
`);
  writeFileSync(join(outDir, 'thunder_runtime.mjs'), REACT_RUNTIME);
  writeFileSync(join(outDir, 'thunder_runtime.d.mts'), REACT_RUNTIME_DTS);
  writeFileSync(join(outDir, 'thunder.css'), REACT_CSS);
  writeFileSync(join(outDir, 'tsconfig.json'), REACT_TSCONFIG);
  writeFileSync(join(outDir, 'package.json'), `${JSON.stringify({
    name: name.toLowerCase().replace(/[^a-z0-9-]+/g, '-') || 'thunder-app',
    private: true,
    type: 'module',
    scripts: { dev: 'vite', build: 'vite build', preview: 'vite preview', typecheck: 'tsc -p .' },
    dependencies: { react: '^18.3.1', 'react-dom': '^18.3.1' },
    devDependencies: { '@types/react': '^18.3.3', '@types/react-dom': '^18.3.0', typescript: '^5.5.3', vite: '^5.4.0' },
  }, null, 2)}\n`);
}
