// Thunder Core -> Python 3.10+.
//
// The generated code is meant to be read and used without Thunder: plain functions, dataclasses, and a small
// runtime file (thunder_runtime.py) that is written next to it. Every generated statement ends with
// `# thunder:N`, the line of the .thunder file it came from; the runtime uses those comments to report errors
// against Thunder lines.

const P = { or: 1, and: 2, not: 3, cmp: 4, add: 5, mul: 6, unary: 7, atom: 9 };
const wrap = (x, min) => (x.p < min ? `(${x.c})` : x.c);
const py = (s) => JSON.stringify(s); // a valid Python string literal for any text

export function percentDecimal(text) {
  const [i, f = ''] = text.split('.');
  const digits = (i + f).replace(/^0+(?=\d)/, '');
  const pos = digits.length - f.length - 2;
  if (pos <= 0) return `0.${'0'.repeat(-pos)}${digits}`;
  return `${digits.slice(0, pos)}.${digits.slice(pos)}`;
}

const pyType = (t) => {
  if (!t) return 'object';
  switch (t.k) {
    case 'whole': return 'int';
    case 'number': return 'Decimal';
    case 'money': return 'Money';
    case 'text': return 'str';
    case 'bool': return 'bool';
    case 'date': return 'date';
    case 'list': return 'list';
    case 'map': return 'dict';
    case 'record': return py(t.py ?? 'object');
    case 'optional': { const inner = pyType(t.of); return inner.startsWith('"') ? `${inner.slice(0, -1)} | None"` : `${inner} | None`; }
    default: return 'object';
  }
};

const singular = (n) => (n.endsWith('ies') ? `${n.slice(0, -3)}y` : n.endsWith('ses') || n.endsWith('xes') ? n.slice(0, -2) : n.endsWith('s') && !n.endsWith('ss') ? n.slice(0, -1) : null);

export function toPython(program, info, { source = 'main.thunder', imports = [] } = {}) {
  const g = new Gen(program, info, source);
  return g.module(imports);
}

class Gen {
  constructor(program, info, source) {
    this.p = program; this.info = info; this.source = source;
    this.out = []; this.ind = 0;
    this.rt = new Set(['run']); this.needDecimal = false; this.needDate = false; this.needDataclass = false;
    this.usedPy = new Set();
  }
  emit(text, line) { this.out.push(`${'    '.repeat(this.ind)}${text}${line ? `  # thunder:${line}` : ''}`); }
  blank() { while (this.out.length && this.out.slice(-2).join('|') !== '|') this.out.push(''); }
  R(name) { this.rt.add(name); return name; }

  module(srcModules) {
    const body = [];
    const top = this.p.body;
    const own = (s) => !this.info.imported?.has(s);
    // Records, functions, kept values, tests, main.
    for (const r of this.info.records.filter(own)) { this.blank(); this.record(r); }
    for (const f of this.info.funcs.filter(own)) { this.blank(); this.func(f); }
    const consts = this.info.consts.filter(own);
    if (consts.length) { this.blank(); for (const k of consts) this.emit(`${k.py} = ${this.x(k.e).c}`, k.line); }
    const tests = this.info.tests;
    for (const t of tests) {
      this.blank();
      this.emit(`def ${t.py}():`, t.line);
      this.ind++; this.block(t.body); this.ind--;
    }
    if (tests.length) {
      this.blank();
      this.emit('THUNDER_TESTS = [');
      for (const t of tests) this.emit(`    (${py(t.title)}, ${t.py}, ${t.line}),`);
      this.emit(']');
    }
    const main = this.p.main ?? [];
    this.blank();
    if (main.length) {
      this.emit('def main():');
      this.ind++; this.block(main); this.ind--;
      this.blank();
      this.emit('if __name__ == "__main__":');
      this.emit(`    ${this.R('run')}(main, __file__)`);
    }
    body.push(...this.out);

    const head = [
      `# Generated by the Thunder compiler from ${this.source}.`,
      `# This file is a build artifact: change ${this.source.split('/').pop()} and build again, or keep this file and edit it as Python.`,
      '# It needs only Python 3.10+ and thunder_runtime.py (written next to it). "# thunder:N" marks the Thunder line.',
      '',
    ];
    if (this.needDataclass) head.push('from dataclasses import dataclass, field');
    if (this.needDate) head.push('from datetime import date');
    if (this.needDecimal) head.push('from decimal import Decimal');
    for (const m of this.info.modules.filter((x) => own(x) && (x.ecosystem ?? 'python') === 'python')) head.push(m.module === m.py || (m.module.split('.')[0] === m.py && !m.module.includes('.')) ? `import ${m.module}` : `import ${m.module} as ${m.py}`);
    head.push(`from thunder_runtime import ${[...this.rt].sort().join(', ')}`);
    for (const m of srcModules) head.push(`from ${m} import *`);
    head.push('', `THUNDER_SOURCE = ${py(this.source)}`, '', '');
    return `${head.join('\n')}\n${body.join('\n').replace(/\n{4,}/g, '\n\n\n')}\n`;
  }

  record(r) {
    this.needDataclass = true;
    this.emit('@dataclass(kw_only=True)', r.line);
    this.emit(`class ${r.py}:`, r.line);
    this.ind++;
    // Fields that may be left out come with a default (nothing, or an empty list or map).
    for (const f of r.fields) {
      const t = pyType(f.type);
      if (t === 'Decimal') this.needDecimal = true;
      if (t === 'Money') this.R('Money');
      if (t === 'date') this.needDate = true;
      const dflt = f.type.k === 'optional' ? ' = None' : f.type.k === 'list' ? ' = field(default_factory=list)' : f.type.k === 'map' ? ' = field(default_factory=dict)' : '';
      this.emit(`${f.py}: ${t}${dflt}`, f.line);
    }
    if (!r.fields.length) this.emit('pass');
    const rules = r.rulesToCheck ?? [];
    if (rules.length) {
      this.out.push('');
      this.emit('def __setattr__(self, name, value):', rules[0].line);
      this.ind++;
      const bySubject = new Map();
      for (const rule of rules) { const f = r.fieldMap.get(rule.subject); (bySubject.get(f.py) ?? bySubject.set(f.py, []).get(f.py)).push(rule); }
      for (const [field, rs] of bySubject) {
        this.emit(`if name == ${py(field)}:`);
        this.ind++;
        for (const rule of rs) this.emit(`${this.R('never')}(${this.x(rule.rule.cond, { subject: 'value' }).c}, ${py(rule.text)}, rule=${rule.line}, value=value)`, rule.line);
        this.ind--;
      }
      this.emit('super().__setattr__(name, value)');
      this.ind--;
    }
    this.ind--;
  }

  func(f) {
    // A default: a fixed value in the signature; a kept value is filled in when the function is called (it may be
    // written further down the file, and a kept value never changes, so this means the same).
    const late = f.params.filter((p) => p.dflt?.k === 'name');
    this.emit(`def ${f.py}(${f.params.map((p) => (p.dflt ? `${p.py}=${p.dflt.k === 'name' ? `${this.R('NOT_GIVEN')}` : this.x(p.dflt).c}` : p.py)).join(', ')}):`, f.line);
    for (const p of late) this.emit(`    if ${p.py} is ${this.R('NOT_GIVEN')}:\n        ${p.py} = ${this.x(p.dflt).c}`, p.line);
    this.ind++;
    for (const p of f.params) for (const rule of p.rules ?? []) this.emit(`${this.R('never')}(${this.x(rule.rule.cond, { subject: p.py }).c}, ${py(rule.text)}, rule=${rule.line}, value=${p.py})`, p.line);
    this.block(f.body);
    this.ind--;
  }

  block(body) {
    if (!body.length) { this.emit('pass'); return; }
    for (const s of body) this.stmt(s);
  }

  // A name watched by a Never rule gets its new value checked before it is stored, so a refused change
  // leaves the old value in place.
  assign(s, name, value) {
    if (!s.rules?.length) { this.emit(`${name} = ${value}`, s.line); return; }
    const tmp = `new_${name}`;
    this.emit(`${tmp} = ${value}`, s.line);
    this.rulesAfter(s, tmp);
    this.emit(`${name} = ${tmp}`, s.line);
  }

  rulesAfter(s, targetPy) {
    for (const rule of s.rules ?? []) this.emit(`${this.R('never')}(${this.x(rule.rule.cond, { subject: targetPy }).c}, ${py(rule.text)}, rule=${rule.line}, value=${targetPy})`, s.line);
  }

  /** Store a value into a name, a field, or an entry (a list position from 1, or a map key). */
  store(t, v, L) {
    if (t.k === 'name') { this.emit(`${t.ref?.py ?? 'unknown'} = ${v}`, L); return; }
    if (t.k === 'field') {
      if (t.static) this.emit(`${wrap(this.x(t.obj), P.atom)}.${t.py} = ${v}`, L);
      else this.emit(`${this.R('set_field')}(${this.x(t.obj).c}, ${py(t.text)}, ${v})`, L);
      return;
    }
    if (t.k === 'at') {
      if (t.objKind === 'list') this.emit(`${this.R('set_item')}(${this.x(t.obj).c}, ${this.x(t.key).c}, ${v})`, L);
      else if (t.objKind === 'map') this.emit(`${wrap(this.x(t.obj), P.atom)}[${this.x(t.key).c}] = ${v}`, L);
      else this.emit(`${this.R('set_entry')}(${this.x(t.obj).c}, ${this.x(t.key).c}, ${v})`, L);
    }
  }

  lv(e) {
    if (e.k === 'name') return e.ref?.py ?? 'unknown';
    return this.x(e).c;
  }

  stmt(s) {
    const L = s.line;
    switch (s.k) {
      case 'say': {
        const v = this.x(s.e);
        this.emit(`print(${s.e.type?.k === 'text' ? v.c : `${this.R('show')}(${v.c})`})`, L);
        return;
      }
      case 'set': {
        const t = s.target;
        const v = this.x(s.e).c;
        if (t.k === 'name') { this.assign(s, t.ref.py, v); return; }
        if (t.k === 'field') {
          if (t.static) this.emit(`${wrap(this.x(t.obj), P.atom)}.${t.py} = ${v}`, L);
          else this.emit(`${this.R('set_field')}(${this.x(t.obj).c}, ${py(t.text)}, ${v})`, L);
          return;
        }
        this.store(t, v, L);
        return;
      }
      case 'give': this.emit(s.e.k === 'nothing' ? 'return None' : `return ${this.x(s.e).c}`, L); return;
      case 'stop': this.emit(`raise ${this.R('Stop')}(${s.e.type?.k === 'text' ? this.x(s.e).c : `${this.R('show')}(${this.x(s.e).c})`})`, L); return;
      case 'if':
        s.branches.forEach((b, k) => {
          this.emit(`${k === 0 ? 'if' : 'elif'} ${this.yn(b.cond).c}:`, b.line);
          this.ind++; this.block(b.body); this.ind--;
        });
        if (s.otherwise) { this.emit('else:'); this.ind++; this.block(s.otherwise); this.ind--; }
        return;
      case 'each': {
        const it = this.x(s.iter).c;
        const [a, b] = s.vars;
        if (b) this.emit(`for ${a.py}, ${b.py} in ${s.iterKind === 'map' ? `${wrap(this.x(s.iter), P.atom)}.items()` : s.iterKind === 'pairs' ? it : `${this.R('pairs_of')}(${it})`}:`, L);
        else this.emit(`for ${a.py} in ${it}:`, L);
        this.ind++; this.block(s.body); this.ind--;
        return;
      }
      case 'range': {
        const to = s.to.k === 'num' && s.to.whole ? String(Number(s.to.text) + 1) : `${wrap(this.x(s.to), P.add)} + 1`;
        this.emit(`for ${s.v.py} in range(${this.x(s.from).c}, ${to}):`, L);
        this.ind++; this.block(s.body); this.ind--;
        return;
      }
      case 'while':
        this.emit(`while ${s.until ? `not ${wrap(this.yn(s.cond), P.not)}` : this.yn(s.cond).c}:`, L);
        this.ind++; this.block(s.body); this.ind--;
        return;
      case 'times':
        this.emit(`for _ in range(${this.x(s.count).c}):`, L);
        this.ind++; this.block(s.body); this.ind--;
        return;
      case 'expect': return this.expect(s);
      case 'add': case 'remove': {
        const v = this.x(s.e).c;
        const target = this.lv(s.target);
        if (s.targetKind === 'list') this.emit(s.k === 'add' ? `${target}.append(${v})` : `${this.R('remove_from')}(${target}, ${v})`, L);
        else if (s.targetKind === 'map') this.emit(`${this.R('remove_from')}(${target}, ${v})`, L);
        else if (s.targetKind === 'number') { if (s.target.k === 'name' && s.rules?.length) { this.assign(s, target, `${target} ${s.k === 'add' ? '+' : '-'} ${v}`); return; } this.emit(`${target} ${s.k === 'add' ? '+' : '-'}= ${v}`, L); }
        else if (s.k === 'add') { if (s.target.k === 'name') this.emit(`${target} = ${this.R('add_to')}(${target}, ${v})`, L); else this.store(s.target, `${this.R('add_to')}(${target}, ${v})`, L); }
        else this.emit(`${this.R('remove_from')}(${target}, ${v})`, L);
        if (s.target.k === 'name') this.rulesAfter(s, target);
        return;
      }
      case 'increase': case 'decrease': {
        const target = this.lv(s.target);
        if (s.target.k === 'name' && s.rules?.length) { this.assign(s, target, `${target} ${s.k === 'increase' ? '+' : '-'} ${wrap(this.x(s.e), P.add + 1)}`); return; }
        if (s.target.k === 'name') { this.emit(`${target} ${s.k === 'increase' ? '+' : '-'}= ${this.x(s.e).c}`, L); return; }
        // A field or an entry: read it, then store the new value (a dynamic field cannot be written with +=).
        this.store(s.target, `${wrap(this.numv(s.target, { c: target, p: P.atom }), P.add)} ${s.k === 'increase' ? '+' : '-'} ${wrap(this.numv(s.e, this.x(s.e)), P.add + 1)}`, L);
        return;
      }
      case 'sort': {
        const target = this.x(s.target);
        const key = s.field ? this.keyLambda(s.field) : null;
        const args = [key ? `key=${key}` : null, s.desc ? 'reverse=True' : null].filter(Boolean).join(', ');
        this.emit(`${wrap(target, P.atom)}.sort(${args})`, L);
        return;
      }
      case 'reverse': this.emit(`${wrap(this.x(s.target), P.atom)}.reverse()`, L); return;
      case 'do': this.emit(this.x(s.e).c, L); return;
      case 'tryFail':
        this.emit('try:', L);
        this.ind++; this.stmt(s.stmt); this.ind--;
        this.emit('except Exception as failure:', L);
        this.ind++;
        this.emit(`${s.errPy} = ${this.R('explain')}(failure)`, L);
        this.block(s.handler);
        this.ind--;
        return;
      default: this.emit(`pass  # not generated: ${s.k}`, L);
    }
  }

  expect(s) {
    const L = s.line;
    const text = py((s.raw ?? 'Expect').trim());
    if (s.mode === 'true') { this.emit(`${this.R('expect_true')}(${this.x(s.e).c}, ${text})`, L); return; }
    if (s.mode === 'fail') {
      this.emit(`with ${this.R('expect_failure')}(${text}${s.msg ? `, ${this.x(s.msg).c}` : ''}):`, L);
      this.ind++; this.emit(this.x(s.e).c, L); this.ind--;
      return;
    }
    const actual = this.x(s.e).c;
    if (s.mode === 'cmp') { this.emit(`${this.R('expect_value')}(${actual}, "contains", ${this.x(s.want).c}, ${text})`, L); return; }
    let c = s.check, neg = '';
    if (c.k === 'not') { neg = 'not '; c = c.e; }
    const OPS = { '==': 'is', '!=': 'is not', '>=': 'at least', '<=': 'at most', '>': 'more than', '<': 'less than' };
    let op, want = 'None';
    if (c.k === 'cmp') { op = OPS[c.op]; want = this.x(c.r).c; }
    else if (c.k === 'adj') op = c.adj;
    else if (c.k === 'isNothing') op = c.neg ? 'not nothing' : 'nothing';
    else if (c.k === 'between') { op = 'between'; want = `(${this.x(c.lo).c}, ${this.x(c.hi).c})`; }
    else if (c.k === 'contains') { op = 'in'; want = this.x(c.l).c; }
    else op = 'is';
    this.emit(`${this.R('expect_value')}(${actual}, ${py(neg + op)}, ${want}, ${text})`, L);
  }

  // A name for the item in a list comprehension: the singular of the list's name when it is free, else "item".
  itemVar(listExpr) {
    const base = listExpr.k === 'name' && listExpr.ref?.py ? singular(listExpr.ref.py) : null;
    const taken = (n) => !n || this.isTaken(n);
    let n = !taken(base) ? base : 'item';
    let k = 2;
    while (this.isTaken(n)) n = `item${k++}`;
    return n;
  }
  isTaken(n) {
    if (this.stack?.includes(n)) return true;
    if (!this.allPy) {
      this.allPy = new Set();
      const add = (s) => { if (s?.py) this.allPy.add(s.py); };
      const visit = (body) => { for (const s of body ?? []) { if (s.k === 'set' && s.target.ref) this.allPy.add(s.target.ref.py); (s.vars ?? []).forEach(add); add(s.v); if (s.errPy) this.allPy.add(s.errPy); visit(s.body); visit(s.handler); visit(s.otherwise); (s.branches ?? []).forEach((b) => visit(b.body)); if (s.stmt) visit([s.stmt]); } };
      for (const f of this.info.funcs) { add(f); f.params.forEach(add); visit(f.body); }
      for (const r of this.info.records) add(r);
      for (const c of this.info.consts) add(c);
      for (const m of this.info.modules) add(m);
      visit(this.p.main); for (const t of this.info.tests) visit(t.body);
    }
    return this.allPy.has(n);
  }

  keyLambda(field, v = 'item') {
    if (field.dynamic) return `lambda ${v}: ${this.R('get_field')}(${v}, ${py(field.key)})`;
    return `lambda ${v}: ${v}.${field.py}`;
  }

  fieldOf(v, field) { return field.dynamic ? `${this.R('get_field')}(${v}, ${py(field.key)})` : `${v}.${field.py}`; }

  // ------------------------------------------------------------ expressions
  /** A value whose kind is not known in advance, used in arithmetic or a comparison: a Python float becomes exact. */
  numv(e, c) {
    return ['whole', 'number', 'money', 'text', 'bool', 'list', 'map', 'record', 'date'].includes(e.type?.k) ? c : { c: `${this.R('num')}(${c.c})`, p: P.atom };
  }

  /** A value used as yes/no: checked at run time unless it is known to be yes/no (never Python's "truthy"). */
  yn(e, ctx = {}) {
    const c = this.x(e, ctx);
    const known = e.type?.k === 'bool' || ['cmp', 'contains', 'between', 'adj', 'isNothing', 'not', 'bool'].includes(e.k) || (e.k === 'bin' && (e.op === 'and' || e.op === 'or'));
    return known ? c : { c: `${this.R('yes_no')}(${c.c})`, p: P.atom };
  }

  x(e, ctx = {}) {
    const A = (c) => ({ c, p: P.atom });
    const sub = (k) => this.x(k, ctx);
    switch (e.k) {
      // A whole number: Python refuses leading zeros (007), and Thunder means 7.
      case 'num': if (e.whole) return A(e.text.replace(/^0+(?=\d)/, '')); this.needDecimal = true; return A(`Decimal(${py(e.text)})`);
      case 'money': return A(`${this.R('Money')}(${py(e.text)})`);
      case 'percent': this.needDecimal = true; return A(`Decimal(${py(percentDecimal(e.text))})`);
      case 'bool': return A(e.v ? 'True' : 'False');
      case 'nothing': return A('None');
      case 'paren': return sub(e.e);
      case 'today': this.needDate = true; return A('date.today()');
      case 'date': this.needDate = true; return A(`date.fromisoformat(${py(e.text)})`);
      case 'str': return A(this.str(e, ctx));
      case 'list': return A(e.items ? `[${e.items.map((i) => sub(i).c).join(', ')}]` : '{}');
      case 'map': return A('{}');
      case 'name': {
        const r = e.ref ?? {};
        if (r.kind === 'subject') return A(ctx.subject ?? 'value');
        if (r.kind === 'elemField') return A(`${ctx.item}.${r.py}`);
        if (r.kind === 'elemKey') return A(`${this.R('get_field')}(${ctx.item}, ${py(r.key)})`);
        if (r.kind === 'elem') return A(ctx.item);
        return A(r.py ?? e.name.replace(/ /g, '_'));
      }
      case 'call': return A(`${e.py}(${e.args.map((a) => sub(a).c).join(', ')})`);
      case 'new': return A(`${e.py}(${e.fields.map((f) => `${f.py}=${sub(f.e).c}`).join(', ')})`);
      case 'field': return e.static ? A(`${wrap(sub(e.obj), P.atom)}.${e.py}`) : A(`${this.R('get_field')}(${sub(e.obj).c}, ${py(e.text)})`);
      case 'at': {
        const o = sub(e.obj), k = sub(e.key);
        if (e.objKind === 'map') return A(e.dflt ? `${wrap(o, P.atom)}.get(${k.c}, ${sub(e.dflt).c})` : `${wrap(o, P.atom)}[${k.c}]`);
        if (e.objKind === 'list') return A(`${this.R('item_at')}(${o.c}, ${k.c}${e.dflt ? `, ${sub(e.dflt).c}` : ''})`);
        return A(`${this.R('entry')}(${o.c}, ${k.c}${e.dflt ? `, ${sub(e.dflt).c}` : ''})`);
      }
      case 'conv': {
        if (e.to === 'list') return A(`list(${sub(e.e).c})`);
        const fn = { number: 'to_number', whole: 'to_whole', money: 'to_money', text: 'to_text', bool: 'to_yes_no', date: 'to_date' }[e.to];
        return A(`${this.R(fn)}(${sub(e.e).c})`);
      }
      case 'where': {
        const v = this.itemVar(e.list);
        return A(`[${v} for ${v} in ${sub(e.list).c} if ${this.withItem(v, () => this.x(e.cond, { ...ctx, item: v }).c)}]`);
      }
      case 'from': {
        const inner = e.list.k === 'where' ? e.list : null;
        const listE = inner ? inner.list : e.list;
        const v = this.itemVar(listE);
        const cond = inner ? ` if ${this.withItem(v, () => this.x(inner.cond, { ...ctx, item: v }).c)}` : '';
        return A(`[${this.fieldOf(v, e.field)} for ${v} in ${sub(listE).c}${cond}]`);
      }
      case 'sorted': {
        const rev = e.desc ? ', reverse=True' : '';
        if (e.mapSort) return A(`sorted(${wrap(sub(e.list), P.atom)}.items(), key=lambda entry: entry[${e.by === 'key' ? 0 : 1}]${rev})`);
        const v = this.itemVar(e.list);
        return A(`sorted(${sub(e.list).c}, key=${this.keyLambda(e.field, v)}${rev})`);
      }
      case 'dot': return A(`${wrap(sub(e.obj), P.atom)}.${e.attr}${e.args ? `(${e.args.map((a) => sub(a).c).join(', ')})` : ''}`);
      case 'op': {
        const a = sub(e.arg);
        switch (e.op) {
          case 'sum': return A(`${this.R('total_of')}(${a.c})`);
          case 'average': return A(`${this.R('average_of')}(${a.c})`);
          case 'count': case 'length': return A(`len(${a.c})`);
          case 'min': return A(`${this.R('smallest_of')}(${a.c})`);
          case 'max': return A(`${this.R('largest_of')}(${a.c})`);
          case 'first': return A(`${this.R('first_of')}(${a.c})`);
          case 'last': return A(`${this.R('last_of')}(${a.c})`);
          case 'words': return A(`${this.R('words_of')}(${a.c})`);
          case 'lines': return A(`${wrap(a, P.atom)}.splitlines()`);
          case 'lowercase': return A(`${wrap(a, P.atom)}.lower()`);
          case 'uppercase': return A(`${wrap(a, P.atom)}.upper()`);
          case 'trimmed': return A(`${wrap(a, P.atom)}.strip()`);
          case 'parts': return A(`${this.R('parts_of')}(${a.c})`);
          case 'abs': return A(`${this.R('absolute')}(${a.c})`);
          case 'jsonText': return A(`${this.R('json_text')}(${a.c})`);
          case 'jsonData': return A(`${this.R('json_data')}(${a.c})`);
          case 'keys': return A(`list(${wrap(a, P.atom)}.keys())`);
          case 'values': return A(`list(${wrap(a, P.atom)}.values())`);
          default: return A(`${e.op}(${a.c})`);
        }
      }
      case 'round': return A(`${this.R('round_to')}(${sub(e.e).c}${e.places ? `, ${sub(e.places).c}` : ''})`);
      case 'readFile': return A(`${this.R('read_file')}(${sub(e.path).c})`);
      case 'neg': return { c: `-${wrap(sub(e.e), P.unary)}`, p: P.unary };
      case 'not': return { c: `not ${wrap(this.yn(e.e, ctx), P.not)}`, p: P.not };
      case 'bin': {
        const l = sub(e.l), r = sub(e.r);
        if (e.op === 'and') { const a = this.yn(e.l, ctx), b = this.yn(e.r, ctx); return { c: `${wrap(a, P.and)} and ${wrap(b, P.and + 1)}`, p: P.and }; }
        if (e.op === 'or') { const a = this.yn(e.l, ctx), b = this.yn(e.r, ctx); return { c: `${wrap(a, P.or)} or ${wrap(b, P.or + 1)}`, p: P.or }; }
        if (e.op === '+' || e.op === '-') { const a = this.numv(e.l, l), b = this.numv(e.r, r); return { c: `${wrap(a, P.add)} ${e.op} ${wrap(b, P.add + 1)}`, p: P.add }; }
        if (e.op === '*') { const a = this.numv(e.l, l), b = this.numv(e.r, r); return { c: `${wrap(a, P.mul)} * ${wrap(b, P.mul + 1)}`, p: P.mul }; }
        if (e.op === '/') return A(`${this.R('divide')}(${l.c}, ${r.c})`);
        if (e.op === 'mod') {
          if (e.l.type?.k === 'whole' && e.r.type?.k === 'whole') return { c: `${wrap(l, P.mul)} % ${wrap(r, P.mul + 1)}`, p: P.mul };
          return A(`${this.R('modulo')}(${l.c}, ${r.c})`);
        }
        return A(`${e.op}(${l.c}, ${r.c})`);
      }
      case 'cmp': {
        const l = sub(e.l), r = sub(e.r);
        if (e.r.k === 'bool' && (e.op === '==' || e.op === '!=')) return { c: `${wrap(this.yn(e.l, ctx), P.cmp + 1)} ${e.op === '==' ? 'is' : 'is not'} ${r.c}`, p: P.cmp };
        return { c: `${wrap(this.numv(e.l, l), P.cmp + 1)} ${e.op} ${wrap(this.numv(e.r, r), P.cmp + 1)}`, p: P.cmp };
      }
      case 'between': return { c: `${wrap(sub(e.lo), P.cmp + 1)} <= ${wrap(sub(e.e), P.cmp + 1)} <= ${wrap(sub(e.hi), P.cmp + 1)}`, p: P.cmp };
      case 'contains': return { c: `${wrap(sub(e.r), P.cmp + 1)} in ${wrap(sub(e.l), P.cmp + 1)}`, p: P.cmp };
      case 'affix': return A(`${this.R(e.end ? 'ends_with' : 'starts_with')}(${sub(e.l).c}, ${sub(e.r).c})`);
      case 'sortedValues': return A(`${this.R('sorted_values')}(${sub(e.list).c}${e.desc ? ', True' : ''})`);
      case 'joined': return A(`${this.R('joined')}(${sub(e.list).c}, ${sub(e.sep).c})`);
      case 'splitAt': return A(`${this.R('split_at')}(${sub(e.text).c}, ${sub(e.sep).c})`);
      case 'replacing': return A(`${this.R('replacing')}(${sub(e.text).c}, ${sub(e.from).c}, ${sub(e.to).c})`);
      case 'adj': {
        const v = sub(e.e);
        if (e.adj === 'empty') return { c: `len(${v.c}) == 0`, p: P.cmp };
        return { c: `${wrap(v, P.cmp + 1)} ${{ positive: '>', negative: '<', zero: '==' }[e.adj]} 0`, p: P.cmp };
      }
      case 'isNothing': return { c: `${wrap(sub(e.e), P.cmp + 1)} ${e.neg ? 'is not' : 'is'} None`, p: P.cmp };
      case 'hole': return A('None');
      default: return A(`None  # not generated: ${e.k}`);
    }
  }
  withItem(v, fn) { (this.stack ??= []).push(v); try { return fn(); } finally { this.stack.pop(); } }

  // Text with {holes} becomes an f-string; a value that is not text is shown the Thunder way (yes/no, $1.00, nothing).
  str(e, ctx) {
    if (e.parts.every((p) => typeof p === 'string')) return py(e.parts.join(''));
    const holes = e.parts.map((p) => {
      if (typeof p === 'string') return null;
      const t = p.e.type?.k;
      const c = this.x(p.e, ctx).c;
      return t === 'text' || t === 'whole' ? c : `${this.R('show')}(${c})`;
    });
    const code = holes.filter(Boolean).join('');
    const q = !code.includes('"') ? '"' : !code.includes("'") ? "'" : null;
    if (q && !code.includes('\\')) {
      const lit = (s) => py(s).slice(1, -1).replace(/\{/g, '{{').replace(/\}/g, '}}').replace(q === "'" ? /'/g : /(?!)/g, "\\'").replace(q === "'" ? /\\"/g : /(?!)/g, '"');
      return `f${q}${e.parts.map((p, k) => (typeof p === 'string' ? lit(p) : `{${holes[k]}}`)).join('')}${q}`;
    }
    return e.parts.map((p, k) => (typeof p === 'string' ? py(p) : holes[k].startsWith('show(') ? holes[k] : `${this.R('show')}(${holes[k]})`)).join(' + ');
  }
}
