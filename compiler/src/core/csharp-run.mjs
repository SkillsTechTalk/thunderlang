// Writing compiled C# to disk, building it with the .NET SDK, and running it.
//
// A build is an ordinary console project: one <module>.cs per Thunder file (a static class), ThunderRuntime.cs, and a
// Program.cs that runs the program (`dotnet ThunderProgram.dll`) or its tests (`dotnet ThunderProgram.dll test`).
// Several programs can share one build (one namespace each, picked by number), which is how the conformance tests
// keep .NET's build time down.
import { writeFileSync, mkdirSync, readFileSync, existsSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { toCSharp, pythonOnlyUses, classOf, cs } from './target-csharp.mjs';
import { npmRefusals } from './target-typescript.mjs';
import { diag } from './diagnostics.mjs';

export const CS_RUNTIME = readFileSync(new URL('./ThunderRuntime.cs', import.meta.url), 'utf8');
export const ASSEMBLY = 'ThunderProgram';

/** TC405 for every Use in a file: Python modules exist only for the Python target. */
export function csharpDiagnostics(result) {
  return [...npmRefusals(result.info, 'C#', diag), ...pythonOnlyUses(result.info).map((u) => diag('TC405', u.line,
    `"${u.module}" is a Python module, and this program is compiled to C#, which cannot use it.`,
    'Build for Python (target = "python") to use Python modules. Thunder never swaps in a different library.'))];
}

/** The .NET SDK here: { cmd, version, major } or { error }. */
export function findDotnet() {
  const cmd = process.env.THUNDER_DOTNET || 'dotnet';
  const r = spawnSync(cmd, ['--version'], { encoding: 'utf8' });
  if (r.status !== 0 || !r.stdout) return { error: 'Building C# needs the .NET SDK (dotnet), version 8 or newer, and I could not find it. Install it from https://dotnet.microsoft.com/download or set THUNDER_DOTNET to its path. "thunder build --target csharp" still writes the C# without it.' };
  const version = r.stdout.trim();
  const major = Number(version.split('.')[0]);
  if (!(major >= 8)) return { error: `Building C# needs the .NET SDK version 8 or newer, but "${cmd}" is ${version}. Install a newer one from https://dotnet.microsoft.com/download.` };
  return { cmd, version, major };
}

/** The .NET boundary (Use "<type>" from .NET or NuGet), written next to the program only when it uses one. */
export const CS_DOTNET = readFileSync(new URL('./ThunderDotnet.cs', import.meta.url), 'utf8');

/** The NuGet packages a program's files name: [{ package, version, line, file }]. */
export function nugetPackages(results) {
  return results.flatMap((r) => (r.info.modules ?? []).filter((m) => !r.info.imported?.has(m) && m.ecosystem === 'nuget').map((m) => ({ package: m.package, version: m.version, line: m.line, file: r.file })));
}

const usesDotnet = (results) => results.some((r) => (r.info.modules ?? []).some((m) => !r.info.imported?.has(m) && (m.ecosystem === 'dotnet' || m.ecosystem === 'nuget')));

const packageRefs = (packages) => {
  const seen = new Map();
  for (const p of packages) if (!seen.has(p.package)) seen.set(p.package, p.version);
  return seen.size ? `  <ItemGroup>\n${[...seen].map(([n, v]) => `    <PackageReference Include="${n}" Version="${v}" />`).join('\n')}\n  </ItemGroup>\n` : '';
};

const csproj = (major, packages = [], invariant = true) => `<Project Sdk="Microsoft.NET.Sdk">
  <!-- Generated by the Thunder compiler. Build: dotnet build; run: dotnet bin/${ASSEMBLY}.dll (add "test" to run the tests). -->
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net${major}.0</TargetFramework>
    <AssemblyName>${ASSEMBLY}</AssemblyName>
    <RootNamespace>${ASSEMBLY}</RootNamespace>
    <Nullable>disable</Nullable>
    <ImplicitUsings>disable</ImplicitUsings>
    <InvariantGlobalization>${invariant}</InvariantGlobalization>
    <SatelliteResourceLanguages>en</SatelliteResourceLanguages>
    <TreatWarningsAsErrors>false</TreatWarningsAsErrors>
    <NoWarn>CS0162;CS0168;CS0219;CS0472;CS1717;CS8321;CS0414</NoWarn>
    <EnableDefaultCompileItems>true</EnableDefaultCompileItems>
  </PropertyGroup>
  <ItemGroup>
    <Compile Remove="bin/**;obj/**" />
  </ItemGroup>
${packageRefs(packages)}</Project>
`;

/** The C# for one program's results (src files, then test files) in `namespace`: { [module]: text }. */
export function compileCSharp(results, namespace = ASSEMBLY) {
  const src = results.filter((r) => r.kind !== 'test');
  const out = {};
  for (const r of results) {
    const imports = r.kind === 'test' ? src.map((s) => s.module) : [];
    out[r.module] = toCSharp(r.program, r.info, { source: r.file, module: r.module, namespace, imports });
  }
  return out;
}

/** The statements that run one program (`entry`) or its tests, the way the other targets load and run them. */
function runCode(results, entry, namespace, indent) {
  const pad = ' '.repeat(indent);
  const q = (m) => `${namespace}.${classOf(m)}`;
  const tests = [
    ...results.map((r) => `${q(r.module)}.Init();`),
    `T.runTests(new (string, (string, System.Action, int)[])[] { ${results.map((r) => `(${cs(r.file)}, ${q(r.module)}.THUNDER_TESTS)`).join(', ')} });`,
  ];
  const run = entry ? [`${q(entry.module)}.Init();`, `T.run(${q(entry.module)}.main);`] : [];
  return { tests: tests.map((l) => pad + l).join('\n'), run: run.map((l) => pad + l).join('\n') };
}

/**
 * Write a project for `results` into `outDir`: <module>.cs, ThunderRuntime.cs, Program.cs, ThunderProgram.csproj.
 * `entry` is the result `thunder run` runs.
 */
export function writeCSharp(results, outDir, { entry = results.find((r) => r.kind !== 'test') ?? null, major = findDotnet().major ?? 8 } = {}) {
  mkdirSync(outDir, { recursive: true });
  const files = compileCSharp(results);
  for (const [m, text] of Object.entries(files)) writeFileSync(join(outDir, `${m}.cs`), text);
  writeFileSync(join(outDir, 'ThunderRuntime.cs'), CS_RUNTIME);
  if (usesDotnet(results)) writeFileSync(join(outDir, 'ThunderDotnet.cs'), CS_DOTNET);
  else rmSync(join(outDir, 'ThunderDotnet.cs'), { force: true });
  const code = runCode(results, entry, ASSEMBLY, 16);
  writeFileSync(join(outDir, 'Program.cs'), `// Generated by the Thunder compiler: runs the program, or every Test block with "test".
using Thunder;

namespace ${ASSEMBLY}
{
    public static class Program
    {
        public static int Main(string[] args)
        {
            bool tests = args.Length > 0 && args[0] == "test";
            return T.Start(() =>
            {
                if (tests)
                {
${code.tests}
                }
                else
                {
${code.run}
                }
            });
        }
    }
}
`);
  writeFileSync(join(outDir, `${ASSEMBLY}.csproj`), csproj(major, nugetPackages(results), !usesDotnet(results)));
  return Object.keys(files);
}

/**
 * Write one build holding many programs, each in its own namespace (P0, P1, …), chosen when it runs:
 * `dotnet ThunderProgram.dll <n> [test]`. `programs`: [{ results, entry }].
 */
export function writeCSharpBatch(programs, outDir, { major = findDotnet().major ?? 8 } = {}) {
  mkdirSync(outDir, { recursive: true });
  const cases = [];
  programs.forEach((p, i) => {
    const ns = `P${i}`;
    for (const [m, text] of Object.entries(compileCSharp(p.results, ns))) writeFileSync(join(outDir, `${ns}_${m}.cs`), text);
    const code = runCode(p.results, p.entry, ns, 24);
    cases.push(`                case ${i}:\n                    if (tests)\n                    {\n${code.tests}\n                    }\n                    else\n                    {\n${code.run}\n                    }\n                    break;`);
  });
  writeFileSync(join(outDir, 'ThunderRuntime.cs'), CS_RUNTIME);
  const all = programs.flatMap((p) => p.results);
  if (usesDotnet(all)) writeFileSync(join(outDir, 'ThunderDotnet.cs'), CS_DOTNET);
  writeFileSync(join(outDir, 'Program.cs'), `// Generated by the Thunder compiler: many programs in one build, chosen by number.
using Thunder;

namespace ${ASSEMBLY}
{
    public static class Program
    {
        public static int Main(string[] args)
        {
            int which = int.Parse(args[0]);
            bool tests = args.Length > 1 && args[1] == "test";
            return T.Start(() =>
            {
                switch (which)
                {
${cases.join('\n')}
                }
            });
        }
    }
}
`);
  writeFileSync(join(outDir, `${ASSEMBLY}.csproj`), csproj(major, nugetPackages(all), !usesDotnet(all)));
}

/** dotnet build the project in `outDir` into outDir/bin. { ok, output } or { error } when there is no .NET SDK. */
export function buildCSharp(outDir, { dotnet = findDotnet() } = {}) {
  if (dotnet.error) return { ok: false, error: dotnet.error };
  const r = spawnSync(dotnet.cmd, ['build', join(outDir, `${ASSEMBLY}.csproj`), '-nologo', '-v', 'q', '-clp:NoSummary;ErrorsOnly', '-o', join(outDir, 'bin')], {
    encoding: 'utf8', env: { ...process.env, DOTNET_CLI_TELEMETRY_OPTOUT: '1', DOTNET_NOLOGO: '1', DOTNET_SKIP_FIRST_TIME_EXPERIENCE: '1' }, maxBuffer: 64 * 1024 * 1024,
  });
  return { ok: r.status === 0, output: `${r.stdout ?? ''}${r.stderr ?? ''}`.trim() };
}

/** Run a built project: `dotnet bin/ThunderProgram.dll …args` in the folder `cwd`. spawnSync's result. */
export function runBuiltCSharp(outDir, args = [], { cwd = outDir, stdio = 'pipe', dotnet = findDotnet() } = {}) {
  return spawnSync(dotnet.cmd, [join(outDir, 'bin', `${ASSEMBLY}.dll`), ...args], {
    cwd, stdio, encoding: 'utf8', env: { ...process.env, DOTNET_CLI_TELEMETRY_OPTOUT: '1', DOTNET_NOLOGO: '1' }, maxBuffer: 64 * 1024 * 1024,
  });
}

/**
 * Build (if needed) and run the project in `outDir`: the program, or its tests when `tests`. Returns spawnSync's
 * result, or { status: 2, stderr, error } when C# cannot be built or run here.
 */
export function runCSharp(outDir, { tests = false, cwd = outDir, stdio = 'pipe' } = {}) {
  const dotnet = findDotnet();
  if (dotnet.error) return { status: 2, stdout: '', stderr: `${dotnet.error}\n`, error: dotnet.error };
  const b = buildCSharp(outDir, { dotnet });
  if (!b.ok) return { status: 2, stdout: '', stderr: `The C# did not build:\n${b.output}\n`, error: `The C# did not build:\n${b.output}` };
  return runBuiltCSharp(outDir, tests ? ['test'] : [], { cwd, stdio, dotnet });
}

export const csharpBuilt = (outDir) => existsSync(join(outDir, 'bin', `${ASSEMBLY}.dll`));
