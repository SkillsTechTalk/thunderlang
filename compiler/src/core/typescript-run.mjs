// Writing compiled TypeScript to disk, and running it.
//
// Running: Node strips the types itself from version 23.6 (22.6 with --experimental-strip-types). On an older Node,
// Thunder uses the `typescript` package when it can find it (in the project, or next to Thunder) to remove the types
// first. Otherwise it says plainly what is needed. The generated code uses only types Node can strip.
import { writeFileSync, mkdirSync, readFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { toTypeScript, pythonOnlyUses } from './target-typescript.mjs';
import { TS_RUNTIME, TS_RUNTIME_DTS } from './runtime-typescript.mjs';
import { diag } from './diagnostics.mjs';

/** The names a src file gives a test file (its records, functions, and kept values). */
const exportedNames = (r) => [...r.info.records, ...r.info.funcs, ...r.info.consts].filter((s) => !r.info.imported?.has(s)).map((s) => s.py);

/** TC405 for every Use in a file: Python modules exist only for the Python target. */
export function typescriptDiagnostics(result) {
  return pythonOnlyUses(result.info).map((u) => diag('TC405', u.line,
    `"${u.module}" is a Python module, and this program is compiled to TypeScript, which cannot use it.`,
    'Build for Python (target = "python") to use Python modules. Thunder never swaps in a different library.'));
}

/**
 * Compile checked results to TypeScript: { [module]: text }. Test files import every src file's names, as the
 * Python target's `from <module> import *` does.
 */
export function compileTypeScript(results) {
  const src = results.filter((r) => r.kind !== 'test');
  const out = {};
  for (const r of results) {
    const imports = r.kind === 'test' ? src.map((s) => ({ module: s.module, names: exportedNames(s) })) : [];
    out[r.module] = toTypeScript(r.program, r.info, { source: r.file, imports });
  }
  return out;
}

export const TSCONFIG = `${JSON.stringify({
  compilerOptions: { strict: true, noEmit: true, target: 'es2022', module: 'nodenext', moduleResolution: 'nodenext', allowImportingTsExtensions: true, skipLibCheck: true, types: [] },
  include: ['*.ts'],
}, null, 2)}\n`;

/** Write <module>.ts for every result, run_tests.ts, the runtime and its types, package.json, and tsconfig.json. */
export function writeTypeScript(results, outDir) {
  mkdirSync(outDir, { recursive: true });
  const files = compileTypeScript(results);
  for (const [m, text] of Object.entries(files)) writeFileSync(join(outDir, `${m}.ts`), text);
  writeFileSync(join(outDir, 'thunder_runtime.mjs'), TS_RUNTIME);
  writeFileSync(join(outDir, 'thunder_runtime.d.mts'), TS_RUNTIME_DTS);
  writeFileSync(join(outDir, 'package.json'), `${JSON.stringify({ type: 'module', private: true }, null, 2)}\n`);
  writeFileSync(join(outDir, 'tsconfig.json'), TSCONFIG);
  writeFileSync(join(outDir, 'run_tests.ts'), [
    '// Generated by the Thunder compiler: runs every Test block in this project.',
    "import * as T from './thunder_runtime.mjs';",
    ...results.map((r, i) => `import { THUNDER_TESTS as tests${i} } from './${r.module}.ts';`),
    '',
    `T.runTests([${results.map((r, i) => `[${JSON.stringify(r.file)}, tests${i}]`).join(', ')}]);`,
    '',
  ].join('\n'));
  return Object.keys(files);
}

/** How this Node runs TypeScript: { args } for Node itself, { ts } for the typescript package, or { error }. */
export function typescriptRunner({ nodeVersion = process.versions.node, searchFrom = [], searchDefaults = true } = {}) {
  const [maj, min] = nodeVersion.split('.').map(Number);
  if (maj > 23 || (maj === 23 && min >= 6)) return { args: [] };
  if ((maj === 22 && min >= 6) || maj === 23) return { args: ['--experimental-strip-types'] };
  const here = dirname(fileURLToPath(import.meta.url));
  for (const from of [...searchFrom, ...(searchDefaults ? [process.cwd(), here] : [])]) {
    try { const req = createRequire(join(from, 'x.js')); return { ts: req(req.resolve('typescript')) }; } catch { /* not there */ }
  }
  return { error: `Running TypeScript needs Node.js 22.6 or newer (this is Node ${nodeVersion}), or the typescript package (npm install typescript). "thunder build --target typescript" works without either.` };
}

/**
 * Run a compiled module (`entry`, e.g. "main.ts" or "run_tests.ts") in `outDir`, in the folder `cwd`.
 * Returns spawnSync's result ({ status, stdout, stderr }), or { status: 2, stderr } when TypeScript cannot run here.
 */
export function runTypeScript(outDir, entry, { cwd = outDir, stdio = 'pipe', searchFrom = [] } = {}) {
  const runner = typescriptRunner({ searchFrom: [outDir, cwd, ...searchFrom] });
  if (runner.error) return { status: 2, stdout: '', stderr: `${runner.error}\n`, error: runner.error };
  const env = { ...process.env, NODE_NO_WARNINGS: '1' };
  if (runner.args) return spawnSync(process.execPath, [...runner.args, join(outDir, entry)], { cwd, stdio, encoding: 'utf8', env });
  // Older Node: remove the types with the typescript package, into .run/ next to the TypeScript.
  const ts = runner.ts;
  const runDir = join(outDir, '.run');
  rmSync(runDir, { recursive: true, force: true });
  mkdirSync(runDir, { recursive: true });
  for (const f of readdirTs(outDir)) {
    const js = ts.transpileModule(readFileSync(join(outDir, f), 'utf8'), { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
    writeFileSync(join(runDir, f.replace(/\.ts$/, '.mjs')), js.replace(/(from\s+['"]\.\/[^'"]+)\.ts(['"])/g, '$1.mjs$2'));
  }
  writeFileSync(join(runDir, 'thunder_runtime.mjs'), readFileSync(join(outDir, 'thunder_runtime.mjs'), 'utf8'));
  return spawnSync(process.execPath, [join(runDir, entry.replace(/\.ts$/, '.mjs'))], { cwd, stdio, encoding: 'utf8', env });
}

function readdirTs(dir) {
  let all = [];
  try { all = readdirSync(dir); } catch { /* no folder */ }
  return all.filter((f) => f.endsWith('.ts') && !f.endsWith('.d.ts'));
}

/** Typecheck compiled TypeScript with tsc --strict, when tsc can be found. { ok, output } or { skipped }. */
export function typecheckTypeScript(outDir, { searchFrom = [] } = {}) {
  const here = dirname(fileURLToPath(import.meta.url));
  for (const from of [outDir, ...searchFrom, process.cwd(), here]) {
    let tsc;
    try { tsc = createRequire(join(from, 'x.js')).resolve('typescript/bin/tsc'); } catch { continue; }
    const r = spawnSync(process.execPath, [tsc, '-p', join(outDir, 'tsconfig.json')], { encoding: 'utf8' });
    return { ok: r.status === 0, output: `${r.stdout}${r.stderr}`.trim() };
  }
  return { skipped: 'tsc was not found (install typescript to check the generated types)' };
}
