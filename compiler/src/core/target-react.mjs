// Thunder Core screens -> React (TSX, function components with useState).
//
// The same checked program the Thunder engine shows (compileCore -> program + info), and the same meaning: a screen
// is shown the way the engine's screen tree shows it (engine-core.mjs, ScreenApp), and a press or typing changes it the
// same way, through the same code (screen-values.mjs, copied into thunder_runtime.mjs with the engine's value code).
// compiler/test/core-react.test.mjs renders every screen program with react-dom/server, reads the HTML back into a
// tree, and requires the engine's tree; then it presses and types the same things in both and compares again.
//
// Records, functions, and kept values are written exactly as the TypeScript target writes them (it is the same
// generator). Each screen is a component: its inputs are props, each Remember is a useState, and each "When pressed"
// is a function that runs the steps on copies of the remembered values and keeps them only if every step works.
// "// thunder:N" (or {/* thunder:N */} inside the markup) marks the Thunder line each line came from.

import { Gen, id } from './target-typescript.mjs';

const js = (s) => JSON.stringify(s);
const pascal = (py) => py.split('_').filter(Boolean).map((w) => w[0].toUpperCase() + w.slice(1)).join('') || 'Value';

/** Programs with screens: the screens a React app is built from. */
export const hasScreens = (info) => (info.screens ?? []).some((s) => !info.imported?.has(s));

/**
 * Compile one checked file with screens to <module>.tsx. Its first screen is where the app starts; ThunderApp shows
 * it, and any screen a button opens.
 */
export function toReact(program, info, { source = 'main.thunder' } = {}) {
  return new ReactGen(program, info, source).app();
}

class ReactGen extends Gen {
  /**
   * A line of markup, with its Thunder line as a JSX comment (a // comment is not allowed there). The comment touches
   * the tag: spaces between them would be text on the page.
   */
  tag(text, line) { this.out.push(`${'  '.repeat(this.ind)}${text}${line ? `{/* thunder:${line} */}` : ''}`); }

  app() {
    const own = (s) => !this.info.imported?.has(s);
    const screens = this.info.screens.filter(own);
    const head = [
      `// Generated by the Thunder compiler from ${this.source}.`,
      `// A build artifact: change ${this.source.split('/').pop()} and build again, or keep this file and edit it as React.`,
      '// It needs React 18 and thunder_runtime.mjs (written next to it). "thunder:N" marks the Thunder line.',
      '',
      "import * as React from 'react';",
      "import * as T from './thunder_runtime.mjs';",
      '',
      `const FILE = ${js(this.source)};`,
      '',
      '/** Opens another screen of the app (by its name). */',
      'type Opens = (screen: string) => void;',
    ];
    for (const r of this.info.records.filter(own)) { this.blank(); this.record(r); }
    for (const f of this.info.funcs.filter(own)) { this.blank(); this.func(f); }
    const consts = this.info.consts.filter(own);
    if (consts.length) {
      this.blank();
      for (const k of consts) this.emit(`export let ${id(k.py)}: any;`, k.line);
      this.emit('T.init(FILE, (F: any) => {');
      this.ind++;
      for (const k of consts) this.emit(`F.line = ${k.line}; ${id(k.py)} = ${this.x(k.e)};`, k.line);
      this.ind--;
      this.emit('});');
    }
    for (const s of screens) { this.blank(); this.screen(s); }
    // The app: the first screen, and the screens a button opens.
    const opened = new Set();
    const visit = (els) => {
      for (const el of els ?? []) {
        if (el.k === 'button') { if (el.opens?.py) opened.add(el.opens.py); walkSteps(el.press?.body, (s) => { if (s.k === 'open' && s.py) opened.add(s.py); }); }
        for (const b of el.branches ?? []) visit(b.body);
        visit(el.otherwise); visit(el.body);
      }
    };
    for (const s of screens) visit(s.body);
    const first = screens[0];
    const others = screens.filter((s) => s !== first && opened.has(s.py));
    this.blank();
    this.emit(`/** The app: it starts on ${first.text}${others.length ? `, and shows ${others.map((s) => s.text).join(', ')} when a button opens ${others.length === 1 ? 'it' : 'them'}` : ''}. */`);
    this.emit('export function ThunderApp() {');
    this.ind++;
    this.emit(`const [screen, setScreen] = React.useState<string>(${js(first.py)});`);
    this.emit('return (');
    this.ind++;
    this.tag('<T.ShowsProblems key={screen}>');
    this.ind++;
    const chain = others.map((s) => `screen === ${js(s.py)} ? <${s.py} open={setScreen} /> : `).join('');
    this.tag(chain ? `{${chain}<${first.py} open={setScreen} />}` : `<${first.py} open={setScreen} />`);
    this.ind--;
    this.tag('</T.ShowsProblems>');
    this.ind--;
    this.emit(');');
    this.ind--;
    this.emit('}');
    return `${head.join('\n')}\n${this.out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
  }

  screen(s) {
    const props = ['open: Opens', ...s.params.map((p) => `${id(p.py)}${p.dflt ? '?' : ''}: any`)];
    this.emit(`/** Screen ${s.text}. */`);
    this.emit(`export function ${s.py}(props: { ${props.join('; ')} }) {`, s.line);
    this.ind++;
    this.emit(`const F = T.enterFrame(FILE, ${s.line});`);
    this.emit('try {');
    this.ind++;
    for (const p of s.params) {
      const v = id(p.py);
      if (p.dflt) this.emit(`const ${v} = props.${v} === undefined ? (F.line = ${p.line}, ${this.x(p.dflt)}) : props.${v};`, p.line);
      else this.emit(`const ${v} = props.${v};`, p.line);
    }
    this.state = s.remember.map((r) => ({ name: id(r.py), set: `set${pascal(r.py)}` }));
    for (const r of s.remember) this.emit(`const [${id(r.py)}, set${pascal(r.py)}] = React.useState<any>(() => (F.line = ${r.line}, ${this.x(r.e)}));`, r.line);
    this.emit('const [screenProblem, setScreenProblem] = React.useState<string | null>(null);');
    // The buttons' steps, one function each.
    this.handlers = new Map();
    const used = new Set();
    const buttons = [];
    // A button inside a list is pressed for one item: the item (and any outer list's item) is given to its steps.
    const visit = (els, items) => {
      for (const el of els) {
        if (el.k === 'button' && el.press) { el.press.items = items; buttons.push(el); }
        for (const b of el.branches ?? []) visit(b.body, items);
        visit(el.otherwise ?? [], items);
        visit(el.body ?? [], el.k === 'list' ? [...items, id(el.v.py)] : items);
      }
    };
    visit(s.body, []);
    for (const el of buttons) {
      const words = el.label.k === 'str' && el.label.parts.every((p) => typeof p === 'string') ? el.label.parts.join('') : '';
      let name = `press${pascal(words.toLowerCase().replace(/[^a-z0-9]+/g, '_')) || 'Button'}`;
      if (used.has(name) || name === 'pressValue') name = `press${pascal(words.toLowerCase().replace(/[^a-z0-9]+/g, '_')) || 'Button'}${el.line}`;
      used.add(name);
      this.handlers.set(el, name);
      this.pressHandler(el, name, s);
    }
    this.emit('return (');
    this.ind++;
    this.tag(`<section className="thunder-screen" aria-label=${js(s.text)}>`, s.line);
    this.ind++;
    this.elements(s.body);
    this.tag('{screenProblem !== null && <p role="alert" className="thunder-problem">{screenProblem}</p>}');
    this.ind--;
    this.tag('</section>');
    this.ind--;
    this.emit(');');
    this.ind--;
    this.emit('} catch (e) { throw T.fail(e); } finally { T.leave(); }');
    this.ind--;
    this.emit('}');
  }

  /** When "<label>" is pressed: the steps run on copies of the remembered values, which are kept only if all work. */
  pressHandler(el, name, s) {
    const names = this.state.map((x) => x.name);
    const outer = new Set([...names, ...s.params.map((p) => id(p.py)), ...(el.press.items ?? [])]);
    this.emit(`// When ${el.label.k === 'str' ? js(el.label.parts.filter((p) => typeof p === 'string').join('')) : 'the button'} is pressed: the steps change copies, kept only if every step works.`, el.press.line);
    const items = el.press.items ?? [];
    this.emit(`const ${name} = (${items.map((v) => `${v}: any`).join(', ')}) => T.press(FILE, ${el.press.line}, setScreenProblem, props.open, [${names.join(', ')}], [${this.state.map((x) => x.set).join(', ')}],`);
    this.ind++;
    this.emit(`(F: any, openScreen: Opens${names.map((n) => `, ${n}: any`).join('')}) => {`);
    this.ind++;
    const locals = this.localsOf(el.press.body).map(id).filter((n) => !outer.has(n));
    if (locals.length) this.emit(`let ${locals.map((n) => `${n}: any`).join(', ')};`);
    this.block(el.press.body, true);
    if (el.opens?.py) this.line(el.line, `openScreen(${js(el.opens.py)});`);
    this.emit(`return [${names.join(', ')}];`);
    this.ind--;
    this.emit('});');
    this.ind--;
  }

  stmt(s, isVoid) {
    if (s.k === 'open') { this.line(s.line, `openScreen(${js(s.py)});`); return; }
    super.stmt(s, isVoid);
  }

  /** A value shown on the screen: text and whole numbers as they are, anything else the Thunder way. */
  shown(e) {
    if (e.k === 'str' && e.parts.every((p) => typeof p === 'string')) return js(e.parts.join(''));
    const k = e.type?.k;
    return `(F.line = ${e.line}, ${k === 'text' || k === 'whole' ? `T.pyStr(${this.x(e)})` : `T.show(${this.x(e)})`})`;
  }

  elements(els) {
    for (const el of els) {
      const L = el.line;
      switch (el.k) {
        case 'heading': this.tag(`<h1>{${this.shown(el.e)}}</h1>`, L); break;
        case 'text': this.tag(`<p>{${this.shown(el.e)}}</p>`, L); break;
        case 'row':
          this.tag('<div className="thunder-row">', L);
          this.ind++; this.elements(el.body); this.ind--;
          this.tag('</div>');
          break;
        case 'list': {
          const v = id(el.v.py);
          this.tag('<ul>', L);
          this.ind++;
          this.tag(`{T.pyIter((F.line = ${L}, ${this.x(el.iter)})).map((${v}: any, itemIndex: number) => (`);
          this.ind++;
          this.tag('<li key={itemIndex}>');
          this.ind++; this.elements(el.body); this.ind--;
          this.tag('</li>');
          this.ind--;
          this.tag('))}');
          this.ind--;
          this.tag('</ul>');
          break;
        }
        case 'when': {
          el.branches.forEach((b, k) => {
            this.tag(`${k === 0 ? '{' : ') : '}(F.line = ${b.line}, ${this.yn(b.cond)}) ? (`);
            this.ind++;
            this.tag(`<React.Fragment key="${k}">`, b.line);
            this.ind++; this.elements(b.body); this.ind--;
            this.tag('</React.Fragment>');
            this.ind--;
          });
          if (el.otherwise) {
            this.tag(') : (');
            this.ind++;
            this.tag('<React.Fragment key="else">');
            this.ind++; this.elements(el.otherwise); this.ind--;
            this.tag('</React.Fragment>');
            this.ind--;
            this.tag(')}');
          } else this.tag(') : null}');
          break;
        }
        case 'textbox': case 'numberbox': {
          const st = this.state.find((x) => x.name === id(el.target.ref.py));
          const change = el.k === 'textbox'
            ? `(event) => T.typeText(event.target.value, ${st.set}, setScreenProblem)`
            : `(event) => T.typeNumber(event.target.value, ${js(el.boxKind)}, ${st.set}, setScreenProblem)`;
          this.tag('<label className="thunder-box">', L);
          this.ind++;
          this.tag(`{${this.shown(el.label)}}`);
          this.tag(`<input type="${el.k === 'textbox' ? 'text' : 'number'}" value={${el.k === 'textbox' ? `T.pyStr(${st.name})` : `T.show(${st.name})`}} onChange={${change}} />`);
          this.ind--;
          this.tag('</label>');
          break;
        }
        case 'button': {
          const h = this.handlers.get(el);
          const onClick = h ? (el.press.items?.length ? `() => ${h}(${el.press.items.join(', ')})` : h) : `() => props.open(${js(el.opens.py)})`;
          const off = el.off ? ` disabled={(F.line = ${L}, ${this.yn(el.off)})}` : '';
          this.tag(`<button type="button"${off} onClick={${onClick}}>{${this.shown(el.label)}}</button>`, L);
          break;
        }
        case 'child': {
          const given = el.given.map((g) => ` ${id(g.py)}={(F.line = ${g.line}, ${this.x(g.e)})}`).join('');
          this.tag(`<${el.screen.py} open={props.open}${given} />`, L);
          break;
        }
        default: this.tag(`{/* not generated: ${el.k} */}`, L);
      }
    }
  }
}

/** Every step under a "When pressed", nested ones too. */
function walkSteps(body, fn) {
  for (const s of body ?? []) {
    fn(s);
    walkSteps(s.body, fn); walkSteps(s.otherwise, fn); walkSteps(s.handler, fn);
    for (const b of s.branches ?? []) walkSteps(b.body, fn);
    if (s.stmt) walkSteps([s.stmt], fn);
  }
}

