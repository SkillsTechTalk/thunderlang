// Thunder Core -> Rust (a binary crate; standard library only).
//
// The same checked program the Python target, the Thunder engine, and the TypeScript target use (compileCore ->
// program + info), and the same meaning: every statement does what target-typescript.mjs writes for it, and every
// operation calls thunder_runtime.rs, a line-by-line port of the engine's own value code (engine-values.mjs).
// compiler/test/core-engines.mjs runs every Core test program on Python, the Thunder engine, compiled TypeScript, and
// compiled Rust, and requires the same output.
//
// Every generated statement sets the frame's line (T::set_line(N)) and ends with `// thunder:N`, the Thunder line it
// came from, so an error says which Thunder line failed, exactly as the other targets do. An error is a panic
// carrying the Thunder error; each function's frame (T::call) catches it on the way out and remembers where it was.

import { percentDecimal } from './target-python.mjs';
import { firstLine } from './target-typescript.mjs';

/** A Rust string literal for any text. */
export function rs(s) {
  let out = '"';
  for (const ch of String(s)) {
    const cp = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (cp < 0x20 || cp === 0x7f || (cp >= 0xd800 && cp <= 0xdfff)) out += `\\u{${cp.toString(16)}}`;
    else out += ch;
  }
  return `${out}"`;
}

const RESERVED = new Set(('as async await break const continue crate dyn else enum extern false fn for if impl in let loop match mod move mut pub ref return self Self static struct super trait true type unsafe use where while abstract become box do final macro override priv typeof unsized virtual yield try union T Value FILE main init thunder_tests std core alloc').split(' '));
/** A Rust name for a Thunder (Python) name: the same, unless Rust or the generated code owns it. */
export const id = (py) => (RESERVED.has(py) ? `${py}_` : py);
/** The function that gives a kept value, and the one that gives a record's kind. */
export const keptFn = (py) => `kept_${py}`;
export const kindFn = (py) => `kind_${py}`;

const KNOWN_BOOL = new Set(['cmp', 'contains', 'between', 'adj', 'isNothing', 'not', 'bool', 'affix']);

/** Thunder modules a program uses that only Python has (Use): compiled Rust cannot call them. */
export function pythonOnlyUses(info) {
  return (info.modules ?? []).filter((m) => !info.imported?.has(m)).map((m) => ({ module: m.module, line: m.line }));
}

/**
 * Compile one checked file. `imports`: [{ module, names }] for a test file (the project's src modules it sees).
 * Gives back the text of the module's .rs file.
 */
export function toRust(program, info, { source = 'main.thunder', imports = [] } = {}) {
  return new Gen(program, info, source).module(imports);
}

/** The names a src module gives a test module: its record kinds, functions, and kept values. */
export function exportedRustNames(info) {
  const own = (s) => !info.imported?.has(s);
  return [
    ...info.records.filter(own).map((r) => kindFn(r.py)),
    ...info.funcs.filter(own).map((f) => id(f.py)),
    ...info.consts.filter(own).map((k) => keptFn(k.py)),
  ];
}

class Gen {
  constructor(program, info, source) {
    this.p = program; this.info = info; this.source = source;
    this.out = []; this.ind = 0; this.tmp = 0;
    this.consts = new Set(info.consts.map((k) => k.py));
    this.funcs = new Map(info.funcs.map((f) => [f.py, f]));
    this.tryDepth = 0; // inside "If this fails": a Give leaves through the closure
    this.isVoid = false;
    this.ruleFns = [];
  }
  emit(text, line) { this.out.push(`${'    '.repeat(this.ind)}${text}${line ? `  // thunder:${line}` : ''}`); }
  blank() { if (this.out.length && this.out[this.out.length - 1] !== '') this.out.push(''); }
  fresh(base) { return `${base}_${++this.tmp}`; }

  module(imports) {
    const own = (s) => !this.info.imported?.has(s);
    const head = [
      `// Generated by the Thunder compiler from ${this.source}.`,
      `// A build artifact: change ${this.source.split('/').pop()} and build again, or keep this file and edit it as Rust.`,
      '// It needs only Rust and thunder_runtime.rs (written next to it). "// thunder:N" marks the Thunder line.',
      '#![allow(unused_mut, unused_variables, unused_assignments, unreachable_code, non_snake_case, dead_code, unused_imports, unused_parens, unused_braces, non_upper_case_globals, clippy::all)]',
      '',
      'use thunder_runtime::{self as T, Value};',
      ...imports.filter((m) => m.names.length).map((m) => `use crate::${m.module}::{${m.names.join(', ')}};`),
      '',
      `const FILE: &str = ${rs(this.source)};`,
    ];
    for (const r of this.info.records.filter(own)) { this.blank(); this.record(r); }
    for (const f of this.info.funcs.filter(own)) { this.blank(); this.func(f); }
    const consts = this.info.consts.filter(own);
    this.blank();
    if (consts.length) {
      this.emit('thread_local! {');
      this.ind++;
      for (const k of consts) this.emit(`static ${this.slot(k.py)}: T::Kept = T::Kept::new();`, k.line);
      this.ind--;
      this.emit('}');
      for (const k of consts) this.emit(`pub fn ${keptFn(k.py)}() -> Value { ${this.slot(k.py)}.with(|k| k.get()) }`, k.line);
      this.blank();
    }
    this.emit('/// Work out this file\'s kept values (before anything runs).');
    this.emit('pub fn init() {');
    this.ind++;
    if (consts.length) {
      this.emit('T::init(FILE, || {');
      this.ind++;
      for (const k of consts) this.emit(`T::set_line(${k.line}); let v = ${this.x(k.e)}; ${this.slot(k.py)}.with(|k| k.set(v));`, k.line);
      this.ind--;
      this.emit('});');
    }
    this.ind--;
    this.emit('}');
    const tests = this.info.tests;
    for (const t of tests) {
      this.blank();
      this.emit(`fn ${id(t.py)}() {`, t.line);
      this.ind++;
      this.frameBody(`T::frame(FILE, ${t.line}`, t.body, [], true);
      this.ind--;
      this.emit('}');
    }
    this.blank();
    this.emit('pub fn thunder_tests() -> Vec<(&\'static str, fn(), i64)> {');
    this.ind++;
    this.emit(`vec![${tests.map((t) => `(${rs(t.title)}, ${id(t.py)} as fn(), ${t.line})`).join(', ')}]`);
    this.ind--;
    this.emit('}');
    const main = this.p.main ?? [];
    this.blank();
    this.emit('pub fn main() {');
    this.ind++;
    if (main.length) this.frameBody('T::frame(FILE, 0', main, [], true);
    this.ind--;
    this.emit('}');
    const rules = this.ruleFns.length ? `\n${this.ruleFns.join('\n')}\n` : '';
    return `${head.join('\n')}\n${this.out.join('\n').replace(/\n{3,}/g, '\n\n')}\n${rules}`;
  }

  slot(py) { return `KEPT_${py.toUpperCase()}`; }

  record(r) {
    const fields = r.fields.map((f) => `(${rs(f.py)}, ${rs(f.type?.k ?? 'any')})`).join(', ');
    const rules = r.rulesToCheck ?? [];
    const bySubject = new Map();
    for (const rule of rules) { const f = r.fieldMap.get(rule.subject); (bySubject.get(f.py) ?? bySubject.set(f.py, []).get(f.py)).push(rule); }
    const ruleCode = [...bySubject].map(([field, rs_]) => `(${rs(field)}, vec![${rs_.map((rule) => {
      const fn = this.ruleFn(`rule_${r.py}_${field}_${rule.line}_${++this.tmp}`, rule.rule.cond);
      return `T::Rule { cond: ${fn}, text: ${rs(rule.text)}, line: ${rule.line} }`;
    }).join(', ')}])`).join(', ');
    this.emit('thread_local! {', r.line);
    this.ind++;
    this.emit(`static KIND_${r.py.toUpperCase()}: std::rc::Rc<T::Kind> = T::kind(${rs(r.py)}, vec![${fields}], vec![${ruleCode}]);`, r.line);
    this.ind--;
    this.emit('}');
    this.emit(`/// The ${r.py} record: its fields${rules.length ? ' and the rules they must keep' : ''}.`);
    this.emit(`pub fn ${kindFn(r.py)}() -> std::rc::Rc<T::Kind> { KIND_${r.py.toUpperCase()}.with(|k| k.clone()) }`, r.line);
  }

  /** A Never rule's condition as a function of the new value. */
  ruleFn(name, cond) {
    const saved = { tryDepth: this.tryDepth };
    const body = this.x(cond, { subject: 'value.clone()' });
    Object.assign(this, saved);
    this.ruleFns.push(`fn ${name}(value: Value) -> Value { ${body} }`);
    return name;
  }

  func(f) {
    const params = f.params.map((p) => `${id(p.py)}: Value`);
    this.emit(`pub fn ${id(f.py)}(${params.join(', ')}) -> Value {`, f.line);
    this.ind++;
    const pre = [];
    for (const p of f.params) pre.push([`let mut ${id(p.py)} = ${id(p.py)};`, null]);
    for (const p of f.params) if (p.dflt?.k === 'name') pre.push([`if matches!(${id(p.py)}, Value::NotGiven) { T::set_line(${p.line}); ${id(p.py)} = ${this.x(p.dflt)}; }`, p.line]);
    for (const p of f.params) for (const rule of p.rules ?? []) pre.push([`T::set_line(${p.line}); T::never(${this.x(rule.rule.cond, { subject: `${id(p.py)}.clone()` })}, ${rs(rule.text)}, ${rule.line}, ${id(p.py)}.clone());`, p.line]);
    const first = firstLine(f);
    this.frameBody(`T::call(FILE, ${f.line}, ${first == null ? 'None' : `Some(${first})`}`, f.body, pre, false, f.params.map((p) => p.py));
    this.ind--;
    this.emit('}');
  }

  /** A body that runs in its own frame: errors leave with the Thunder line they happened on. */
  frameBody(enter, body, pre, isVoid, params = []) {
    const savedVoid = this.isVoid;
    this.isVoid = isVoid;
    this.emit(`${enter}, move || {`);
    this.ind++;
    const locals = [...this.localsOf(body)].filter((n) => !params.includes(n));
    for (const n of locals) this.emit(`let mut ${id(n)}: Value = T::NOTHING;`);
    for (const [code, line] of pre) this.emit(code, line);
    this.block(body);
    if (!isVoid) this.emit('T::NOTHING');
    this.ind--;
    this.emit(isVoid ? '});' : '})');
    this.isVoid = savedVoid;
  }

  /** The names a body assigns (Python's locals): declared once at the top, as a Python function's are. */
  localsOf(body) {
    const names = new Set();
    const visit = (ss) => {
      for (const s of ss ?? []) {
        if (s.k === 'set' && s.target.k === 'name' && s.target.ref?.py) names.add(s.target.ref.py);
        for (const v of s.vars ?? []) if (v?.py) names.add(v.py);
        if (s.k === 'range' && s.v?.py) names.add(s.v.py);
        if (s.errPy) names.add(s.errPy);
        visit(s.body); visit(s.handler); visit(s.otherwise);
        for (const b of s.branches ?? []) visit(b.body);
        if (s.stmt) visit([s.stmt]);
      }
    };
    visit(body);
    const globals = new Set([...this.info.consts, ...this.info.funcs, ...this.info.records].map((x) => x.py));
    return [...names].filter((n) => !globals.has(n));
  }

  block(body) { for (const s of body) this.stmt(s); }

  /** T::set_line(N); <code>  // thunder:N */
  line(L, code) { this.emit(`T::set_line(${L}); ${code}`, L); }

  /** Give: leave the function (or, inside "If this fails", the closure that catches the failure). */
  giveCode(value) {
    if (this.tryDepth > 0) return `return Some(${this.isVoid ? 'T::NOTHING' : value});`;
    return this.isVoid ? 'return;' : `return ${value};`;
  }

  /** Check a watched name's Never rules on its new value, then store it. */
  assign(s, name, valueCode) {
    if (!s.rules?.length) { this.line(s.line, `${id(name)} = ${valueCode};`); return; }
    const v = this.fresh('new');
    this.line(s.line, `{ let ${v} = ${valueCode};`);
    this.ind++;
    for (const rule of s.rules) this.emit(`T::never(${this.x(rule.rule.cond, { subject: `${v}.clone()` })}, ${rs(rule.text)}, ${rule.line}, ${v}.clone());`, s.line);
    this.emit(`${id(name)} = ${v}; }`, s.line);
    this.ind--;
  }
  rulesAfter(s, name) {
    for (const rule of s.rules ?? []) this.emit(`T::never(${this.x(rule.rule.cond, { subject: `${id(name)}.clone()` })}, ${rs(rule.text)}, ${rule.line}, ${id(name)}.clone());`, s.line);
  }

  /** Code that stores `v` (a Rust variable holding the value) into a name, a field, or an entry. */
  storeCode(t, v) {
    if (t.k === 'name') return `${id(t.ref?.py ?? 'unknown')} = ${v};`;
    if (t.k === 'field') return t.static ? `T::set_attr(${this.x(t.obj)}, ${rs(t.py)}, ${v});` : `T::set_field(${this.x(t.obj)}, ${rs(t.text)}, ${v});`;
    if (t.k === 'at') {
      const fn = t.objKind === 'list' ? 'T::set_item' : t.objKind === 'map' ? 'T::map_set' : 'T::set_entry';
      return `${fn}(${this.x(t.obj)}, ${this.x(t.key)}, ${v});`;
    }
    return '';
  }

  stmt(s) {
    const L = s.line;
    switch (s.k) {
      case 'say': this.line(L, `T::say(${s.e.type?.k === 'text' ? `T::py_str(${this.x(s.e)})` : `T::show(${this.x(s.e)})`});`); return;
      case 'set': {
        const t = s.target;
        if (t.k === 'name') { this.assign(s, t.ref.py, this.x(s.e)); return; }
        const v = this.fresh('v');
        this.line(L, `{ let ${v} = ${this.x(s.e)}; ${this.storeCode(t, v)} }`);
        return;
      }
      case 'give': this.line(L, this.giveCode(s.e.k === 'nothing' ? 'T::NOTHING' : this.x(s.e))); return;
      case 'stop': { const v = this.x(s.e); this.line(L, `T::stop_with(${s.e.type?.k === 'text' ? `T::py_str(${v})` : `T::show(${v})`});`); return; }
      case 'if': {
        this.emit(`T::set_line(${L});`, L);
        s.branches.forEach((b, k) => {
          this.emit(`${k === 0 ? 'if' : '} else if'} { T::set_line(${b.line}); ${this.yn(b.cond)} } {`, b.line);
          this.ind++; this.block(b.body); this.ind--;
        });
        if (s.otherwise) { this.emit('} else {'); this.ind++; this.block(s.otherwise); this.ind--; }
        this.emit('}');
        return;
      }
      case 'each': {
        const [a, b] = s.vars;
        const it = this.x(s.iter);
        const seq = b ? (s.iterKind === 'map' ? `T::map_items(${it})` : s.iterKind === 'pairs' ? `T::py_iter(${it})` : `T::pairs_of(${it})`) : `T::py_iter(${it})`;
        const el = this.fresh('el');
        this.line(L, `for ${el} in ${seq} {`);
        this.ind++;
        if (b) { const p = this.fresh('pair'); this.emit(`T::set_line(${L}); let ${p} = T::unpack2(${el}); ${id(a.py)} = ${p}.0; ${id(b.py)} = ${p}.1;`, L); }
        else this.emit(`T::set_line(${L}); ${id(a.py)} = ${el};`, L);
        this.block(s.body);
        this.ind--;
        this.emit('}');
        return;
      }
      case 'range': {
        const lo = this.fresh('from'), hi = this.fresh('to'), n = this.fresh('n');
        const to = s.to.k === 'num' && s.to.whole ? `T::int(${rs(String(BigInt(s.to.text.replace(/_/g, '')) + 1n))})` : `T::add(${this.x(s.to)}, T::int_n(1))`;
        const a = this.fresh('a'), b = this.fresh('b');
        this.line(L, `{ let ${a} = ${this.x(s.from)}; let ${b} = ${to}; let ${lo} = T::range_int(${a}); let ${hi} = T::range_int(${b});`);
        this.ind++;
        this.emit(`for ${n} in ${lo}..${hi} {`);
        this.ind++;
        this.emit(`T::set_line(${L}); ${id(s.v.py)} = T::int_n(${n});`, L);
        this.block(s.body);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      case 'while':
        this.emit(`while { T::set_line(${L}); ${s.until ? `!${this.yn(s.cond)}` : this.yn(s.cond)} } {`, L);
        this.ind++; this.block(s.body); this.ind--;
        this.emit('}');
        return;
      case 'times': {
        const count = this.fresh('count'), k = this.fresh('k');
        this.line(L, `{ let ${count} = T::range_int(${this.x(s.count)});`);
        this.ind++;
        this.emit(`for ${k} in 0..${count} {`);
        this.ind++;
        this.emit(`T::set_line(${L});`, L);
        this.block(s.body);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      case 'expect': this.expect(s); return;
      case 'add': case 'remove': this.addRemove(s); return;
      case 'increase': case 'decrease': {
        const op = s.k === 'increase' ? 'T::add' : 'T::sub';
        if (s.target.k === 'name') { const py = s.target.ref?.py ?? 'unknown'; this.assign(s, py, `${op}(${this.nameRef(py, s.target.ref)}, ${this.x(s.e)})`); return; }
        const v = this.fresh('v');
        this.line(L, `{ let ${v} = ${op}(${this.x(s.target)}, ${this.x(s.e)}); ${this.storeCode(s.target, v)} }`);
        return;
      }
      case 'sort': {
        const key = s.field ? `Some(T::key_with(Box::new(|item: Value| ${this.fieldGet('item', s.field)})))` : 'None';
        this.line(L, `T::sort_in_place(${this.x(s.target)}, ${key}, ${!!s.desc});`);
        return;
      }
      case 'reverse': this.line(L, `T::reverse_in_place(${this.x(s.target)});`); return;
      case 'do': this.line(L, `${this.x(s.e)};`); return;
      case 'tryFail': {
        const r = this.fresh('tried'), e = this.fresh('failure');
        this.emit(`let ${r} = T::catch(|| -> Option<Value> {`, L);
        this.ind++;
        this.tryDepth++;
        this.stmt(s.stmt);
        this.tryDepth--;
        this.emit('None');
        this.ind--;
        this.emit('});', L);
        this.emit(`match ${r} {`, L);
        this.ind++;
        this.emit(`Ok(Some(given)) => { ${this.tryDepth > 0 ? 'return Some(given);' : this.isVoid ? 'return;' : 'return given;'} }`);
        this.emit('Ok(None) => {}');
        this.emit(`Err(${e}) => {`);
        this.ind++;
        this.line(L, `${id(s.errPy)} = T::explain(${e});`);
        this.block(s.handler);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      default: this.emit(`// not generated: ${s.k}`, L);
    }
  }

  addRemove(s) {
    const L = s.line;
    const isName = s.target.k === 'name';
    const py = isName ? s.target.ref?.py ?? 'unknown' : null;
    const v = this.fresh('v'), t = this.fresh('t');
    const head = `let ${v} = ${this.x(s.e)}; let ${t} = ${this.x(s.target)};`;
    let body;
    if (s.targetKind === 'list') body = s.k === 'add' ? `T::append_to(${t}, ${v});` : `T::remove_from(${t}, ${v});`;
    else if (s.targetKind === 'map') body = `T::remove_from(${t}, ${v});`;
    else if (s.targetKind === 'number') {
      const nv = `${s.k === 'add' ? 'T::add' : 'T::sub'}(${t}, ${v})`;
      if (isName && s.rules?.length) {
        const n = this.fresh('new');
        this.line(L, `{ ${head} let ${n} = ${nv};`);
        this.ind++;
        for (const rule of s.rules) this.emit(`T::never(${this.x(rule.rule.cond, { subject: `${n}.clone()` })}, ${rs(rule.text)}, ${rule.line}, ${n}.clone());`, L);
        this.emit(`${id(py)} = ${n}; }`, L);
        this.ind--;
        this.rulesAfter(s, py);
        return;
      }
      body = isName ? `${id(py)} = ${nv};` : this.storeCode(s.target, nv);
    } else if (s.k === 'add') body = isName ? `${id(py)} = T::add_to(${t}, ${v});` : this.storeCode(s.target, `T::add_to(${t}, ${v})`);
    else body = `T::remove_from(${t}, ${v});`;
    this.line(L, `{ ${head} ${body} }`);
    if (isName) this.rulesAfter(s, py);
  }

  expect(s) {
    const L = s.line;
    const text = rs((s.raw ?? 'Expect').trim());
    if (s.mode === 'true') { this.line(L, `T::expect_true(${this.x(s.e)}, ${text});`); return; }
    if (s.mode === 'fail') {
      const m = this.fresh('msg');
      this.line(L, `{ let ${m} = ${s.msg ? this.x(s.msg) : 'T::NOTHING'}; T::expect_failure(|| { ${this.x(s.e)}; }, ${text}, ${m}); }`);
      return;
    }
    if (s.mode === 'cmp') { this.line(L, `T::expect_value(${this.x(s.e)}, "contains", "contains", ${this.x(s.want)}, ${text});`); return; }
    let c = s.check, negate = false;
    if (c.k === 'not') { negate = true; c = c.e; }
    const OPS = { '==': 'is', '!=': 'is not', '>=': 'at least', '<=': 'at most', '>': 'more than', '<': 'less than' };
    let op, want = 'T::NOTHING';
    if (c.k === 'cmp') { op = OPS[c.op]; want = this.x(c.r); }
    else if (c.k === 'adj') op = c.adj;
    else if (c.k === 'isNothing') op = c.neg ? 'not nothing' : 'nothing';
    else if (c.k === 'between') { op = 'between'; want = `T::list(vec![${this.x(c.lo)}, ${this.x(c.hi)}])`; }
    else if (c.k === 'contains') { op = 'in'; want = this.x(c.l); }
    else op = 'is';
    this.line(L, `T::expect_value(${this.x(s.e)}, ${rs(negate ? `not ${op}` : op)}, ${rs(op)}, ${want}, ${text});`);
  }

  fieldGet(v, field) { return field.dynamic ? `T::get_field(${v}, ${rs(field.key)})` : `T::get_attr(${v}, ${rs(field.py)})`; }

  /** A value used as yes/no: a Rust bool, checked when the program runs. */
  yn(e, ctx = {}) { return `T::yes_no(${this.x(e, ctx)})`; }

  /** A name's value: a kept value comes from its slot; a local or an input is cloned (values are shared, like Python's). */
  nameRef(py, ref) {
    if (ref?.kind === 'const' || (this.consts.has(py) && ref?.kind !== 'var' && ref?.kind !== 'param')) return `${keptFn(py)}()`;
    return `${id(py)}.clone()`;
  }

  /** A call to a Thunder function, with the inputs it leaves out filled in (as Python's defaults do). */
  callCode(e, sub) {
    const f = this.funcs.get(e.py);
    const args = e.args.map(sub);
    if (f && args.length < f.params.length) {
      for (const p of f.params.slice(args.length)) args.push(p.dflt?.k === 'name' ? 'T::NOT_GIVEN' : p.dflt ? this.x(p.dflt) : 'T::NOTHING');
    }
    return `${id(e.py)}(${args.join(', ')})`;
  }

  x(e, ctx = {}) {
    const sub = (k) => this.x(k, ctx);
    switch (e.k) {
      case 'num': return e.whole ? `T::int(${rs(String(BigInt(e.text.replace(/_/g, ''))))})` : `T::dec(${rs(e.text)})`;
      case 'money': return `T::money(${rs(e.text)})`;
      case 'percent': return `T::dec(${rs(percentDecimal(e.text))})`;
      case 'bool': return `T::yes(${e.v ? 'true' : 'false'})`;
      case 'nothing': case 'hole': return 'T::NOTHING';
      case 'paren': return sub(e.e);
      case 'today': return 'T::today()';
      case 'date': return `T::date(${rs(e.text)})`;
      case 'str': return this.str(e, ctx);
      case 'list': return e.items ? `T::list(vec![${e.items.map(sub).join(', ')}])` : 'T::new_map()';
      case 'map': return 'T::new_map()';
      case 'name': {
        const r = e.ref ?? {};
        if (r.kind === 'subject') return ctx.subject ?? 'T::NOTHING';
        if (r.kind === 'elemField') return `T::get_attr(${ctx.item}, ${rs(r.py)})`;
        if (r.kind === 'elemKey') return `T::get_field(${ctx.item}, ${rs(r.key)})`;
        if (r.kind === 'elem') return ctx.item;
        return this.nameRef(r.py ?? e.name.replace(/ /g, '_'), r);
      }
      case 'call': return this.callCode(e, sub);
      case 'new': return `T::new_record(${kindFn(e.py)}(), vec![${e.fields.map((f) => `(${rs(f.py)}, ${sub(f.e)})`).join(', ')}])`;
      case 'field': return e.static ? `T::get_attr(${sub(e.obj)}, ${rs(e.py)})` : `T::get_field(${sub(e.obj)}, ${rs(e.text)})`;
      case 'at': {
        const fn = e.objKind === 'map' ? 'T::map_get' : e.objKind === 'list' ? 'T::item_at' : 'T::entry';
        return `${fn}(${sub(e.obj)}, ${sub(e.key)}, ${e.dflt ? `Some(${sub(e.dflt)})` : 'None'})`;
      }
      case 'conv': {
        const fn = { list: 'T::py_list', number: 'T::to_number', whole: 'T::to_whole', money: 'T::to_money', text: 'T::show', bool: 'T::to_yes_no', date: 'T::to_date' }[e.to];
        return fn ? `${fn}(${sub(e.e)})` : sub(e.e);
      }
      case 'where': {
        const v = this.fresh('item');
        return `T::list(T::py_iter(${sub(e.list)}).into_iter().filter(|${v}: &Value| T::truthy(&${this.x(e.cond, { ...ctx, item: `${v}.clone()` })})).collect())`;
      }
      case 'from': {
        const inner = e.list.k === 'where' ? e.list : null;
        const v = this.fresh('item');
        const list = `T::py_iter(${sub(inner ? inner.list : e.list)}).into_iter()`;
        const filtered = inner ? `${list}.filter(|${v}: &Value| T::truthy(&${this.x(inner.cond, { ...ctx, item: `${v}.clone()` })}))` : list;
        return `T::list(${filtered}.map(|${v}: Value| ${this.fieldGet(v, e.field)}).collect())`;
      }
      case 'sorted': {
        if (e.mapSort) return `T::py_sort(T::list(T::map_items(${sub(e.list)})), Some(T::key_with(Box::new(|entry: Value| T::tuple_at(entry, ${e.by === 'key' ? 0 : 1})))), ${!!e.desc})`;
        return `T::py_sort(T::py_list(${sub(e.list)}), Some(T::key_with(Box::new(|item: Value| ${this.fieldGet('item', e.field)}))), ${!!e.desc})`;
      }
      case 'op': return `T::apply_op(${rs(e.op)}, ${sub(e.arg)})`;
      case 'round': return `T::round_to(${sub(e.e)}, ${e.places ? sub(e.places) : 'T::int_n(0)'})`;
      case 'readFile': return `T::read_text(${sub(e.path)})`;
      case 'neg': return `T::neg(${sub(e.e)})`;
      case 'not': return `T::yes(!${this.yn(e.e, ctx)})`;
      case 'bin': {
        if (e.op === 'and') return `T::yes(${this.yn(e.l, ctx)} && ${this.yn(e.r, ctx)})`;
        if (e.op === 'or') return `T::yes(${this.yn(e.l, ctx)} || ${this.yn(e.r, ctx)})`;
        const fn = { '+': 'T::add', '-': 'T::sub', '*': 'T::mul', '/': 'T::divide' }[e.op]
          ?? (e.op === 'mod' ? (e.l.type?.k === 'whole' && e.r.type?.k === 'whole' ? 'T::int_mod' : 'T::modulo') : null);
        return fn ? `${fn}(${sub(e.l)}, ${sub(e.r)})` : 'T::NOTHING';
      }
      case 'cmp': {
        if (e.r.k === 'bool' && (e.op === '==' || e.op === '!=')) return `T::yes(${this.yn(e.l, ctx)} ${e.op === '==' ? '==' : '!='} ${e.r.v ? 'true' : 'false'})`;
        return `T::compare(${rs(e.op)}, ${sub(e.l)}, ${sub(e.r)})`;
      }
      case 'between': return `T::between(${sub(e.lo)}, ${sub(e.e)}, || ${sub(e.hi)})`;
      case 'contains': return `T::is_in(${sub(e.r)}, ${sub(e.l)})`;
      case 'affix': return `T::affix(${sub(e.l)}, ${sub(e.r)}, ${!!e.end})`;
      case 'sortedValues': return `T::py_sort(T::py_list(${sub(e.list)}), None, ${!!e.desc})`;
      case 'joined': return `T::joined(${sub(e.list)}, ${sub(e.sep)})`;
      case 'splitAt': return `T::split_at(${sub(e.text)}, ${sub(e.sep)})`;
      case 'replacing': return `T::replacing(${sub(e.text)}, ${sub(e.from)}, ${sub(e.to)})`;
      case 'adj': {
        if (e.adj === 'empty') return `T::eq(T::len_of(${sub(e.e)}), T::int_n(0))`;
        return `T::compare(${rs({ positive: '>', negative: '<', zero: '==' }[e.adj])}, ${sub(e.e)}, T::int_n(0))`;
      }
      case 'isNothing': return `T::yes(${e.neg ? '!' : ''}T::is_nothing(${sub(e.e)}))`;
      default: return `T::NOTHING /* not generated: ${e.k} */`;
    }
  }

  /** Text with {holes}: text and whole numbers as they are, anything else shown the Thunder way. */
  str(e, ctx) {
    const parts = e.parts.filter((p) => p !== '').map((p) => {
      if (typeof p === 'string') return `T::text(${rs(p)})`;
      const t = p.e.type?.k;
      return t === 'text' || t === 'whole' ? `T::py_str(${this.x(p.e, ctx)})` : `T::show(${this.x(p.e, ctx)})`;
    });
    if (!parts.length) return 'T::text("")';
    return parts.length === 1 && parts[0].startsWith('T::text(') ? parts[0] : `T::cat(vec![${parts.join(', ')}])`;
  }
}
