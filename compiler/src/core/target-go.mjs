// Thunder Core -> Go (one `main` package; standard library only).
//
// The same checked program the Python target, the Thunder engine, and the TypeScript target use (compileCore ->
// program + info), and the same meaning: every statement does what the TypeScript target writes for it, and every
// operation calls thunder/thunder_runtime.go, a Go port of the engine's own value code (engine-values.mjs).
// compiler/test/core-engines.mjs runs every Core test program on Python, the Thunder engine, TypeScript, and Go, and
// requires the same output from all of them.
//
// Every generated statement sets the frame's line (F.Line = N) and ends with `// thunder:N`, the Thunder line it came
// from, so an error says which Thunder line failed, exactly as the other targets do. A Thunder error is a Go panic
// with a *T.Err; each frame records where it happened on the way out (defer T.Exit(recover())).

import { percentDecimal } from './target-python.mjs';
import { firstLine } from './target-typescript.mjs';

/** A Go string literal for any text. */
export function goStr(s) {
  let out = '"';
  for (const ch of String(s)) {
    const cp = ch.codePointAt(0);
    if (ch === '"') out += '\\"';
    else if (ch === '\\') out += '\\\\';
    else if (ch === '\n') out += '\\n';
    else if (ch === '\r') out += '\\r';
    else if (ch === '\t') out += '\\t';
    else if (cp < 0x20 || cp === 0x7f) out += `\\x${cp.toString(16).padStart(2, '0')}`;
    else if (cp >= 0xd800 && cp <= 0xdfff) out += '\\uFFFD';
    else out += ch;
  }
  return `${out}"`;
}

// Go's keywords and the names the generated code or Go itself owns.
const RESERVED = new Set(('break case chan const continue default defer else fallthrough for func go goto if import interface map package range return select struct switch type var '
  + 'T F main init append cap close complex copy delete imag len make new panic print println real recover bool byte error float32 float64 int int8 int16 int32 int64 rune string uint uint8 uint16 uint32 uint64 uintptr true false nil iota any comparable').split(' '));
/** A Go name for a Thunder (Python) name: the same, unless Go or the generated code owns it. */
export const id = (py) => (RESERVED.has(py) || /^_/.test(py) ? `${py}_` : py);

const KNOWN_BOOL = new Set(['cmp', 'contains', 'between', 'adj', 'isNothing', 'not', 'bool']);

/** Thunder modules a program uses that only Python has (Use): compiled Go cannot call them. */
export function pythonOnlyUses(info) {
  return (info.modules ?? []).filter((m) => !info.imported?.has(m) && (m.ecosystem ?? 'python') === 'python').map((m) => ({ module: m.module, line: m.line }));
}

/**
 * Compile one checked file to the text of <module>.go. `ns` names every module-level thing in the program:
 * ns.name(py) -> the Go name (records, functions, kept values this file defines or sees), ns.params(py) -> how many
 * inputs a function takes.
 */
export function toGo(program, info, { source = 'main.thunder', module = 'main', ns }) {
  return new Gen(program, info, source, module, ns).module();
}

class Gen {
  constructor(program, info, source, module, ns) {
    this.p = program; this.info = info; this.source = source; this.mod = module; this.ns = ns;
    this.out = []; this.ind = 0; this.tmp = 0;
    this.file = `file_${module}`;
    this.scope = new Set(); // the names of the function being written (its inputs and locals)
    this.closures = []; // the "If this fails" closures a Give is inside (innermost last): { ret, flag, isVoid }
  }
  emit(text, line) { this.out.push(`${'\t'.repeat(this.ind)}${text}${line ? `  // thunder:${line}` : ''}`); }
  blank() { if (this.out.length && this.out[this.out.length - 1] !== '') this.out.push(''); }
  fresh(base) { return `_${base}${++this.tmp}`; }
  g(py) { return this.ns.name(py); }

  module() {
    const own = (s) => !this.info.imported?.has(s);
    const head = [
      `// Generated by the Thunder compiler from ${this.source}.`,
      `// A build artifact: change ${this.source.split('/').pop()} and build again, or keep this file and edit it as Go.`,
      '// It needs only Go and thunder/thunder_runtime.go (written next to it). "// thunder:N" marks the Thunder line.',
      '',
      'package main',
      '',
      'import T "thunderprogram/thunder"',
      '',
      `const ${this.file} = ${goStr(this.source)}`,
    ];
    const records = this.info.records.filter(own);
    for (const r of records) { this.blank(); this.record(r); }
    const ruled = records.filter((r) => (r.rulesToCheck ?? []).length);
    if (ruled.length) {
      this.blank();
      this.emit('func init() {');
      this.ind++;
      for (const r of ruled) this.recordRules(r);
      this.ind--;
      this.emit('}');
    }
    for (const f of this.info.funcs.filter(own)) { this.blank(); this.func(f); }
    // Stored lists: filled from data/<name>.json when the program runs, saved when it finishes well (runtime Run).
    const stores = (this.info.stores ?? []).filter(own);
    if (stores.length) {
      this.blank();
      const kind = (t) => (t.k === 'optional' ? `?${kind(t.of)}` : t.k);
      for (const s of stores) this.emit(`var ${this.g(s.py)} = T.NewStore(${this.file}, ${s.line}, ${goStr(s.py.toLowerCase())}, ${this.g(s.record.py)}, []T.StoreField{${s.record.fields.map((f) => `{Py: ${goStr(f.py)}, Kind: ${goStr(kind(f.type))}}`).join(', ')}})`, s.line);
    }
    const consts = this.info.consts.filter(own);
    this.blank();
    for (const k of consts) this.emit(`var ${this.g(k.py)} T.V`, k.line);
    this.emit(`// The kept values of ${this.source}, worked out when the program starts.`);
    this.emit(`func keep_${this.mod}() {`);
    this.ind++;
    if (consts.length) {
      this.emit(`T.Init(${this.file}, func(F *T.Frame) {`);
      this.ind++;
      for (const k of consts) this.emit(`F.Line = ${k.line}; ${this.g(k.py)} = ${this.x(k.e)}`, k.line);
      this.ind--;
      this.emit('})');
    }
    this.ind--;
    this.emit('}');
    const tests = this.info.tests;
    for (const t of tests) {
      this.blank();
      this.emit(`func ${this.testName(t)}() {`, t.line);
      this.ind++;
      this.frameBody(`T.EnterFrame(${this.file}, ${t.line})`, t.body, [], true);
      this.ind--;
      this.emit('}');
    }
    this.blank();
    this.emit(`var tests_${this.mod} = []T.Test{`);
    for (const t of tests) this.emit(`\t{Title: ${goStr(t.title)}, Run: ${this.testName(t)}, Line: ${t.line}},`);
    this.emit('}');
    const main = this.p.main ?? [];
    this.blank();
    this.emit(`func main_${this.mod}() {`);
    this.ind++;
    if (main.length) this.frameBody(`T.EnterFrame(${this.file}, 0)`, main, [], true);
    this.ind--;
    this.emit('}');
    this.blank();
    this.emit('var _ = T.I');
    return `${head.join('\n')}\n${this.out.join('\n').replace(/\n{3,}/g, '\n\n')}\n`;
  }

  testName(t) { return `test_${this.mod}_${t.py.replace(/^test_/, '')}`; }

  record(r) {
    const fields = r.fields.map((f) => `{Py: ${goStr(f.py)}, Kind: ${goStr(f.type?.k ?? 'any')}}`).join(', ');
    this.emit(`var ${this.g(r.py)} = T.Kind(${goStr(r.py)}, []T.Field{${fields}}, nil)`, r.line);
  }

  recordRules(r) {
    const bySubject = new Map();
    for (const rule of r.rulesToCheck) { const f = r.fieldMap.get(rule.subject); (bySubject.get(f.py) ?? bySubject.set(f.py, []).get(f.py)).push(rule); }
    for (const [field, rs] of bySubject) {
      this.emit(`${this.g(r.py)}.Rules[${goStr(field)}] = []T.Rule{`);
      this.ind++;
      for (const rule of rs) this.emit(`{Cond: func(value T.V) T.V { F := T.TopFrame(); _ = F; return ${this.x(rule.rule.cond, { subject: 'value' })} }, Text: ${goStr(rule.text)}, Line: ${rule.line}},`, rule.line);
      this.ind--;
      this.emit('}');
    }
  }

  func(f) {
    this.emit(`func ${this.g(f.py)}(${f.params.map((p) => `${id(p.py)} T.V`).join(', ')}) T.V {`, f.line);
    this.ind++;
    this.scope = new Set(f.params.map((p) => p.py));
    const pre = [];
    // A default: filled in when a call leaves the input out (T.NotGiven). A kept value is read when the call
    // happens, at its line (it may be written further down the file); a fixed value can't fail.
    for (const p of f.params) {
      if (!p.dflt) continue;
      pre.push(p.dflt.k === 'name'
        ? [`if ${id(p.py)} == T.NotGiven { F.Line = ${p.line}; ${id(p.py)} = ${this.x(p.dflt)} }`, p.line]
        : [`if ${id(p.py)} == T.NotGiven { ${id(p.py)} = ${this.x(p.dflt)} }`, null]);
    }
    for (const p of f.params) for (const rule of p.rules ?? []) pre.push([`F.Line = ${p.line}; T.Never(${this.x(rule.rule.cond, { subject: id(p.py) })}, ${goStr(rule.text)}, ${rule.line}, ${id(p.py)})`, p.line]);
    const first = firstLine(f);
    this.frameBody(`T.EnterCall(${this.file}, ${f.line}, ${first ?? 0})`, f.body, pre, false, f.params.map((p) => p.py));
    this.ind--;
    this.emit('}');
  }

  /** A body that runs in its own frame: an error leaves with the Thunder line it happened on. */
  frameBody(enter, body, pre, isVoid, params = []) {
    this.emit(`F := ${enter}`);
    this.emit('defer func() { T.Exit(recover()) }()');
    this.emit('_ = F');
    const locals = [...this.localsOf(body)].filter((n) => !params.includes(n));
    this.scope = new Set([...params, ...locals]);
    if (locals.length) {
      this.emit(`var ${locals.map(id).join(', ')} T.V`);
      this.emit(`${locals.map(() => '_').join(', ')} = ${locals.map(id).join(', ')}`);
    }
    for (const [code, line] of pre) this.emit(code, line);
    this.block(body, isVoid);
    if (!isVoid) this.emit('return nil');
    this.scope = new Set();
  }

  /** The names a body assigns (Python's locals): declared once at the top, as a Python function's are. */
  localsOf(body) {
    const names = new Set();
    const visit = (ss) => {
      for (const s of ss ?? []) {
        if (s.k === 'set' && s.target.k === 'name' && s.target.ref?.py) names.add(s.target.ref.py);
        for (const v of s.vars ?? []) if (v?.py) names.add(v.py);
        if (s.k === 'range' && s.v?.py) names.add(s.v.py);
        if (s.errPy) names.add(s.errPy);
        visit(s.body); visit(s.handler); visit(s.otherwise);
        for (const b of s.branches ?? []) visit(b.body);
        if (s.stmt) visit([s.stmt]);
      }
    };
    visit(body);
    const globals = new Set([...this.info.consts, ...(this.info.stores ?? []), ...this.info.funcs, ...this.info.records].map((x) => x.py));
    return [...names].filter((n) => !globals.has(n));
  }

  /** A local name, or a module-level one (a kept value). */
  nameOf(py) { return !this.scope.has(py) && this.ns.has(py) ? this.g(py) : id(py); }

  block(body, isVoid) { for (const s of body) this.stmt(s, isVoid); }

  /** F.Line = N; <code>  // thunder:N */
  line(L, code) { this.emit(`F.Line = ${L}; ${code}`, L); }

  /** Give: return from the function, or (inside an "If this fails" closure) remember the value and leave it. */
  giveCode(valueCode, isVoid) {
    const c = this.closures[this.closures.length - 1];
    if (!c) return isVoid ? 'return' : `return ${valueCode}`;
    return isVoid ? `${c.flag} = true; return` : `${c.ret} = ${valueCode}; ${c.flag} = true; return`;
  }

  /** Check a watched name's Never rules on its new value, then store it. */
  assign(s, name, valueCode) {
    const target = this.nameOf(name);
    if (!s.rules?.length) { this.line(s.line, `${target} = ${valueCode}`); return; }
    const v = this.fresh('new');
    this.line(s.line, `{ ${v} := ${valueCode}`);
    this.ind++;
    for (const rule of s.rules) this.emit(`T.Never(${this.x(rule.rule.cond, { subject: v })}, ${goStr(rule.text)}, ${rule.line}, ${v})`, s.line);
    this.emit(`${target} = ${v} }`, s.line);
    this.ind--;
  }
  rulesAfter(s, name) {
    for (const rule of s.rules ?? []) this.emit(`T.Never(${this.x(rule.rule.cond, { subject: this.nameOf(name) })}, ${goStr(rule.text)}, ${rule.line}, ${this.nameOf(name)})`, s.line);
  }

  /** Code that stores `v` (a name of generated code) into a name, a field, or an entry. */
  storeCode(t, v) {
    if (t.k === 'name') return `${this.nameOf(t.ref?.py ?? 'unknown')} = ${v}`;
    if (t.k === 'field') return t.static ? `T.SetAttr(${this.x(t.obj)}, ${goStr(t.py)}, ${v})` : `T.SetField(${this.x(t.obj)}, ${goStr(t.text)}, ${v})`;
    if (t.k === 'at') {
      const fn = t.objKind === 'list' ? 'T.SetItem' : t.objKind === 'map' ? 'T.MapSet' : 'T.SetEntry';
      return `${fn}(${this.x(t.obj)}, ${this.x(t.key)}, ${v})`;
    }
    return '';
  }

  stmt(s, isVoid) {
    const L = s.line;
    switch (s.k) {
      case 'say': this.line(L, `T.Say(${s.e.type?.k === 'text' ? `T.Str(${this.x(s.e)})` : `T.Shown(${this.x(s.e)})`})`); return;
      case 'set': {
        const t = s.target;
        if (t.k === 'name') { this.assign(s, t.ref.py, this.x(s.e)); return; }
        const v = this.fresh('v');
        this.line(L, `{ ${v} := ${this.x(s.e)}; ${this.storeCode(t, v)} }`);
        return;
      }
      case 'give': this.line(L, this.giveCode(s.e.k === 'nothing' ? 'nil' : this.x(s.e), isVoid)); return;
      case 'stop': { const v = this.x(s.e); this.line(L, `panic(T.Stop(${s.e.type?.k === 'text' ? `T.Str(${v})` : `T.Shown(${v})`}))`); return; }
      case 'if': {
        this.emit(`F.Line = ${L}`, L);
        s.branches.forEach((b, k) => {
          this.emit(`${k === 0 ? 'if' : '} else if'} F.Line = ${b.line}; ${this.yn(b.cond)} {`, b.line);
          this.ind++; this.block(b.body, isVoid); this.ind--;
        });
        if (s.otherwise) { this.emit('} else {'); this.ind++; this.block(s.otherwise, isVoid); this.ind--; }
        this.emit('}');
        return;
      }
      case 'each': {
        const [a, b] = s.vars;
        const it = this.x(s.iter);
        const seq = b ? (s.iterKind === 'map' ? `T.MapItems(${it})` : s.iterKind === 'pairs' ? it : `T.PairsOf(${it})`) : it;
        const iter = this.fresh('it'), k = this.fresh('k'), el = this.fresh('el'), ok = this.fresh('ok');
        this.line(L, `${iter} := T.PyIter(${seq})`);
        this.emit(`for ${k} := 0; ; ${k}++ {`);
        this.ind++;
        this.emit(`${el}, ${ok} := ${iter}.Next(${k})`);
        this.emit(`if !${ok} { break }`);
        this.emit(b ? `F.Line = ${L}; ${this.nameOf(a.py)}, ${this.nameOf(b.py)} = T.Unpack2(${el})` : `F.Line = ${L}; ${this.nameOf(a.py)} = ${el}`, L);
        this.block(s.body, isVoid);
        this.ind--;
        this.emit('}');
        return;
      }
      case 'range': {
        const lo = this.fresh('from'), hi = this.fresh('to'), n = this.fresh('n');
        const to = s.to.k === 'num' && s.to.whole ? this.wholeLit(BigInt(s.to.text.replace(/_/g, '')) + 1n) : `T.Add(${this.x(s.to)}, T.I(1))`;
        const a = this.fresh('a'), b = this.fresh('b');
        this.line(L, `{ ${a} := ${this.x(s.from)}; ${b} := ${to}; ${lo} := T.RangeInt(${a}); ${hi} := T.RangeInt(${b})`);
        this.ind++;
        this.emit(`for ${n} := ${lo}; ${n} < ${hi}; ${n}++ {`);
        this.ind++;
        this.emit(`F.Line = ${L}; ${this.nameOf(s.v.py)} = T.I(${n})`, L);
        this.block(s.body, isVoid);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      case 'while':
        this.emit('for {', L);
        this.ind++;
        this.emit(`F.Line = ${L}; if !(${s.until ? `!(${this.yn(s.cond)})` : this.yn(s.cond)}) { break }`, L);
        this.block(s.body, isVoid);
        this.ind--;
        this.emit('}');
        return;
      case 'times': {
        const count = this.fresh('count'), k = this.fresh('k');
        this.line(L, `{ ${count} := T.RangeInt(${this.x(s.count)})`);
        this.ind++;
        this.emit(`for ${k} := int64(0); ${k} < ${count}; ${k}++ {`);
        this.ind++;
        this.emit(`F.Line = ${L}`, L);
        this.block(s.body, isVoid);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      case 'expect': this.expect(s); return;
      case 'add': case 'remove': this.addRemove(s); return;
      case 'increase': case 'decrease': {
        const op = s.k === 'increase' ? 'T.Add' : 'T.Sub';
        if (s.target.k === 'name') { const py = s.target.ref?.py ?? 'unknown'; this.assign(s, py, `${op}(${this.nameOf(py)}, ${this.x(s.e)})`); return; }
        const v = this.fresh('v');
        this.line(L, `{ ${v} := ${op}(${this.x(s.target)}, ${this.x(s.e)}); ${this.storeCode(s.target, v)} }`);
        return;
      }
      case 'sort': {
        const key = s.field ? `T.KeyAt(F, func(item T.V) T.V { return ${this.fieldGet('item', s.field)} })` : 'nil';
        this.line(L, `T.SortInPlace(${this.x(s.target)}, ${key}, ${!!s.desc})`);
        return;
      }
      case 'reverse': this.line(L, `T.ReverseInPlace(${this.x(s.target)})`); return;
      case 'do': this.line(L, `_ = ${this.x(s.e)}`); return;
      case 'tryFail': {
        const ret = this.fresh('ret'), flag = this.fresh('gave'), failure = this.fresh('failure');
        this.emit(`{ var ${ret} T.V; ${flag} := false; _ = ${ret}`, L);
        this.ind++;
        this.emit(`${failure} := T.Try(func() {`, L);
        this.ind++;
        this.closures.push({ ret, flag });
        this.stmt(s.stmt, isVoid);
        this.closures.pop();
        this.ind--;
        this.emit('})');
        this.emit(`if ${flag} { ${this.giveCode(ret, isVoid)} }`);
        this.emit(`if ${failure} != nil {`);
        this.ind++;
        this.line(L, `${this.nameOf(s.errPy)} = T.Explain(${failure})`);
        this.block(s.handler, isVoid);
        this.ind--;
        this.emit('}');
        this.ind--;
        this.emit('}');
        return;
      }
      default: this.emit(`// not generated: ${s.k}`, L);
    }
  }

  addRemove(s) {
    const L = s.line;
    const isName = s.target.k === 'name';
    const py = isName ? s.target.ref?.py ?? 'unknown' : null;
    const v = this.fresh('v'), t = this.fresh('t');
    const head = `${v} := ${this.x(s.e)}; ${t} := ${this.x(s.target)}`;
    let body;
    if (s.targetKind === 'list') body = s.k === 'add' ? `T.AppendTo(${t}, ${v})` : `T.RemoveFrom(${t}, ${v})`;
    else if (s.targetKind === 'map') body = `T.RemoveFrom(${t}, ${v})`;
    else if (s.targetKind === 'number') {
      const nv = `${s.k === 'add' ? 'T.Add' : 'T.Sub'}(${t}, ${v})`;
      if (isName && s.rules?.length) {
        const n = this.fresh('new');
        this.line(L, `{ ${head}; ${n} := ${nv}`);
        this.ind++;
        for (const rule of s.rules) this.emit(`T.Never(${this.x(rule.rule.cond, { subject: n })}, ${goStr(rule.text)}, ${rule.line}, ${n})`, L);
        this.emit(`${this.nameOf(py)} = ${n} }`, L);
        this.ind--;
        this.rulesAfter(s, py);
        return;
      }
      body = isName ? `${this.nameOf(py)} = ${nv}` : this.storeCode(s.target, nv);
    } else if (s.k === 'add') body = isName ? `${this.nameOf(py)} = T.AddTo(${t}, ${v})` : this.storeCode(s.target, `T.AddTo(${t}, ${v})`);
    else body = `T.RemoveFrom(${t}, ${v})`;
    this.line(L, `{ ${head}; ${body} }`);
    if (isName) this.rulesAfter(s, py);
  }

  expect(s) {
    const L = s.line;
    const text = goStr((s.raw ?? 'Expect').trim());
    if (s.mode === 'true') { this.line(L, `T.ExpectTrue(${this.x(s.e)}, ${text})`); return; }
    if (s.mode === 'fail') {
      const m = this.fresh('msg');
      this.line(L, `{ var ${m} T.V = ${s.msg ? this.x(s.msg) : 'nil'}; T.ExpectFailure(func() { _ = ${this.x(s.e)} }, ${text}, ${m}) }`);
      return;
    }
    if (s.mode === 'cmp') { this.line(L, `T.ExpectValue(${this.x(s.e)}, "contains", "contains", ${this.x(s.want)}, ${text})`); return; }
    let c = s.check, negate = false;
    if (c.k === 'not') { negate = true; c = c.e; }
    const OPS = { '==': 'is', '!=': 'is not', '>=': 'at least', '<=': 'at most', '>': 'more than', '<': 'less than' };
    let op, want = 'nil';
    if (c.k === 'cmp') { op = OPS[c.op]; want = this.x(c.r); }
    else if (c.k === 'adj') op = c.adj;
    else if (c.k === 'isNothing') op = c.neg ? 'not nothing' : 'nothing';
    else if (c.k === 'between') { op = 'between'; want = `T.NewList(${this.x(c.lo)}, ${this.x(c.hi)})`; }
    else if (c.k === 'contains') { op = 'in'; want = this.x(c.l); }
    else op = 'is';
    this.line(L, `T.ExpectValue(${this.x(s.e)}, ${goStr(negate ? `not ${op}` : op)}, ${goStr(op)}, ${want}, ${text})`);
  }

  fieldGet(v, field) { return field.dynamic ? `T.GetField(${v}, ${goStr(field.key)})` : `T.GetAttr(${v}, ${goStr(field.py)})`; }

  /** A value used as yes/no: a Go condition. Values that are not known to be yes/no are checked when it runs. */
  yn(e, ctx = {}) {
    const c = this.x(e, ctx);
    const known = KNOWN_BOOL.has(e.k) || (e.k === 'bin' && (e.op === 'and' || e.op === 'or'));
    return known ? c : `T.YesNo(${c})`;
  }

  wholeLit(n) {
    const big = BigInt(n);
    return big >= -(2n ** 63n) && big < 2n ** 63n ? `T.I(${big})` : `T.Int(${goStr(big.toString())})`;
  }

  x(e, ctx = {}) {
    const sub = (k) => this.x(k, ctx);
    switch (e.k) {
      case 'num': return e.whole ? this.wholeLit(BigInt(e.text.replace(/_/g, ''))) : `T.D(${goStr(e.text)})`;
      case 'money': return `T.M(${goStr(e.text)})`;
      case 'percent': return `T.D(${goStr(percentDecimal(e.text))})`;
      case 'bool': return e.v ? 'true' : 'false';
      case 'nothing': case 'hole': return 'nil';
      case 'paren': return sub(e.e);
      case 'today': return 'T.Today()';
      case 'date': return `T.DateOf(${goStr(e.text)})`;
      case 'str': return this.str(e, ctx);
      case 'list': return e.items ? `T.NewList(${e.items.map(sub).join(', ')})` : 'T.NewMap()';
      case 'map': return 'T.NewMap()';
      case 'name': {
        const r = e.ref ?? {};
        if (r.kind === 'subject') return ctx.subject ?? 'nil';
        if (r.kind === 'elemField') return `T.GetAttr(${ctx.item}, ${goStr(r.py)})`;
        if (r.kind === 'elemKey') return `T.GetField(${ctx.item}, ${goStr(r.key)})`;
        if (r.kind === 'elem') return ctx.item;
        return this.nameOf(r.py ?? e.name.replace(/ /g, '_'));
      }
      case 'call': {
        const args = e.args.map(sub);
        const n = this.ns.params(e.py);
        while (n != null && args.length < n) args.push('T.NotGiven');
        return `${this.g(e.py)}(${args.join(', ')})`;
      }
      case 'new': return `T.NewRecord(${this.g(e.py)}${e.fields.map((f) => `, T.Pair{Py: ${goStr(f.py)}, V: ${sub(f.e)}}`).join('')})`;
      case 'field': return e.static ? `T.GetAttr(${sub(e.obj)}, ${goStr(e.py)})` : `T.GetField(${sub(e.obj)}, ${goStr(e.text)})`;
      case 'at': {
        const fn = e.objKind === 'map' ? 'T.MapGet' : e.objKind === 'list' ? 'T.ItemAt' : 'T.Entry';
        return `${fn}(${sub(e.obj)}, ${sub(e.key)}${e.dflt ? `, ${sub(e.dflt)}` : ''})`;
      }
      case 'conv': {
        const fn = { list: 'T.PyList', number: 'T.ToNumber', whole: 'T.ToWhole', money: 'T.ToMoney', text: 'T.Shown', bool: 'T.ToYesNo', date: 'T.ToDate' }[e.to];
        return fn ? `${fn}(${sub(e.e)})` : sub(e.e);
      }
      case 'where': {
        const v = this.fresh('item');
        return `T.Filter(${sub(e.list)}, func(${v} T.V) bool { return T.Truthy(${this.x(e.cond, { ...ctx, item: v })}) })`;
      }
      case 'from': {
        const inner = e.list.k === 'where' ? e.list : null;
        const v = this.fresh('item');
        const list = sub(inner ? inner.list : e.list);
        const filtered = inner ? `T.Filter(${list}, func(${v} T.V) bool { return T.Truthy(${this.x(inner.cond, { ...ctx, item: v })}) })` : list;
        const w = this.fresh('item');
        return `T.Pick(${filtered}, func(${w} T.V) T.V { return ${this.fieldGet(w, e.field)} })`;
      }
      case 'sorted': {
        if (e.mapSort) return `T.PySort(T.MapItems(${sub(e.list)}), T.KeyAt(F, func(entry T.V) T.V { return T.EntryAt(entry, ${e.by === 'key' ? 0 : 1}) }), ${!!e.desc})`;
        return `T.PySort(T.PyList(${sub(e.list)}), T.KeyAt(F, func(item T.V) T.V { return ${this.fieldGet('item', e.field)} }), ${!!e.desc})`;
      }
      case 'op': return `T.ApplyOp(${goStr(e.op)}, ${sub(e.arg)})`;
      case 'round': return `T.RoundTo(${sub(e.e)}${e.places ? `, ${sub(e.places)}` : ''})`;
      case 'readFile': return `T.ReadText(${sub(e.path)})`;
      case 'neg': return `T.Neg(${sub(e.e)})`;
      case 'not': return `!${this.yn(e.e, ctx)}`;
      case 'bin': {
        if (e.op === 'and') return `(${this.yn(e.l, ctx)} && ${this.yn(e.r, ctx)})`;
        if (e.op === 'or') return `(${this.yn(e.l, ctx)} || ${this.yn(e.r, ctx)})`;
        const fn = { '+': 'T.Add', '-': 'T.Sub', '*': 'T.Mul', '/': 'T.Divide' }[e.op]
          ?? (e.op === 'mod' ? (e.l.type?.k === 'whole' && e.r.type?.k === 'whole' ? 'T.IntMod' : 'T.Modulo') : null);
        return fn ? `${fn}(${sub(e.l)}, ${sub(e.r)})` : 'nil';
      }
      case 'cmp': {
        if (e.r.k === 'bool' && (e.op === '==' || e.op === '!=')) return `(${this.yn(e.l, ctx)} ${e.op} ${sub(e.r)})`;
        return `T.Compare(${goStr(e.op)}, ${sub(e.l)}, ${sub(e.r)})`;
      }
      case 'between': return `T.Between(${sub(e.lo)}, ${sub(e.e)}, func() T.V { return ${sub(e.hi)} })`;
      case 'contains': return `T.IsIn(${sub(e.r)}, ${sub(e.l)})`;
      case 'affix': return `T.Affix(${sub(e.l)}, ${sub(e.r)}, ${!!e.end})`;
      case 'sortedValues': return `T.PySort(T.PyList(${sub(e.list)}), nil, ${!!e.desc})`;
      case 'joined': return `T.Joined(${sub(e.list)}, ${sub(e.sep)})`;
      case 'splitAt': return `T.SplitAt(${sub(e.text)}, ${sub(e.sep)})`;
      case 'replacing': return `T.Replacing(${sub(e.text)}, ${sub(e.from)}, ${sub(e.to)})`;
      case 'adj': {
        if (e.adj === 'empty') return `T.Eq(T.PyLen(${sub(e.e)}), T.I(0))`;
        return `T.Compare(${goStr({ positive: '>', negative: '<', zero: '==' }[e.adj])}, ${sub(e.e)}, T.I(0))`;
      }
      case 'isNothing': return `${e.neg ? '!' : ''}T.IsNothing(${sub(e.e)})`;
      default: return `nil /* not generated: ${e.k} */`;
    }
  }

  /** Text with {holes}: text and whole numbers as they are, anything else shown the Thunder way. */
  str(e, ctx) {
    const parts = e.parts.filter((p) => p !== '').map((p) => {
      if (typeof p === 'string') return goStr(p);
      const t = p.e.type?.k;
      return t === 'text' || t === 'whole' ? `T.Str(${this.x(p.e, ctx)})` : `T.Shown(${this.x(p.e, ctx)})`;
    });
    if (!parts.length) return '""';
    return parts.length === 1 ? parts[0] : `(${parts.join(' + ')})`;
  }
}

const own = (r) => (s) => !r.info.imported?.has(s);

/**
 * The Go names of every module-level thing (records, functions, kept values), per module. A name two Thunder files
 * both define gets its module in front (orders_total), so the one Go package can hold them all.
 */
export function goNamespaces(results) {
  const defs = new Map();
  for (const r of results) for (const s of [...r.info.records, ...r.info.funcs, ...r.info.consts, ...(r.info.stores ?? [])].filter(own(r))) (defs.get(s.py) ?? defs.set(s.py, []).get(s.py)).push(r.module);
  const goName = (module, py) => ((defs.get(py)?.length ?? 0) > 1 ? `${module}_${py}` : id(py));
  const out = new Map();
  for (const r of results) {
    const visible = new Map();
    const funcs = new Map();
    const take = (x) => {
      for (const s of [...x.info.records, ...x.info.funcs, ...x.info.consts, ...(x.info.stores ?? [])].filter(own(x))) visible.set(s.py, goName(x.module, s.py));
      for (const f of x.info.funcs.filter(own(x))) funcs.set(f.py, f.params.length);
    };
    // A test file sees every src file's names (as the Python target's `from <module> import *`), later ones winning.
    if (r.kind === 'test') for (const s of results.filter((x) => x.kind !== 'test')) take(s);
    take(r);
    out.set(r.module, { name: (py) => visible.get(py) ?? id(py), has: (py) => visible.has(py), params: (py) => funcs.get(py) ?? null });
  }
  return out;
}
