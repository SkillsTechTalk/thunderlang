// Writing compiled Rust to disk, building it, and running it.
//
// The output is a small Cargo project: main.rs (which runs the program or its tests), one <module>.rs per Thunder
// file, and thunder_runtime.rs (a library crate, standard library only). It builds offline with no dependencies:
// `cargo build` (or plain rustc). Running needs the Rust toolchain; without it, Thunder says plainly what to install.
import { writeFileSync, mkdirSync, readFileSync, existsSync, copyFileSync, rmSync, readdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { toRust, pythonOnlyUses, exportedRustNames, rs } from './target-rust.mjs';
import { diag } from './diagnostics.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
/** The runtime the compiled Rust uses: thunder_runtime.rs, a line-by-line port of the engine's value code. */
export const RUST_RUNTIME = readFileSync(join(HERE, 'rust', 'thunder_runtime.rs'), 'utf8');

/** The Rust module for a Thunder module (always a valid Rust name, never a keyword or the runtime's). */
export const rustModule = (m) => `m_${m}`;

/** TC405 for every Use in a file: Python modules exist only for the Python target. */
export function rustDiagnostics(result) {
  return pythonOnlyUses(result.info).map((u) => diag('TC405', u.line,
    `"${u.module}" is a Python module, and this program is compiled to Rust, which cannot use it.`,
    'Build for Python (target = "python") to use Python modules. Thunder never swaps in a different library.'));
}

/** Compile checked results to Rust: { [rustModule]: text }. Test modules see every src module's names. */
export function compileRust(results) {
  const src = results.filter((r) => r.kind !== 'test');
  const out = {};
  for (const r of results) {
    const imports = r.kind === 'test' ? src.map((s) => ({ module: rustModule(s.module), names: exportedRustNames(s.info) })) : [];
    out[rustModule(r.module)] = toRust(r.program, r.info, { source: r.file, imports });
  }
  return out;
}

/** main.rs: kept values first (in order), then the entry's program, or every module's tests with --tests. */
export function mainRs(results, entryModule) {
  const mods = results.map((r) => rustModule(r.module));
  const entry = rustModule(entryModule ?? results[0]?.module ?? 'main');
  return [
    '// Generated by the Thunder compiler: runs the program, or every Test block with --tests.',
    '#![allow(unused_imports)]',
    ...mods.map((m) => `mod ${m};`),
    '',
    'use thunder_runtime as T;',
    '',
    'fn main() { T::start(run); }',
    '',
    'fn run(tests: bool) {',
    '    if tests {',
    ...mods.map((m) => `        ${m}::init();`),
    `        T::run_tests(vec![${results.map((r) => `(${rs(r.file)}, ${rustModule(r.module)}::thunder_tests())`).join(', ')}]);`,
    '    } else {',
    `        ${entry}::init();`,
    `        T::run(${entry}::main);`,
    '    }',
    '}',
    '',
  ].join('\n');
}

export const CARGO_TOML = `# Generated by the Thunder compiler. Builds offline: no dependencies.
[package]
name = "thunder_program"
version = "0.1.0"
edition = "2021"

[lib]
name = "thunder_runtime"
path = "thunder_runtime.rs"

[[bin]]
name = "program"
path = "main.rs"

[profile.dev]
opt-level = 1
`;

/** Write the Cargo project: Cargo.toml, main.rs, <module>.rs for every result, and thunder_runtime.rs. */
export function writeRust(results, outDir, { entryModule = null } = {}) {
  mkdirSync(outDir, { recursive: true });
  const files = compileRust(results);
  for (const [m, text] of Object.entries(files)) writeFileSync(join(outDir, `${m}.rs`), text);
  writeFileSync(join(outDir, 'main.rs'), mainRs(results, entryModule));
  writeFileSync(join(outDir, 'thunder_runtime.rs'), RUST_RUNTIME);
  writeFileSync(join(outDir, 'Cargo.toml'), CARGO_TOML);
  writeFileSync(join(outDir, '.gitignore'), 'target/\nCargo.lock\n');
  return Object.keys(files);
}

const MISSING = 'Running Rust needs the Rust toolchain (rustc and cargo): install it from https://rustup.rs. "thunder build --target rust" works without it.';

/** Is the Rust toolchain here? { rustc, cargo, version } or { error }. */
export function rustToolchain() {
  const v = spawnSync('rustc', ['--version'], { encoding: 'utf8' });
  if (v.error || v.status !== 0) return { error: MISSING };
  const c = spawnSync('cargo', ['--version'], { encoding: 'utf8' });
  return { rustc: 'rustc', cargo: c.error || c.status !== 0 ? null : 'cargo', version: v.stdout.trim() };
}

/** Build the Cargo project in `outDir` (offline). { ok, binary, output }. */
export function buildRust(outDir) {
  const tc = rustToolchain();
  if (tc.error) return { ok: false, output: tc.error, missing: true };
  if (!tc.cargo) return buildWithRustc(outDir, join(outDir, 'target', 'program'));
  const r = spawnSync(tc.cargo, ['build', '--offline', '--quiet', '--manifest-path', join(outDir, 'Cargo.toml'), '--target-dir', join(outDir, 'target')], { encoding: 'utf8' });
  if (r.status !== 0) return { ok: false, output: `${r.stdout}${r.stderr}`.trim() };
  return { ok: true, binary: join(outDir, 'target', 'debug', process.platform === 'win32' ? 'program.exe' : 'program') };
}

/**
 * Run the built program (or, with tests, its Test blocks) in the folder `cwd`. Returns spawnSync's result, or
 * { status: 2, stderr } when Rust is missing or the generated code does not build.
 */
export function runRust(outDir, { tests = false, cwd = outDir, stdio = 'pipe' } = {}) {
  const b = buildRust(outDir);
  if (!b.ok) return { status: 2, stdout: '', stderr: b.missing ? `${b.output}\n` : `The generated Rust did not build:\n${b.output}\n`, error: b.output };
  return spawnSync(b.binary, tests ? ['--tests'] : [], { cwd, stdio, encoding: 'utf8' });
}

// ── Building with rustc directly, with the runtime compiled once and every program cached by its content ───────
// (What the conformance tests use: hundreds of small programs would each spend seconds in cargo.)

const CACHE = join(tmpdir(), 'thunder-rust-cache');
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 24);
let runtimeLib = null;

/** The runtime compiled once (optimized) as an rlib, cached by its text and the rustc version. */
export function runtimeRlib() {
  if (runtimeLib) return runtimeLib;
  const tc = rustToolchain();
  if (tc.error) return { error: tc.error };
  const dir = join(CACHE, `runtime-${sha(RUST_RUNTIME + tc.version)}`);
  const lib = join(dir, 'libthunder_runtime.rlib');
  if (!existsSync(lib)) {
    mkdirSync(dir, { recursive: true });
    const srcPath = join(dir, 'thunder_runtime.rs');
    writeFileSync(srcPath, RUST_RUNTIME);
    const tmpLib = join(dir, `lib.${process.pid}.rlib`);
    const r = spawnSync(tc.rustc, ['--edition', '2021', '--crate-type', 'rlib', '--crate-name', 'thunder_runtime', '-O', srcPath, '-o', tmpLib], { encoding: 'utf8' });
    if (r.status !== 0) return { error: `The Rust runtime did not build:\n${r.stderr}` };
    copyFileSync(tmpLib, lib);
    rmSync(tmpLib, { force: true });
  }
  runtimeLib = { lib, dir, version: tc.version };
  return runtimeLib;
}

/** Build outDir/main.rs with rustc against the cached runtime; the binary is cached by the sources' content. */
export function buildWithRustc(outDir, binaryOut = null) {
  const rt = runtimeRlib();
  if (rt.error) return { ok: false, output: rt.error, missing: /install it/.test(rt.error) };
  const sources = Object.entries(Object.fromEntries(['main.rs', ...listRs(outDir)].map((f) => [f, readFileSync(join(outDir, f), 'utf8')]))).sort();
  const key = sha(JSON.stringify(sources) + rt.lib);
  const cached = join(CACHE, 'bin', key, process.platform === 'win32' ? 'program.exe' : 'program');
  if (!existsSync(cached)) {
    mkdirSync(dirname(cached), { recursive: true });
    const tmpBin = `${cached}.${process.pid}`;
    const r = spawnSync('rustc', ['--edition', '2021', '-C', 'opt-level=0', '-C', 'debuginfo=0', join(outDir, 'main.rs'), '--extern', `thunder_runtime=${rt.lib}`, '-L', rt.dir, '-o', tmpBin], { encoding: 'utf8' });
    if (r.status !== 0) return { ok: false, output: `${r.stdout}${r.stderr}`.trim() };
    copyFileSync(tmpBin, cached);
    rmSync(tmpBin, { force: true });
  }
  if (binaryOut) { mkdirSync(dirname(binaryOut), { recursive: true }); copyFileSync(cached, binaryOut); return { ok: true, binary: binaryOut }; }
  return { ok: true, binary: cached };
}

/** The generated module files in a folder (not main.rs or the runtime). */
function listRs(dir) {
  let all = [];
  try { all = readdirSync(dir); } catch { /* no folder */ }
  return all.filter((f) => f.endsWith('.rs') && f !== 'main.rs' && f !== 'thunder_runtime.rs');
}

/** Run compiled Rust built with rustc (the fast path the tests use). */
export function runRustFast(outDir, { tests = false, cwd = outDir } = {}) {
  const b = buildWithRustc(outDir);
  if (!b.ok) return { status: 2, stdout: '', stderr: b.missing ? `${b.output}\n` : `The generated Rust did not build:\n${b.output}\n`, error: b.output };
  return spawnSync(b.binary, tests ? ['--tests'] : [], { cwd, encoding: 'utf8' });
}
